// #3 Fixture data outside `fixtures/` and `packs/<id>/upstream/`, or pack test data in git.
//
// Predicate (owned by ../fixtures.mjs, `fixtureLayout(repo).outside`): a tracked file is fixture data when
// a directory in its path is named `fixtures`/`__fixtures__`, its basename matches
// /(^|[-_.])fixtures?([-_.]|$)/i, it is a `*.expected.json`/`*.cases.json` recording, or it is a code-rule
// JSON document; it may live only under `fixtures/`, `packs/<id>/upstream/`, or (rule documents only)
// `packs/<id>/rules/`.
// Exemption `pack-candidates` (in fixtures.mjs): `packs/<id>/candidates/**` holds candidate ports and their
// hand-labelled probe packs, pack data scored but never shipped.
// No tracked file may be pack test data, a path PACK_FIXTURE_PATTERNS (scripts/s3/pack-fixtures.mjs) matches. Derived
// data (upstream's tests and the tool's recorded answers) is regenerated by `npm run fixtures:derive` and CI, so it is
// never committed. Authored data (what the tool's own UPSTREAM.md lists as Rerail's, or upstream/<tool>/authored/) lives
// in S3: a pull request that adds or changes it tracks it with `git add -f` for review, and before merge a maintainer
// runs `npm run fixtures:push`, which uploads it and untracks it (CONTRIBUTING.md, "Pack test data").

import { isPackFixture, listedAuthored, packFixtureKind } from "../../../s3/pack-fixtures.mjs";
import { fixtureLayout } from "../fixtures.mjs";
import { finding, sortFindings } from "../lib.mjs";

export const id = 3;
export const title = "Fixture data outside `fixtures/` and `packs/*/upstream`, or pack test data in git";
export const target = "0";

/** The authored files the tracked tool records (packs/<id>/upstream/<tool>/UPSTREAM.md) list. */
function authoredOf(repo) {
  const records = repo.files.filter((path) => /^packs\/[^/]+\/upstream\/[^/]+\/UPSTREAM\.md$/u.test(path));
  return new Set(records.flatMap((record) => listedAuthored(record, repo.text(record))));
}

export function check(repo) {
  const { outside } = fixtureLayout(repo);
  const authored = authoredOf(repo);
  const findings = [
    ...outside.map((path) => finding(path, "fixture data belongs in fixtures/<family>/ or packs/<id>/upstream/<tool>/")),
    ...repo.files
      .filter((path) => isPackFixture(path))
      .map((path) => packFixtureKind(path, authored) === "derived"
        ? finding(path, "derived pack test data: regenerated by CI (`npm run fixtures:derive`), never committed; git rm --cached it")
        : finding(path, "authored pack test data is in S3; a maintainer runs `npm run fixtures:push` before merge")),
  ];
  return { actual: String(findings.length), findings: sortFindings(findings) };
}
