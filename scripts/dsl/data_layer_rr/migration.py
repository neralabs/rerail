def sha(data):
    return hashlib.sha256(data).hexdigest()


def read_json(path):
    return json.loads(path.read_text())


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n')


def imported_content(content):
    text = content.decode().replace('#include "../data-layer/', '#include "')
    if any(line.lstrip().startswith('//') and 'generated by' in line.lower() for line in text.splitlines()[:3]):
        marker = '// Generated by scripts/generate/packs/data_layer_rr.py; do not edit.\n'
        if not text.startswith(marker):
            text = marker + text
    return text.encode()


def git(root, *args):
    return subprocess.check_output(['git', '-C', str(root), *args], text=True).strip()


def targets(root):
    plan = read_json(fixtures_path('host', 'data-layer-port', 'batches.json'))
    if plan['source_commit'] != PIN:
        raise ValueError('The migration source pin changed')
    result = []
    for batch in plan['batches'][:10]:
        for check in batch['checks']:
            name = 'data-layer-' + check.replace('_', '-') + '.json'
            paths = [root / 'gate/data-layer/packs/data-layer' / directory / name
                     for directory in ['rules', 'candidates/rules']]
            found = [path for path in paths if path.is_file()]
            if len(found) != 1:
                raise ValueError(f'{check}: expected exactly one existing authored policy, found {found}')
            path = found[0]
            result.append(dict(check=check, batch=batch['id'],
                               legacyPath=path.relative_to(root).as_posix(),
                               legacySha256=sha(path.read_bytes())))
    if len(result) != 100 or len({e['check'] for e in result}) != 100:
        raise ValueError('Expected the existing 100 authored checks')
    return result


def compare(expected, actual, *, unordered=False):
    """Compare full DTOs. Only APIs with an explicit unordered contract opt in."""
    if unordered:
        if not isinstance(expected, list) or not isinstance(actual, list):
            raise AssertionError('Unordered comparison requires two lists')
        key = lambda value: json.dumps(value, sort_keys=True, ensure_ascii=False)
        expected, actual = sorted(expected, key=key), sorted(actual, key=key)
    if expected != actual:
        raise AssertionError(f'Full result differs\nexpected: {expected!r}\nactual: {actual!r}')


def compare_inputs(recorded, files, scope):
    """A recorded result is an oracle only for exactly the recorded input."""
    if recorded['files'] != files:
        raise AssertionError('Recorded input differs; make a fresh recording with a fixed PYTHONHASHSEED')
    if recorded['scope'] != scope:
        raise AssertionError('Recorded scope differs; results cannot be compared')


def require_complete(entries):
    """A syntax score or a set score is never a completed migration."""
    required = {'assertions', 'positives', 'failures', 'skipped', 'semanticFallbacks',
                'ruleSha256', 'engineCommit', 'corpusSha256', 'sourceCommit',
                'engineSha256', 'originalInventory', 'reports'}
    for entry in entries:
        evidence = entry.get('evidence', {})
        if entry.get('status') != 'full-contract-passed' or not required <= evidence.keys():
            raise ValueError(f"{entry['check']}: full assertion evidence is missing")
        if evidence['sourceCommit'] != PIN or evidence['assertions'] <= 0 or evidence['positives'] <= 0:
            raise ValueError(f"{entry['check']}: invalid assertion coverage")
        if any(evidence[key] for key in ['failures', 'skipped', 'semanticFallbacks']):
            raise ValueError(f"{entry['check']}: failing, skipped or fallback assertions")
        for key, size in [('ruleSha256', 64), ('engineCommit', 40), ('corpusSha256', 64)]:
            value = evidence[key]
            if not isinstance(value, str) or len(value) != size or any(c not in '0123456789abcdef' for c in value):
                raise ValueError(f"{entry['check']}: invalid {key}")
        if evidence['ruleSha256'] != entry.get('ruleSha256'):
            raise ValueError(f"{entry['check']}: assertion evidence belongs to another rule")

        def artifact(reference):
            path = ROOT / reference['path']
            if not path.is_file() or sha(path.read_bytes()) != reference['sha256']:
                raise ValueError(f'{path}: missing or stale assertion evidence')
            return read_json(path)

        inventory = artifact(evidence['originalInventory'])
        if inventory.get('sourcePin') != PIN:
            raise ValueError(f"{entry['check']}: wrong original assertion inventory")
        files = {name for name, value in inventory['files'].items() if entry['check'] in value['detectors']}
        wanted = {identity for identity in inventory['cases'] if identity.split('::', 1)[0] in files}
        if not wanted:
            raise ValueError(f"{entry['check']}: no original assertion inventory; supply the source-evaluated suite contract before acceptance")
        seen = {'snapshot': set(), 'workspace': set()}
        for reference in evidence['reports']:
            report = artifact(reference)
            mode = report.get('mode')
            if mode not in seen or report.get('oracle') is not False or report.get('exitCode') != 0:
                raise ValueError(f"{entry['check']}: report is not successful native assertion execution")
            if report.get('engineSha256') != evidence['engineSha256'] or report.get('policySha256', {}).get(entry['check']) != entry['ruleSha256']:
                raise ValueError(f"{entry['check']}: report uses another engine or rule")
            if report.get('semanticFallbacks') or report.get('missingResults') or report.get('retainedCaseIds'):
                raise ValueError(f"{entry['check']}: source assertions were omitted or delegated")
            for identity, phases in report['cases'].items():
                if identity not in wanted:
                    continue
                if identity in seen[mode] or {p['phase']: p['outcome'] for p in phases} != dict(setup='passed', call='passed', teardown='passed'):
                    raise ValueError(f'{identity}: duplicate, skipped, failed or incomplete assertion execution')
                seen[mode].add(identity)
        if any(identities != wanted for identities in seen.values()):
            raise ValueError(f"{entry['check']}: original assertions are missing from a native execution API")


def snapshot(source):
    """Read the active sibling once, then refuse a moving snapshot."""
    root = source / 'docs/rule-syntax'
    files = sorted(set((root / 'lib').rglob('*.rr')) | set((root / 'data-layer').glob('*.rr')))
    data = {path.relative_to(root).as_posix(): path.read_bytes() for path in files}
    # Record uncommitted work by bytes, never by a commit that does not contain it.
    head = git(source, 'rev-parse', 'HEAD')
    dirty = git(source, 'status', '--porcelain', '--', 'docs/rule-syntax')
    if any((root / name).read_bytes() != content for name, content in data.items()):
        raise ValueError('The sibling changed during the snapshot; retry')
    return head, dirty.splitlines(), data


def adopt(root, source):
    head, dirty, data = snapshot(source)
    entries = targets(root)
    previous = read_json(root / MANIFEST) if (root / MANIFEST).exists() else {}
    old_hashes = {f['destination']: f['sha256'] for f in previous.get('files', [])}
    writes = {}
    policy_files = {}
    for name, content in data.items():
        if name.startswith('lib/'):
            destination = LIBRARY / name.removeprefix('lib/')
        else:
            destination = DESTINATION / Path(name).name
            text = content.decode()
            if any(line.startswith('.policy ') for line in text.splitlines()):
                policy_files[Path(name).stem.replace('-', '_')] = destination
        writes[destination.as_posix()] = imported_content(content)
    # Check every destination before writing any. Preserve local repairs on later imports.
    for name, content in writes.items():
        path = root / name
        if path.exists() and path.read_bytes() != content:
            current = sha(path.read_bytes())
            if old_hashes.get(name) != current:
                raise ValueError(f'{name}: local changes differ from the imported snapshot')
    files = []
    for name, content in writes.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        original = next(value for key, value in data.items()
                        if (LIBRARY / key.removeprefix('lib/') if key.startswith('lib/') else DESTINATION / Path(key).name).as_posix() == name)
        files.append(dict(destination=name, sha256=sha(content), importedSha256=sha(original)))
    for entry in entries:
        path = policy_files.get(entry['check'])
        entry.update(status='draft' if path else 'absent', rulePath=path.as_posix() if path else None)
        if path:
            entry['ruleSha256'] = sha(writes[path.as_posix()])
    manifest = dict(format='rerail.data-layer-rr-migration/v1', sourceCommit=PIN,
                    syntaxSource=dict(branch=git(source, 'branch', '--show-current'), commit=head,
                                      uncommitted=dirty),
                    legacyBaseline=git(root, 'rev-parse', 'HEAD'),
                    contract='Full original assertions, DTOs, messages, order and multiplicity; no semantic fallbacks',
                    files=files, rules=entries)
    write_json(root / MANIFEST, manifest)
    return manifest


def verify(root):
    manifest = read_json(root / MANIFEST)
    verify_engine_alignment(root, manifest['engineSource'])
    actual = targets(root)
    fields = ['check', 'batch', 'legacyPath', 'legacySha256']
    if [{k: e[k] for k in fields} for e in manifest['rules']] != actual:
        raise ValueError('The legacy target set changed; inspect the migration coverage')
    for item in manifest['files']:
        path = root / item['destination']
        if not path.exists() or sha(path.read_bytes()) != item['sha256']:
            raise ValueError(f'{path}: imported source changed; record and validate the repair')
    return manifest


def verify_engine_alignment(root, source):
    """Reject a detached engine or native edits outside the reviewed modern extensions."""
    if source.get('checkout') != '.':
        raise ValueError('Build and develop the engine in the repository root')
    upstream = source['upstreamCommit']
    try:
        git(root, 'merge-base', '--is-ancestor', upstream, 'HEAD')
    except subprocess.CalledProcessError as error:
        raise ValueError('The engine does not include the adopted Final shape commit') from error
    # Check both the sibling and the fetched remote. A stale local branch must
    # not hide an upstream resolution that is already available in this clone.
    if branch := source.get('upstreamBranch'):
        refs = [('local', branch)]
        if branch.startswith('refs/heads/'):
            refs.append(('remote', 'refs/remotes/origin/' + branch.removeprefix('refs/heads/')))
        checked = set()
        for location, ref in refs:
            try:
                current = git(root, 'rev-parse', '--verify', ref)
            except subprocess.CalledProcessError:
                continue  # A standalone clone still checks the recorded commit.
            if not current or current in checked:
                continue
            try:
                git(root, 'merge-base', '--is-ancestor', current, 'HEAD')
            except subprocess.CalledProcessError as error:
                raise ValueError(f'Merge the newer {location} Final shape before migration acceptance') from error
            checked.add(current)
    reviewed = {item['path']: item['sha256'] for item in source['nativeExtensions']}
    for name in reviewed:
        if not any(name == boundary or boundary.endswith('python_') and name.startswith(boundary)
                   for boundary in ENGINE_EXTENSION_BOUNDARIES):
            raise ValueError(f'{name}: outside the generic extension boundary')
    changed = set(git(root, 'diff', '--name-only', upstream, '--', 'native', 'Cargo.toml', 'Cargo.lock').splitlines())
    changed.update(git(root, 'ls-files', '--others', '--exclude-standard', '--', 'native').splitlines())
    if changed != set(reviewed):
        raise ValueError('Unreviewed engine changes: ' + repr(sorted(changed ^ set(reviewed))))
    for name, digest in reviewed.items():
        path = root / name
        if not path.is_file() or sha(path.read_bytes()) != digest:
            raise ValueError(f'{name}: engine bytes differ from the reviewed extension')


def verify_engine_artifact(root, source, engine):
    """Source ancestry is insufficient: the executed bytes must match its recorded build."""
    artifact = source.get('cliArtifact')
    if not artifact:
        raise ValueError('Native acceptance requires a recorded CLI artifact')
    if artifact.get('upstreamCommit') != source['upstreamCommit']:
        raise ValueError('The binary was not built for the adopted Final shape')
    if git(root, 'diff', '--name-only', 'HEAD', '--', *ENGINE_SOURCE_TREES):
        raise ValueError('Engine sources must be committed before native acceptance')
    for name in ENGINE_SOURCE_TREES:
        if artifact.get('sourceTrees', {}).get(name) != git(root, 'rev-parse', 'HEAD:' + name):
            raise ValueError(f'{name}: binary source tree differs from the active engine')
    git(root, 'merge-base', '--is-ancestor', artifact['engineCommit'], 'HEAD')
    stat = engine.stat()
    key = (str(engine.absolute()), stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns)
    # Hash immutable frozen artifacts once per process, rather than reading a
    # large executable for every fixture. A changed file has a different key.
    if key not in _ARTIFACT_DIGESTS:
        _ARTIFACT_DIGESTS[key] = sha(engine.read_bytes())
    if _ARTIFACT_DIGESTS[key] != artifact['sha256']:
        raise ValueError('The executed binary differs from the recorded CLI artifact')


def verify_source_cohort(root, source):
    """Audit live sibling tips once per process and adopted source identity.

    Another worktree can advance while an immutable acceptance cohort runs.
    Every execution still checks the actual source trees and binary artifact.
    A new process or adoption always performs the live-tip audit again.
    """
    key = (str(root), sha(json.dumps(source, sort_keys=True).encode()))
    if key not in _SOURCE_COHORTS:
        verify_engine_alignment(root, source)
        _SOURCE_COHORTS.add(key)


def register_artifact(root, receipt_path):
    """Register a successful root build only after its provenance and bytes pass."""
    manifest = read_json(root / MANIFEST)
    receipt = read_json(receipt_path)
    source = dict(manifest['engineSource'], cliArtifact=receipt)
    verify_engine_alignment(root, source)
    verify_engine_artifact(root, source, root / receipt['path'])
    manifest['engineSource'] = source
    write_json(root / MANIFEST, manifest)
    return manifest


def repair(root, paths, reason):
    """Bind a reviewed edit to its imported bytes; invalidate any earlier test status."""
    manifest = read_json(root / MANIFEST)
    names = {path.relative_to(root).as_posix() for path in paths}
    for item in manifest['files']:
        if item['destination'] not in names:
            continue
        content = (root / item['destination']).read_bytes()
        old = item['sha256']
        item.setdefault('importedSha256', old)
        item['sha256'] = sha(content)
        if old != item['sha256']:
            item.setdefault('repairs', []).append(dict(before=old, after=item['sha256'], reason=reason))
        names.remove(item['destination'])
    if names:
        raise ValueError(f'Files not in migration inventory: {sorted(names)}')
    for entry in manifest['rules']:
        if entry['rulePath']:
            entry['ruleSha256'] = sha((root / entry['rulePath']).read_bytes())
            entry['status'] = 'draft'
            entry.pop('evidence', None)
    write_json(root / MANIFEST, manifest)


def sync(root, source):
    """Refresh sibling drafts without overwriting local semantic repairs or authored ports."""
    manifest = verify(root)
    head, dirty, data = snapshot(source)
    previous = {item['destination']: item for item in manifest['files']}
    changes = []
    for name, content in data.items():
        destination = LIBRARY / name.removeprefix('lib/') if name.startswith('lib/') else DESTINATION / Path(name).name
        key = destination.as_posix()
        item = previous.get(key)
        remote = sha(content)
        if item and remote == item.get('upstreamSha256', item.get('importedSha256', item['sha256'])):
            continue
        if item and item.get('origin') == 'authored':
            raise ValueError(f'{key}: both branches authored this policy; merge it explicitly')
        if item and item.get('repairs') and any('Resolve generated tables beside' not in edit['reason'] for edit in item['repairs']):
            raise ValueError(f'{key}: both branches changed a repaired policy; merge it explicitly')
        output = imported_content(content)
        changes.append((destination, output, item, remote))
    # Refusals happen before writes.
    for destination, content, item, remote in changes:
        (root / destination).parent.mkdir(parents=True, exist_ok=True)
        (root / destination).write_bytes(content)
        if item is None:
            item = dict(destination=destination.as_posix(), importedSha256=remote)
            manifest['files'].append(item)
        item.update(sha256=sha(content), upstreamSha256=remote, upstreamCommit=head)
    manifest.setdefault('syntaxSnapshots', []).append(manifest['syntaxSource'])
    manifest['syntaxSource'] = dict(branch=git(source, 'branch', '--show-current'), commit=head, uncommitted=dirty)
    for entry in manifest['rules']:
        path = DESTINATION / (entry['check'].replace('_', '-') + '.rr')
        if (root / path).is_file():
            entry.update(rulePath=path.as_posix(), ruleSha256=sha((root / path).read_bytes()), status='draft')
            entry.pop('evidence', None)
    write_json(root / MANIFEST, manifest)
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    commands.add_parser('adopt').add_argument('source', type=Path)
    commands.add_parser('sync').add_argument('source', type=Path)
    commands.add_parser('inventory')
    commands.add_parser('check')
    commands.add_parser('register-artifact').add_argument('receipt', type=Path)
    args = parser.parse_args()
    manifest = (adopt(ROOT, args.source.resolve()) if args.command == 'adopt'
                else sync(ROOT, args.source.resolve()) if args.command == 'sync'
                else register_artifact(ROOT, args.receipt) if args.command == 'register-artifact' else verify(ROOT))
    if args.command == 'check':
        require_complete(manifest['rules'])
    counts = {}
    for entry in manifest['rules']:
        counts[entry['status']] = counts.get(entry['status'], 0) + 1
    print(json.dumps(dict(targets=len(manifest['rules']), status=counts), indent=2))


if __name__ == '__main__':
    main()
