"""Extract literal direct-execution settings from the pinned source without importing it."""
import argparse
import ast
import hashlib
import json
from pathlib import Path

from migration import ROOT, PIN, git


def generate(source):
    name='scripts/lint_impl_direct_execution.py'
    if git(source,'rev-parse','HEAD')!=PIN:raise ValueError('Use the pinned data-layer source')
    text=git(source,'show',PIN+':'+name)
    if (source/name).read_text()!=text+'\n' and (source/name).read_text()!=text:raise ValueError('Source differs from its commit')
    constants={}
    for node in ast.parse(text).body:
        if isinstance(node,ast.Assign) and len(node.targets)==1 and isinstance(node.targets[0],ast.Name):
            try:constants[node.targets[0].id]=ast.literal_eval(node.value)
            except (ValueError,TypeError):pass
        elif isinstance(node,ast.AnnAssign) and isinstance(node.target,ast.Name):
            try:constants[node.target.id]=ast.literal_eval(node.value)
            except (ValueError,TypeError):pass
    lines=['// Generated by scripts/dsl/data_layer_rr/generate_impl_direct_settings.py.',
           '// Source: https://github.com/neralabs/nera-data-layer/blob/'+PIN+'/'+name,
           '// Source SHA256: '+hashlib.sha256((source/name).read_bytes()).hexdigest(),
           '.decl ide_allowed_file(path: symbol)', '.decl ide_directory_pattern(index: number, pattern: symbol)',
           '.decl ide_allowlist_signature(value: symbol)',
           '.decl ide_pattern(priority: number, pattern: symbol, attribute: symbol)']
    for path in sorted(constants['ALLOWED_FILES']):lines.append('ide_allowed_file('+json.dumps(path)+').')
    lines.append('ide_allowlist_signature('+json.dumps(constants['_ALLOWED_FILES_SIGNATURE'])+').')
    for i,pattern in enumerate(constants['ALLOWED_DIR_PATTERNS']):
        lines.append(f'ide_directory_pattern({i},{json.dumps(pattern)}).')
        lines.append('ide_allowed(p) :- ide_path(p), match_all('+json.dumps('(^|/)'+pattern)+',p).')
    for i,pattern in enumerate(constants['DIRECT_EXECUTION_PATTERNS']):
        attribute=pattern.removeprefix('\\.').removesuffix('\\(')
        lines.append(f'ide_pattern({i},{json.dumps(pattern)},{json.dumps(attribute)}).')
        capture='(?<m>'+pattern+')'
        lines.append(f'ide_raw_match(d,p,m,{i}) :- ide_active(d,p,{i},_,_), source(d,sp), match_all({json.dumps(capture)},sp).')
    return '\n'.join(lines)+'\n'


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=Path,required=True);p.add_argument('--out',type=Path,default=ROOT/'docs/rule-syntax/lib/data-layer/impl-direct-settings.rr');a=p.parse_args();a.out.write_text(generate(a.source))


if __name__=='__main__':main()
