#!/usr/bin/env python3
"""Writes gpu/device/src/mldb/builtin/metal/agx_g13_table.rs: the Apple G13 (M1) GPU instruction encodings the exit-code check walks.

    git clone https://github.com/dougallj/applegpu /tmp/applegpu   # at 28dd80468d4a6c94fa4dac34ed488196f5fedc5f
    python3 scripts/dev/metal/agx-g13-table.py /tmp/applegpu > gpu/device/src/mldb/builtin/metal/agx_g13_table.rs

Each row is one of applegpu's instruction descriptors, in its order (the first that matches decodes): the bits that
identify it, its two lengths, and the bit that picks the long one. Only lengths and names are taken: the check
decodes the few operands it reads itself (gpu/device/src/mldb/builtin/metal/agx.rs). Decision 0672.
"""
import os
import subprocess
import sys

root = sys.argv[1]
sys.path.insert(0, root)
import applegpu  # noqa: E402

commit = subprocess.run(['git', '-C', root, 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip()
print('// Generated by scripts/dev/metal/agx-g13-table.py from applegpu (https://github.com/dougallj/applegpu)')
print('// at %s. Do not edit.' % commit)
print('//')
for line in open(os.path.join(root, 'LICENSE')).read().rstrip().split('\n'):
    print(('// ' + line).rstrip())
print()
print('/// An instruction encoding: it is the instruction when `(word & mask) == bits`, `word` the instruction\'s bytes')
print('/// (little-endian) cut to its length, which is `lengths[(word >> length_bit) & 1]` bytes.')
print('pub(crate) struct Encoding {')
print('    pub mask: u128,')
print('    pub bits: u128,')
print('    pub lengths: [u8; 2],')
print('    pub length_bit: u8,')
print('    /// applegpu\'s descriptor class.')
print('    pub name: &\'static str,')
print('}')
print()
print('pub(crate) const ENCODINGS: &[Encoding] = &[')
for d in applegpu.instruction_descriptors:
    print('    Encoding { mask: %#x, bits: %#x, lengths: [%d, %d], length_bit: %d, name: "%s" },'
          % (d.mask, d.bits, d.sizes[0], d.sizes[1], d.length_bit_pos, type(d).__name__))
print('];')
