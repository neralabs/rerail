// Writes native/src/code_rule_dsl/value/ecma/entities.generated.rs: the character entity names typescript-estree
// decodes in JSX attribute strings and text (unescapeStringLiteralText over dist/jsx/xhtml-entities.js, the XHTML 1.0
// set), each a UTF-16 code unit, sorted by name. Run offline, not in CI:
//   node scripts/generate/value/ecma-entities.mjs <node_modules with @typescript-eslint/typescript-estree@8.70.1>
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";

const modules = resolve(process.argv[2]);
const require = createRequire(join(modules, "noop.js"));
const estree = join(modules, "@typescript-eslint/typescript-estree");
const { version } = require(join(estree, "package.json"));
const { xhtmlEntities } = require(join(estree, "dist/jsx/xhtml-entities.js"));

const entries = Object.entries(xhtmlEntities).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
for (const [name, text] of entries) {
  if (!/^[0-9A-Za-z]+$/.test(name) || text.length !== 1) throw new Error(`${name}: ${JSON.stringify(text)}`);
}
const rows = entries.map(([name, text]) => `    ("${name}", 0x${text.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0")}),`);
writeFileSync(
  join(import.meta.dirname, "../../../native/src/code_rule_dsl/value/ecma/entities.generated.rs"),
  `// Generated by scripts/generate/value/ecma-entities.mjs; do not edit.
//! The ${entries.length} JSX character entity names typescript-estree ${version} decodes
//! (\`dist/jsx/xhtml-entities.js\`), each one UTF-16 code unit, sorted by name.

pub(super) const ENTITIES: &[(&str, u16)] = &[
${rows.join("\n")}
];
`,
);
