"""Generate pinned plan-scope constants; runtime decisions remain in native relations."""
import argparse,importlib,json,sys
from dataclasses import asdict
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'scripts/dsl/data_layer_rr'))
from migration import PIN,MANIFEST,DESTINATION,git,read_json,sha,write_json
NAMES=['SKIP_DIRS','SIDE_EFFECT_CALLS','SIDE_EFFECT_RECEIVERS','LEGACY_CALLBACK_METHODS','EAGER_VALUE_ATTRS','EAGER_CALLS','TYPED_EAGER_QUERY_TERMINALS','RAW_DB_CALLS','PLAN_OPENERS','WRITE_PLAN_OPENERS']
def main():
 p=argparse.ArgumentParser();p.add_argument('--source',type=Path,required=True);a=p.parse_args();source=a.source.resolve()
 if git(source,'rev-parse','HEAD')!=PIN:raise ValueError('Wrong source pin')
 sys.path[:0]=[str(source),str(source/'scripts')];m=importlib.import_module('scripts.lint_plan_scope_side_effects')
 configuration='.decl pse_config(key:symbol,value:symbol)\n.decl pse_constant(group:symbol,value:symbol)\n'
 configuration+='// Source: https://github.com/neralabs/nera-data-layer/blob/'+PIN+'/scripts/lint_plan_scope_side_effects.py\n'
 for name in NAMES:
  values=sorted(getattr(m,name));configuration+='pse_config('+json.dumps(name)+','+json.dumps(json.dumps(values))+').\n'
  for v in values:configuration+='pse_constant('+json.dumps(name)+','+json.dumps(v)+').\n'
 configuration+='pse_config("extractor",'+json.dumps(json.dumps(asdict(m.PLAN_SCOPE_SIDE_EFFECTS_EXTRACTOR)))+').\n'
 prefix='// Generated by scripts/generate/packs/data_layer_rr_side_effects.py.\n'
 text=prefix+''' .policy "data-layer:plan-scope-side-effects" revision 3
.description "Exact plan-scope collector spelling, scope and monotonic eager-read state."
.language python
.mode block
.scope include "**/*.py"
#include "core.rr"
#include "data-layer/side-effects-configuration.rr"
#include "data-layer/side-effects-detect.rr"
#include "data-layer/side-effects-api.rr"
#include "data-layer/side-effects-helpers.rr"
#include "data-layer/side-effects-events.rr"
'''.lstrip()
 path=DESTINATION/'plan-scope-side-effects.rr';(ROOT/path).write_text(text)
 config=Path('docs/rule-syntax/lib/data-layer/side-effects-configuration.rr');(ROOT/config).write_text(prefix+configuration)
 repository=DESTINATION/'plan-scope-side-effects-repository.rr'
 (ROOT/repository).write_text(prefix+'''.policy "data-layer:plan-scope-side-effects-repository" revision 1
.description "Public plan-scope scanners and severity selection over native filesystem demands."
.language python
.mode block
.scope dirs "__no_primary__"
#include "core.rr"
#include "data-layer/side-effects-configuration.rr"
#include "data-layer/side-effects-detect.rr"
#include "data-layer/side-effects-files.rr"
''')
 manifest=read_json(ROOT/MANIFEST)
 for item in manifest['rules']:
  if item['check']=='plan_scope_side_effects':item['ruleSha256']=sha(text.encode())
 for item in manifest['files']:
  if item['destination']==str(path):item.update(sha256=sha(text.encode()),origin='authored',sourceCommit=PIN,upstreamPath='scripts/lint_plan_scope_side_effects.py')
 for target in [config,repository,Path('docs/rule-syntax/lib/data-layer/side-effects-events.rr'),Path('docs/rule-syntax/lib/data-layer/side-effects-detect.rr'),Path('docs/rule-syntax/lib/data-layer/side-effects-helpers.rr')]:
  content=(ROOT/target).read_bytes();row=dict(destination=str(target),sha256=sha(content),origin='authored',sourceCommit=PIN,upstreamPath='scripts/lint_plan_scope_side_effects.py')
  old=next((r for r in manifest['files']if r['destination']==str(target)),None)
  if old is None:manifest['files'].append(row)
  else:old.update(row)
 write_json(ROOT/MANIFEST,manifest)
if __name__=='__main__':main()
