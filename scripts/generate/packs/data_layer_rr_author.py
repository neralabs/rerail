"""Generate native .rr rules from the pinned upstream source, offline."""
import argparse
import ast
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / 'scripts/dsl/data_layer_rr'))
from migration import ROOT, PIN, MANIFEST, DESTINATION, targets, read_json, write_json, sha, git


def constants(path):
    result = {}
    for statement in ast.parse(path.read_text()).body:
        if not isinstance(statement, (ast.Assign, ast.AnnAssign)):
            continue
        names = statement.targets if isinstance(statement, ast.Assign) else [statement.target]
        value = statement.value
        if isinstance(value, ast.Call) and isinstance(value.func, ast.Name) and value.func.id in {'frozenset', 'set'} and len(value.args) == 1:
            value = value.args[0]
        for name in names:
            if isinstance(name, ast.Name):
                try:
                    result[name.id] = ast.literal_eval(value)
                except (ValueError, TypeError):
                    pass
    return result


def header(check, target):
    legacy = read_json(ROOT / target['legacyPath'])
    text = '// Generated by scripts/generate/packs/data_layer_rr_author.py; do not edit.\n'
    text += f'.policy {json.dumps(legacy["id"])} revision 1\n'
    text += f'.description "Port of nera-data-layer {check} at {PIN}."\n.language python\n.mode {legacy["mode"]}\n'
    for key in ['include', 'exclude']:
        text += (f'.scope {key} ' + ', '.join(json.dumps(x) for x in legacy['scope'][key])).rstrip() + '\n'
    text += f'// Source: https://github.com/neralabs/nera-data-layer/blob/{PIN}/scripts/lint_{check}.py\n'
    return text + '#include "python/ast.rr"\n'


def removed(source, target):
    values = constants(source / 'scripts/lint_removed_compat_surfaces.py')['_FORBIDDEN_NAMES']
    text = header('removed_compat_surfaces', target)
    text += '.decl removed_name(x: symbol)\n'
    text += ''.join(f'removed_name({json.dumps(x)}).\n' for x in sorted(values))
    text += '.decl removed_root(x: symbol)\n'
    text += ''.join(f'removed_root({json.dumps(x)}).\n' for x in constants(source / 'scripts/lint_removed_compat_surfaces.py')['_DEFAULT_ROOTS'])
    return text + '''
.decl removed_symbol(n: node, x: symbol)
removed_symbol(n, @nfkc(raw)) :- ast_name(n, raw), removed_name(@nfkc(raw)).
removed_symbol(n, @nfkc(raw)) :- kind(n, "attribute"), field(n, "attribute", a), text(a, raw), removed_name(@nfkc(raw)).
removed_symbol(n, @nfkc(raw)) :- def_name(n, raw), removed_name(@nfkc(raw)).
.decl removed_hidden(d: number)
removed_hidden(d) :- path_part(d, "tests").
removed_hidden(d) :- path_part(d, "test").
removed_hidden(d) :- path_part(d, ".git").
removed_hidden(d) :- path_part(d, ".venv").
removed_hidden(d) :- path_part(d, "venv").
removed_hidden(d) :- path_part(d, "__pycache__").
removed_hidden(d) :- path_part(d, "tmp").
.decl removed_selected(d: number)
removed_selected(d) :- doc(d, _, _), option("entryPoint", "scan_file").
removed_selected(d) :- doc(d, p, _), !option("entryPoint", _), file_name(d, f), suffix(".py", f),
    removed_root(root), prefix(cat(root, "/"), p), !removed_hidden(d),
    source(d, sp), text(sp, t), removed_name(name), contains(name, t).
.decl removed_hit(d: number, l: number, name: symbol, ordinal: number)
removed_hit(d, l, x, i) :- removed_symbol(n, x), docof(n, d), removed_selected(d), line(n, l),
    visit_index(n, i), !syntax_error(d, _, _).
// scan_file deduplicates by line and name, retaining the first semantic visit.
.decl removed_first(d: number, l: number, name: symbol, ordinal: number)
removed_first(d, l, x, first) :- removed_hit(d, l, x, _), first = min i : { removed_hit(d, l, x, i) }.
.violation RemovedAPI(at: span, name: symbol, ordinal: number) code "RCS001"
    "removed compatibility surface '{name}' must not be reintroduced"
RemovedAPI(@place(p, l), x, i) :- removed_first(d, l, x, i), doc(d, p, _), option("entryPoint", "scan_file").
// The configured reporter preserves each collector event, including repeated names on one line.
.violation Removed(at: node, name: symbol, ordinal: number) code "RCS001"
    "removed compatibility surface '{name}' must not be reintroduced"
Removed(n, x, i) :- removed_symbol(n, x), docof(n, d), removed_selected(d), visit_index(n, i),
    !option("entryPoint", _), !syntax_error(d, _, _).
'''


def lifecycle(source, target):
    values = constants(source / 'scripts/lint_versioned_lifecycle_legacy_surfaces.py')['BANNED_METHODS']
    text = header('versioned_lifecycle_legacy_surfaces', target)
    text += '.decl lifecycle_method(x: symbol)\n'
    text += ''.join(f'lifecycle_method({json.dumps(x)}).\n' for x in sorted(values))
    return text + '''
.decl lifecycle_class(c: node, x: symbol)
lifecycle_class(c, x) :- kind(c, "class_definition"), def_name(c, x),
    (suffix("VersionedWriteTransaction", x) ; suffix("LazyVersionedWriteTransactionSparse", x)).
.violation Lifecycle(at: node, cls: symbol, method: symbol) code "VLL001"
    "{cls}.{method} shadows the base LazyVersionedWriteTransaction @legacy lifecycle surface; move backend behavior to *_lazy methods, helpers, or ServerPlan lowering."
Lifecycle(f, cls, name) :- lifecycle_class(c, cls), field(c, "body", b), body_stmt(b, st, _), defstmt(f, st),
    kind(f, "function_definition"), def_name(f, name), lifecycle_method(name), docof(c, d), !syntax_error(d, _, _).
'''


def permission_error(source, target):
    suppression = constants(source / 'scripts/lint_permission_error.py')['SUPPRESSION_COMMENT']
    text = header('permission_error', target)
    text += '''
// The collector is ordered: an import encountered after a raise does not excuse it.
.decl permission_import(i: node)
permission_import(i) :- from_module_raw(i, raw), contains("l1100_exceptions", @nfkc(raw)),
    field(i, "name", n), kind(n, "dotted_name"), text(n, t), @nfkc(t) = "PermissionError".
permission_import(i) :- from_module_raw(i, raw), contains("l1100_exceptions", @nfkc(raw)),
    field(i, "name", n), kind(n, "aliased_import"), field(n, "name", nm), text(nm, t), @nfkc(t) = "PermissionError",
    field(n, "alias", al), text(al, a), @nfkc(a) = "PermissionError".
.decl permission_exc(r: node, e: node)
permission_exc(r, e) :- kind(r, "raise_statement"), child(r, v, 0), !field(r, "cause", v), unparen(v, e).
.decl permission_raise(r: node)
permission_raise(r) :- permission_exc(r, e), ast_name(e, "PermissionError").
permission_raise(r) :- permission_exc(r, e), kind(e, "call"), field(e, "function", f), unparen(f, n), ast_name(n, "PermissionError").
.decl permission_authorized(r: node)
permission_authorized(r) :- permission_raise(r), docof(r, d), permission_import(i), docof(i, d), earlier(i, r).
.decl permission_trigger(d: number)
permission_trigger(d) :- split_line(d, _, t), contains("PermissionError", t).
.decl permission_suppressed(d: number, l: number)
'''
    text += f'permission_suppressed(d, l) :- split_line(d, l, t), contains({json.dumps(suppression)}, t).\n'
    text += '''
.violation BuiltinPermission(at: node) code "builtin_permission_error"
    "Raises built-in PermissionError instead of l1100_exceptions.PermissionError"
BuiltinPermission(r) :- permission_raise(r), docof(r, d), permission_trigger(d), line(r, l),
    !permission_authorized(r), !permission_suppressed(d, l), !permission_suppressed(d, l - 1), !syntax_error(d, _, _).
'''
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    args = parser.parse_args()
    source = args.source.resolve()
    if git(source, 'rev-parse', 'HEAD') != PIN:
        raise ValueError('Wrong upstream source pin')
    manifest = read_json(ROOT / MANIFEST)
    by_check = {entry['check']: entry for entry in manifest['rules']}
    from data_layer_rr_text import no_source_inspection, serverplan_name_inference, hasattr_async, no_blanket_grammar_bypass, admin_async_purity, async_executor, rust_sql_grammar_boundary
    from data_layer_rr_dynamic import dynamic_module_loading
    from data_layer_rr_ast import classvar_check, forwardref
    from data_layer_rr_types import type_safety_patterns
    from data_layer_rr_facade_purity import data_layer_facade_purity
    from data_layer_rr_signatures import sync_async_signatures
    from data_layer_rr_coupling import backend_coupling
    from data_layer_rr_connection_caches import connection_caches
    from data_layer_rr_api_imports import no_api_root_imports
    from data_layer_rr_error_handling import error_handling
    from data_layer_rr_backend_types import backend_type_strings
    from data_layer_rr_grammar_surface import serverplan_grammar_surface
    from data_layer_rr_unresolved import unresolved_forward_refs
    from data_layer_rr_aliases import data_layer_compat_aliases
    generators = [('removed_compat_surfaces', removed), ('versioned_lifecycle_legacy_surfaces', lifecycle),
                  ('permission_error', permission_error),
                  ('no_source_inspection', lambda s, t: no_source_inspection(s, t, header)),
                  ('hasattr_async', lambda s, t: hasattr_async(s, t, header)),
                  ('no_blanket_grammar_bypass', lambda s, t: no_blanket_grammar_bypass(s, t, header)),
                  ('admin_async_purity', lambda s, t: admin_async_purity(s, t, header)),
                  ('async_executor', lambda s, t: async_executor(s, t, header)),
                  ('rust_sql_grammar_boundary', lambda s, t: rust_sql_grammar_boundary(s, t, header)),
                  ('dynamic_module_loading', lambda s, t: dynamic_module_loading(s, t, header)),
                  ('classvar_check', lambda s, t: classvar_check(s, t, header)),
                  ('type_safety_patterns', lambda s, t: type_safety_patterns(s, t, header)),
                  ('forwardref', lambda s, t: forwardref(s, t, header)),
                  ('data_layer_compat_aliases', lambda s, t: data_layer_compat_aliases(s, t, header)),
                  ('data_layer_facade_purity', lambda s, t: data_layer_facade_purity(s, t, header)),
                  ('sync_async_signatures', lambda s, t: sync_async_signatures(s, t, header)),
                  ('backend_coupling', lambda s, t: backend_coupling(s, t, header)),
                  ('connection_caches', lambda s, t: connection_caches(s, t, header)),
                  ('no_api_root_imports', lambda s, t: no_api_root_imports(s, t, header)),
                  ('error_handling', lambda s, t: error_handling(s, t, header)),
                  ('backend_type_strings', lambda s, t: backend_type_strings(s, t, header)),
                  ('serverplan_grammar_surface', lambda s, t: serverplan_grammar_surface(s, t, header)),
                  ('unresolved_forward_refs', lambda s, t: unresolved_forward_refs(s, t, header)),
                  ('serverplan_name_inference', lambda s, t: serverplan_name_inference(s, t, header))]
    for check, generate in generators:
        entry = by_check[check]
        path = DESTINATION / (check.replace('_', '-') + '.rr')
        text = generate(source, entry)
        (ROOT / path).write_text(text)
        digest = sha(text.encode())
        previous = next((file for file in manifest['files'] if file['destination'] == path.as_posix()), {})
        item = dict(previous, destination=path.as_posix(), sha256=digest, origin='authored',
                    upstreamPath=f'scripts/lint_{check}.py', sourceCommit=PIN)
        manifest['files'] = [file for file in manifest['files'] if file['destination'] != path.as_posix()] + [item]
        if entry.get('ruleSha256') != digest:
            entry.update(status='draft')
            entry.pop('evidence', None)
        entry.update(rulePath=path.as_posix(), ruleSha256=digest)
    write_json(ROOT / MANIFEST, manifest)


if __name__ == '__main__':
    main()
