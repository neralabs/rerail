"""Generate pinned constants for the supplied-tree structural connection helper."""
import argparse
import importlib
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'scripts/dsl/data_layer_rr'))
from migration import PIN,MANIFEST,DESTINATION,git,read_json,sha,write_json


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--source',type=Path,required=True);args=parser.parse_args()
    source=args.source.resolve()
    if git(source,'rev-parse','HEAD')!=PIN:raise ValueError('Wrong source pin')
    sys.path[:0]=[str(source),str(source/'scripts')]
    owner=importlib.import_module('scripts.lint_connection_structural_boundaries')
    text='''// Generated by scripts/generate/packs/data_layer_rr_structural_helper.py.
.policy "data-layer:connection-structural-boundaries-supplied" revision 1
.description "Connection structural helper over the caller's supplied syntax tree."
.language python
.mode block
.scope include "**/*.py"
#include "core.rr"
.decl sch_config(key:symbol,value:symbol)
'''
    text+='// Source: https://github.com/neralabs/nera-data-layer/blob/'+PIN+'/scripts/lint_connection_structural_boundaries.py#L254\n'
    for name in ['CONNECTION_FILE_MAX_LINES','CONNECTION_RESIDUAL_SYMBOLS','ALLOWED_DATABASE_CORE_BASES']:
        value=getattr(owner,name)
        if isinstance(value,frozenset):value=sorted(value)
        text+='sch_config('+json.dumps(name)+','+json.dumps(json.dumps(value))+').\n'
    text+='#include "data-layer/structural-connection-helper.rr"\n'
    path=DESTINATION/'connection-structural-boundaries-supplied.rr';(ROOT/path).write_text(text)
    manifest=read_json(ROOT/MANIFEST)
    item=dict(destination=path.as_posix(),sha256=sha(text.encode()),origin='authored',sourceCommit=PIN,upstreamPath='scripts/lint_connection_structural_boundaries.py')
    index=next((i for i,r in enumerate(manifest['files'])if r['destination']==path.as_posix()),None)
    if index is None:manifest['files'].append(item)
    else:manifest['files'][index]=dict(manifest['files'][index],**item)
    write_json(ROOT/MANIFEST,manifest)


if __name__=='__main__':main()
