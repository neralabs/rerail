"""Generate the pinned plan-scope production-root pattern for a native discovery contract."""
import argparse,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'scripts/dsl/data_layer_rr'))
from migration import PIN,MANIFEST,DESTINATION,git,read_json,sha,write_json
from data_layer_rr_text import character_class

def main():
    p=argparse.ArgumentParser();p.add_argument('--source',type=Path,required=True);a=p.parse_args()
    if git(a.source.resolve(),'rev-parse','HEAD')!=PIN:raise ValueError('Wrong source pin')
    layer=r'\Al'+character_class(str.isdecimal)+r'{4}_.+(?s:.*)'
    text='''// Generated by scripts/generate/packs/data_layer_rr_directory_discovery.py.
.policy "data-layer:plan-scope-directory-discovery" revision 1
.description "The plan-scope plugin's production FileScopeSpec discovery."
.language python
.mode block
.scope dirs "__no_primary__"
#include "core.rr"
#include "data-layer/plugin-discovery.rr"
// Source: https://github.com/neralabs/nera-data-layer/blob/'''+PIN+'''/scripts/lint_plan_scope_side_effects.py#L459
pfd_root(p) :- dir_entry(".",p,1),(p="impl";p="data_layer";p="_internal").
pfd_root(p) :- dir_entry(".",p,1),match('''+json.dumps(layer)+''',p).
.violation DirectoryFile(at:span,path:symbol,path_order:symbol) code "PSE_DISCOVERY" "{path}"
DirectoryFile(@place("",0),p,@replace_all(p,"/","\\u0000")) :- pfd_file(p).
'''
    path=DESTINATION/'plan-scope-directory-discovery.rr';(ROOT/path).write_text(text)
    m=read_json(ROOT/MANIFEST);row=dict(destination=str(path),sha256=sha(text.encode()),origin='authored',sourceCommit=PIN,upstreamPath='scripts/lint_plan_scope_side_effects.py')
    old=next((r for r in m['files']if r['destination']==str(path)),None)
    if old is None:m['files'].append(row)
    else:old.update(row)
    write_json(ROOT/MANIFEST,m)

if __name__=='__main__':main()
