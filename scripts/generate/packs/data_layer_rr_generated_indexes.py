"""Author native generated-index configuration from pinned declarative source values."""
import argparse
from dataclasses import asdict
import importlib
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'scripts/dsl/data_layer_rr'))
from migration import PIN,git


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--source',type=Path,required=True)
    args=parser.parse_args();source=args.source.absolute()
    if git(source,'rev-parse','HEAD')!=PIN:raise ValueError('Wrong source pin')
    sys.path[:0]=[str(source),str(source/'scripts')]
    module=importlib.import_module('scripts.lint_generated_index_sources')
    plugin=module.generated_index_sources_plugin(Path('.'))
    config=dict(plugin=json.dumps(dict(name=plugin.name,enforcement=plugin.enforcement,description=plugin.description)),
        extractor=json.dumps(asdict(module.GENERATED_INDEX_SOURCES_EXTRACTOR)),
        description=module.__doc__,check_help='Exit non-zero on violations',
        runtime_error='generated_index_sources uses AstEventCollector facts')
    lines=['// Generated by scripts/generate/packs/data_layer_rr_generated_indexes.py.',
        '// Pinned source: '+PIN,'.decl gis_config(key: symbol, value: symbol)',
        '.decl gis_generator_file(path: symbol)']
    for key,value in config.items():lines.append('gis_config('+json.dumps(key)+','+json.dumps(value)+').')
    for path in module.GENERATOR_FILES:lines.append('gis_generator_file('+json.dumps(path.as_posix())+').')
    (ROOT/'gate/data-layer/packs/data-layer/candidates/rr/generated-index-sources.tables.rr').write_text('\n'.join(lines)+'\n')


if __name__=='__main__':main()
