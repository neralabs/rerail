"""Generate literal survey-name tables from the pinned linter source."""
import argparse
import ast
import json
from pathlib import Path
import subprocess

PIN = '2b1504adc4291daaf080b2e932962b134da1a69a'


def generate(source):
    path = source/'scripts/lint_lib/symbol_graph.py'
    original = subprocess.check_output(['git','-C',str(source),'show',PIN+':scripts/lint_lib/symbol_graph.py'])
    if path.read_bytes() != original:
        raise ValueError('The survey source differs from the pinned bytes')
    tree=ast.parse(original)
    text = '// Generated by scripts/generate/packs/data_layer_rr_survey_constants.py.\n'
    text += '// Literal tables from nera-data-layer '+PIN+' scripts/lint_lib/symbol_graph.py.\n'
    graph=next(n for n in tree.body if isinstance(n,ast.ClassDef) and n.name=='SymbolGraph')
    for block,name,relation in [(tree,'_BUILTIN_NAMES','sgb_builtin'),(tree,'EXECUTION_NAMES','sgb_execution_literal'),
                                (tree,'PUBLIC_METHOD_SKIP','sgb_public_skip'),(graph,'_CLASS_DUNDERS_TO_WALK','sgb_class_dunder')]:
        node=next(n for n in block.body if isinstance(n,ast.AnnAssign) and isinstance(n.target,ast.Name) and n.target.id==name)
        assert isinstance(node.value,ast.Call) and isinstance(node.value.func,ast.Name) and node.value.func.id=='frozenset'
        values=ast.literal_eval(node.value.args[0])
        text+='\n.decl '+relation+'(name: symbol)\n'
        text+=''.join(relation+'('+json.dumps(v)+').\n' for v in sorted(values))
    return text


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,required=True)
    parser.add_argument('--out',type=Path,required=True)
    args=parser.parse_args()
    args.out.write_text(generate(args.source))
