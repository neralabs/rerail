import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { generateSQLiteDrizzleJson, generateSQLiteMigration } from "drizzle-kit/api";
import {
  events,
  presentationPreferences,
  repositoryAudits,
  auditResultPages,
  audits,
  auditRequests,
  policySessionOwners,
  auditSettings,
  repositories,
  checkouts,
  setupReviews,
  ruleAttachments,
  ruleSettings,
  schemaMigrations,
  libraryRules,
  ruleCatalogIdentities,
  rules,
  sessions,
  workLinks,
  AUDIT_HISTORY_TRIGGER_STATEMENTS,
  auditRuleSetRules,
  auditRuleSets,
  auditRuleSetUses,
  auditViolations,
  ruleViolationRollup,
} from "../../../src/engine/index.js";

export const SCHEMA_SQL_PATH = resolve(fileURLToPath(import.meta.url), "..", "..", "..", "..", "src", "engine", "storage", "schema-sql.generated.ts");

/**
 * Render the DDL for the Drizzle tables in `src/engine/storage/schema.ts`, then the triggers that keep the derived
 * audit history in step (`audit-history.ts`), as an idempotent statement list applied verbatim on every open.
 */
export async function renderRerailSchemaStatements(): Promise<string[]> {
  const empty = await generateSQLiteDrizzleJson({});
  // Explicit order: module namespace key order differs between loaders.
  const current = await generateSQLiteDrizzleJson({
  sessions,
  events,
  rules,
  workLinks,
  audits: audits,
  auditResultPages: auditResultPages,
  auditViolations,
  ruleViolationRollup,
  auditRuleSets,
  auditRuleSetRules,
  auditRuleSetUses,
  presentationPreferences,
  auditSettings: auditSettings,
  repositoryAudits: repositoryAudits,
  auditRequests: auditRequests,
  policySessionOwners,
  ruleCatalogIdentities,
  repositories,
  checkouts,
  setupReviews,
  ruleAttachments,
  ruleSettings,
  libraryRules,
  schemaMigrations,
  });
  const statements = await generateSQLiteMigration(empty, current);
  return [
    ...statements.map(statement =>
      statement
        .trim()
        .replace(/^CREATE TABLE `/u, "CREATE TABLE IF NOT EXISTS `")
        .replace(/^CREATE (UNIQUE )?INDEX `/u, "CREATE $1INDEX IF NOT EXISTS `")
        .replace(/;$/u, ""),
    ),
    ...AUDIT_HISTORY_TRIGGER_STATEMENTS,
  ];
}

export async function renderRerailSchemaModule(): Promise<string> {
  const statements = await renderRerailSchemaStatements();
  return [
    "// Generated by scripts/generate/schema/schema-sql.ts; do not edit. Source: src/engine/storage/schema.ts (`npm run generate:schema`).",
    "",
    "/** DDL statements applied, in order, when a Rerail database is opened. */",
    "export const RERAIL_SCHEMA_STATEMENTS: readonly string[] = [",
    ...statements.map(statement => `  ${JSON.stringify(statement)},`),
    "];",
    "",
    "export const RERAIL_SCHEMA_SQL = `${RERAIL_SCHEMA_STATEMENTS.join(\";\\n\\n\")};\\n`;",
    "",
  ].join("\n");
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(SCHEMA_SQL_PATH, await renderRerailSchemaModule());
  process.stdout.write(`Wrote ${SCHEMA_SQL_PATH}\n`);
}
