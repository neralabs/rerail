// Writes src/engine/catalog/lint-config/generated/ruff-rules.generated.ts: each Ruff rule's status (those of stable,
// preview, deprecated and removed the pinned Ruff has, the status type naming only those) and category, and Ruff's
// default rule selection with and without preview, as the pinned Ruff reports them
// (`ruff rule --all --output-format json`, and `ruff check --isolated --show-settings` in an empty folder, with and
// without `--preview`). Set-up reads a Ruff config as data; what Ruff runs for a code no selector names comes from this
// table. Run offline, not in CI:
//   node scripts/generate/lint-config/ruff-rules.mjs <ruff 0.16.9>
// (`uvx ruff@0.16.9`'s binary, or any ruff 0.16.9). A different Ruff version is refused; bump PIN and regenerate.
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const PIN = "0.16.9";
const STATUS = { Stable: "stable", Preview: "preview", Deprecated: "deprecated", Removed: "removed" };

const ruff = process.argv[2];
if (ruff === undefined) throw new Error("usage: node scripts/generate/lint-config/ruff-rules.mjs <ruff binary>");
const version = execFileSync(ruff, ["version"], { encoding: "utf8" }).trim();
if (!version.startsWith(`ruff ${PIN} `)) throw new Error(`${version} found; the table is pinned to ruff ${PIN}`);

const rules = JSON.parse(execFileSync(ruff, ["rule", "--all", "--output-format", "json"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));

/** The codes Ruff enables with every option at its default, in an empty folder, with `flags`. */
function defaultCodes(flags) {
  const folder = mkdtempSync(join(tmpdir(), "rerail-ruff-defaults-"));
  try {
    writeFileSync(join(folder, "a.py"), "");
    const settings = execFileSync(ruff, ["check", "--isolated", ...flags, "--show-settings", "a.py"], { cwd: folder, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
    const enabled = /^linter\.rules\.enabled = \[\n([\s\S]*?)^\]/mu.exec(settings);
    if (enabled === null) throw new Error("ruff --show-settings printed no linter.rules.enabled");
    return new Set([...enabled[1].matchAll(/\(([A-Z]+[0-9]+)\),$/gmu)].map(match => match[1]));
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
}

const stable = defaultCodes([]);
const preview = defaultCodes(["--preview"]);
// A rule without a code (selected by name, in preview only) has no noqa code a port could name.
const rows = rules.filter(rule => rule.code !== null).map(rule => {
  const status = STATUS[Object.keys(rule.status)[0]];
  if (status === undefined) throw new Error(`${rule.code}: unknown status ${JSON.stringify(rule.status)}`);
  return [rule.code, status, rule.category, stable.has(rule.code), preview.has(rule.code)];
}).sort(([left], [right]) => left.localeCompare(right));
for (const code of [...stable, ...preview]) if (!rows.some(([known]) => known === code)) throw new Error(`${code} is enabled by default but not listed`);
// The status type names only the statuses the pin has, so that one a bump brings fails type-checking until handled.
const statuses = Object.values(STATUS).filter(status => rows.some(row => row[1] === status));

const text = `// Generated by scripts/generate/lint-config/ruff-rules.mjs; do not edit.
// From ruff ${PIN}: \`ruff rule --all --output-format json\` and \`ruff check --isolated [--preview] --show-settings\`.

/** A Ruff rule: its status, its category, and whether Ruff's default selection enables it without and with preview. */
export interface RuffRuleInfo {
  readonly status: ${statuses.map(status => JSON.stringify(status)).join(" | ")};
  readonly category: string;
  readonly byDefault: boolean;
  readonly byPreviewDefault: boolean;
}

const ROWS: readonly (readonly [string, RuffRuleInfo["status"], string, boolean, boolean])[] = [
${rows.map(row => `  ${JSON.stringify(row)},`).join("\n")}
];

/** Every rule of Ruff ${PIN} by its code. */
export const RUFF_RULES: ReadonlyMap<string, RuffRuleInfo> = new Map(ROWS.map(([code, status, category, byDefault, byPreviewDefault]) => [code, { status, category, byDefault, byPreviewDefault }]));
`;
writeFileSync(join(import.meta.dirname, "../../../src/engine/catalog/lint-config/generated/ruff-rules.generated.ts"), text);
