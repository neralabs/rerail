// Writes src/engine/catalog/lint-config/generated/oxlint-rules.generated.ts: oxlint's built-in rules by plugin and category, and
// which are type-aware, as `oxlint --rules --format=json` lists them. Set-up reads an `.oxlintrc.json` as data; what a
// category, or oxlint's default, turns on comes from this table. Run offline, not in CI:
//   npm install --prefix <tools> oxlint@1.88.0
//   node scripts/generate/lint-config/oxlint-rules.mjs <tools>/node_modules/.bin/oxlint
// A different oxlint version is refused; bump PIN and regenerate to move the table.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const PIN = "1.88.0";
/** The plugins oxlint runs with no `plugins` key (with `eslint`, always on), whose correctness rules are `default`. */
const DEFAULT_PLUGINS = new Set(["eslint", "unicorn", "typescript", "oxc"]);

const oxlint = process.argv[2];
if (oxlint === undefined) throw new Error("usage: node scripts/generate/lint-config/oxlint-rules.mjs <oxlint binary>");
const version = execFileSync(oxlint, ["--version"], { encoding: "utf8" }).trim();
if (version !== `Version: ${PIN}`) throw new Error(`${version} found; the table is pinned to oxlint ${PIN}`);
const rules = JSON.parse(execFileSync(oxlint, ["--rules", "--format=json"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));

// The table derives oxlint's default (the correctness rules of the default plugins) rather than storing it; refuse a
// release where that no longer holds.
for (const rule of rules) {
  const derived = rule.category === "correctness" && DEFAULT_PLUGINS.has(rule.scope);
  if (derived !== rule.default) throw new Error(`${rule.scope}/${rule.value}: default is ${rule.default}, not the correctness rule of a default plugin`);
}

const byPlugin = {};
for (const rule of rules) ((byPlugin[rule.scope] ??= {})[rule.category] ??= []).push(rule.value);
const sorted = Object.fromEntries(Object.entries(byPlugin).sort(([left], [right]) => left.localeCompare(right))
  .map(([plugin, categories]) => [plugin, Object.fromEntries(Object.entries(categories).sort(([left], [right]) => left.localeCompare(right)).map(([category, names]) => [category, names.sort()]))]));
const typeAware = rules.filter(rule => rule.type_aware).map(rule => `${rule.scope}/${rule.value}`).sort();

const text = `// Generated by scripts/generate/lint-config/oxlint-rules.mjs; do not edit.
// From \`oxlint --rules --format=json\` of oxlint ${PIN}.

/** Per oxlint plugin (its internal name), per category, the names of its built-in rules. */
export const OXLINT_RULES: Readonly<Record<string, Readonly<Record<string, readonly string[]>>>> = ${JSON.stringify(sorted, undefined, 1)};

/** The rules (\`<plugin>/<name>\`) oxlint runs only with type information (\`--type-aware\`). */
export const OXLINT_TYPE_AWARE: ReadonlySet<string> = new Set(${JSON.stringify(typeAware, undefined, 1)});

/** The upstream version the table comes from. */
export const UPSTREAM_VERSIONS: Readonly<Record<string, string>> = { oxlint: ${JSON.stringify(PIN)} };
`;
writeFileSync(join(import.meta.dirname, "../../../src/engine/catalog/lint-config/generated/oxlint-rules.generated.ts"), text);
