// Writes src/terminal-brand.generated.ts: the terminal colour of Nera's canonical `--brand` token, read from a
// nera-landing checkout's web/src/index.css. Run offline, not in CI:
//   node scripts/generate/ui/terminal-brand.mjs <nera-landing checkout>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const landing = process.argv[2];
if (landing === undefined) throw new Error("usage: node scripts/generate/ui/terminal-brand.mjs <nera-landing checkout>");
const source = readFileSync(join(landing, "web/src/index.css"), "utf8");
const root = source.replace(/\/\*[\s\S]*?(?:\*\/|$)/gu, "").match(/^[^\S\r\n\u2028\u2029]*:root\s*\{([^}]+)\}/mu)?.[1];
const brand = root?.match(/^[^\S\r\n\u2028\u2029]*--brand:\s*#([\da-f]{6})\s*;/imu)?.[1];
if (brand === undefined) throw new Error("Canonical :root --brand must be a six-digit hex color");
const rgb = [0, 2, 4].map(offset => Number.parseInt(brand.slice(offset, offset + 2), 16));
writeFileSync(
  join(import.meta.dirname, "../../../src/terminal-brand.generated.ts"),
  "// Generated by scripts/generate/ui/terminal-brand.mjs; do not edit. Source: nera-landing web/src/index.css --brand.\n"
    + `export const RERAIL_BRAND_FOREGROUND = ${JSON.stringify(`\u001b[38;2;${rgb.join(";")}m`)};\n`,
);
