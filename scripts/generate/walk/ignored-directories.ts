import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { IGNORED_DIRECTORIES } from "../../../src/engine/index.js";

/**
 * The engine's copy of the host's `IGNORED_DIRECTORIES` (src/engine/code-rule/ignored-directories.ts): the folders no
 * repository walk enters. The engine's corpus listing, its `file` facts, its artifact inputs and its server graphs
 * `include!` the generated Rust file, so a `.rerail` run reads the files a host's walk reads.
 */

const ROOT = resolve(fileURLToPath(import.meta.url), "..", "..", "..", "..");
export const IGNORED_DIRECTORIES_RUST_PATH = resolve(ROOT, "native", "src", "code_rule_dsl", "ignored_directories.generated.rs");

export function renderIgnoredDirectoriesRust(names: Iterable<string> = IGNORED_DIRECTORIES): string {
  const list = [...names];
  return [
    "// Generated by scripts/generate/walk/ignored-directories.ts; do not edit. Source: src/engine/code-rule/ignored-directories.ts (`npm run generate:ignored-directories`).",
    "",
    "/// The folders no repository walk enters, by name: the host's `IGNORED_DIRECTORIES`.",
    `const IGNORED_DIRECTORIES: [&str; ${list.length}] = [`,
    ...list.map(name => `    ${JSON.stringify(name)},`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(IGNORED_DIRECTORIES_RUST_PATH, renderIgnoredDirectoriesRust());
}
