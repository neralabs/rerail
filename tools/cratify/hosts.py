"""The test hosts of the crate split: which crate compiles each test module that reads a crate above its own.

usage: hosts.py <tree.tsv> <tests.tsv> [--extract]

A test module is compiled by the least crate that sees everything it reads (its own crate's included): a test of
the facts that reads W's test support is W's, one that compiles a whole rule set is the engine's. Writes
test-hosts.tsv (module -> crate, read after crate-map.tsv, so it overrides it).

An inline test module in a production file (`#[cfg(test)] mod tests { ... }`) cannot be mounted by another crate,
so such a module is listed for extraction: --extract writes its body to the file its declaration would name
(`a/b.rs`'s `tests` to `a/b/tests.rs`) and leaves `mod tests;` in its place. Byte-exact, by the module's span in
tree.tsv; run `cratify tree` again after it.
"""
import collections, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from crate_map import ALLOW, DAG, ROOT

DSL = 'crate::code_rule_dsl'


def sees(c):
    return ALLOW.get(c, set()) | {c}


def host(crates):
    """The least crate that sees all of `crates`: the engine when two minimal ones are apart."""
    cands = [c for c in DAG if crates <= sees(c)]
    least = [c for c in cands if not any(o != c and o in ALLOW.get(c, ()) for o in cands)]
    return least[0] if len(least) == 1 else 'rerail-engine'


def main(tree_tsv, tests_tsv, *flags):
    nodes = {}
    for line in open(tree_tsv):
        p, f, df, s, e, vis, cfg, pa, kind = line.rstrip('\n').split('\t')
        f, df = os.path.join(ROOT, f), os.path.join(ROOT, df) if df else df
        nodes[p] = dict(file=f, decl_file=df, s=int(s), e=int(e), cfg=cfg, inline=kind == 'inline', path_attr=pa)

    def tested(p):
        while p != 'crate':
            if 'test' in nodes[p]['cfg'].replace(' ', ''):
                return True
            p = p.rsplit('::', 1)[0]
        return False

    file_mod = {os.path.relpath(n['file'], ROOT): p for p, n in nodes.items() if not n['inline']}
    line_starts = {}

    def byte_of(f, line):
        if f not in line_starts:
            data = open(os.path.join(ROOT, f), 'rb').read()
            starts = [0]
            i = data.find(b'\n')
            while i >= 0:
                starts.append(i + 1)
                i = data.find(b'\n', i + 1)
            line_starts[f] = starts
        L = line_starts[f]
        return L[min(line - 1, len(L) - 1)]

    def enclosing_test(f, line):
        """The test module a site at (f, line) is in: its file's, or the innermost inline test module there."""
        b = byte_of(f, line)
        best = None
        for p, n in nodes.items():
            if n['inline'] and os.path.relpath(n['decl_file'], ROOT) == f and n['s'] <= b < n['e'] and tested(p):
                if best is None or n['s'] > nodes[best]['s']:
                    best = p
        if best:
            return best
        p = file_mod.get(f)
        return p if p and tested(p) else None

    reads = collections.defaultdict(set)
    own = {}
    for line in list(open(tests_tsv))[1:]:
        frm, to, kind, item, defined, sites = line.rstrip('\n').split('\t')
        for s in sites.split():
            f, l = s.rsplit(':', 1)
            m = enclosing_test(f, int(l))
            if m:
                reads[m].add(to)
                own[m] = frm
    out, extract = [], []
    for m, to in sorted(reads.items()):
        h = host(to | {own[m]})
        if h == own[m]:
            continue
        key = m[len(DSL):].lstrip(':') if m.startswith(DSL) else m
        if nodes[m]['inline']:
            parent = m.rsplit('::', 1)[0]
            if nodes[parent]['inline']:
                print(f'NESTED inline test module (move by hand): {m} -> {h}')
                continue
            extract.append((m, h))
        out.append((key, h))
    with open(os.path.join(HERE, 'test-hosts.tsv'), 'w') as w:
        w.write('# Generated by hosts.py from the index: the crate that compiles each test module reading above its own.\n')
        for k, h in out:
            w.write(f'{k}\t{h}\n')
    print(f'test modules hosted above their crate: {len(out)} ({len(extract)} inline, to extract)')
    print(' ', dict(collections.Counter(h for _, h in out)))
    if '--extract' in flags:
        for m, h in sorted(extract, key=lambda x: (nodes[x[0]]['decl_file'], -nodes[x[0]]['s'])):
            extract_one(m, nodes)


def extract_one(m, nodes):
    n = nodes[m]
    parent = nodes[m.rsplit('::', 1)[0]]
    name = m.rsplit('::', 1)[1]
    src = n['decl_file']
    data = open(src, 'rb').read()
    decl = data[n['s']:n['e']]
    open_at = decl.index(b'{')
    assert decl.rstrip().endswith(b'}'), m
    head, body = decl[:open_at].rstrip(), decl[open_at + 1:decl.rstrip().rindex(b'}')]
    base, fname = os.path.split(parent['file'])
    stem = os.path.splitext(fname)[0]
    d = base if (fname == 'mod.rs' or parent['path_attr']) else os.path.join(base, stem)
    target = os.path.join(d, name + '.rs')
    if os.path.exists(target):
        print(f'SKIP {m}: {os.path.relpath(target, ROOT)} exists')
        return
    # the body's lines lose the block's indentation (four spaces)
    lines = body.strip(b'\n').split(b'\n')
    lines = [l[4:] if l.startswith(b'    ') else l for l in lines]
    os.makedirs(d, exist_ok=True)
    open(target, 'wb').write(b'\n'.join(lines).rstrip() + b'\n')
    open(src, 'wb').write(data[:n['s']] + head + b';' + data[n['e']:])
    print(f'extracted {m} -> {os.path.relpath(target, ROOT)}')


if __name__ == '__main__':
    main(*sys.argv[1:])
