"""The crate split's runtime test hosts: the test modules that need what the engine installs as it loads (the language
packs, the embedders, the build identity). The core asks for a language through its registry, so a test of a crate
below the languages that parses Python reads no Python item the index sees; it fails in its crate's own test binary,
where nothing registers Python. Such a module runs in the engine.

    python3 tools/cratify/runtime_hosts.py --tree <cratify tree output> [--passing <the unsplit engine's test output>]
        <cargo test --workspace output>...

Adds each module whose test panicked so (or, with --passing, that failed outside the engine's test binary although it
passes in the unsplit engine's: it needs something else the engine installs, a device or a snapshot reader) to
runtime-hosts.tsv (module -> rerail-engine, read after test-hosts.tsv),
keeping the ones already there. Run it over a split's `cargo test --workspace` and regenerate."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
PATH = os.path.join(HERE, 'runtime-hosts.tsv')
NEEDS_ENGINE = re.compile(r'no language (pack )?registered|no embedder registered|sets its build identity as it loads')
mods = set()
if os.path.exists(PATH):
    mods = {l.split('\t')[0] for l in open(PATH) if l.strip() and not l.startswith('#')}
args = sys.argv[1:]
assert args[:1] == ['--tree'], 'usage: --tree <tree.tsv> first'
nodes = {}
for line in open(args[1]):
    f = line.rstrip('\n').split('\t')
    nodes[f[0]] = f[6]
args = args[2:]


def tested(p):
    while p in nodes:
        if 'test' in nodes[p].replace(' ', ''):
            return True
        p = p.rsplit('::', 1)[0]
    return False


mods = {m for m in mods if tested('crate::code_rule_dsl::' + m if not m.startswith('crate::') else m)}
passing = set()
if args[:1] == ['--passing']:
    passing = set(re.findall(r'(?m)^test (\S+) \.\.\. ok$', open(args[1], errors='replace').read()))
    args = args[2:]
for out in args:
    lines = open(out, errors='replace').read().split('\n')
    binary = ''
    for i, line in enumerate(lines):
        b = re.match(r'\s*Running unittests src/lib.rs \(target/debug/deps/(\w+?)-', line)
        if b:
            binary = b.group(1)
        m = re.match(r"thread '([^']+)' \(\d+\) panicked at", line)
        outside = binary not in ('', 'rerail_engine') and m and m.group(1) in passing
        if m and (outside or NEEDS_ENGINE.search('\n'.join(lines[i + 1:i + 3]))):
            module = m.group(1).rsplit('::', 1)[0]
            if not tested('crate::' + module):
                print('a test in a production module (move it into a test module):', m.group(1))
                continue
            mods.add(module[len('code_rule_dsl::'):] if module.startswith('code_rule_dsl::') else 'crate::' + module)
with open(PATH, 'w') as w:
    w.write('# Generated by runtime_hosts.py from a split\'s test run: test modules that need what the engine installs as it\n'
            '# loads (language packs, embedders, the build identity), so the engine runs them.\n')
    for m in sorted(mods):
        w.write(f'{m}\trerail-engine\n')
print(len(mods), 'runtime hosts')
