//! Cranelift IR as UKL (decisions 0348 stage 5, 0440 step D): the same functions the JIT runs
//! as Rust, printed as UKL's C, so every GPU (Metal, CUDA, OpenCL, the CPU's backend) runs the same code.
//!
//! - **Values:** each a local of its type's unsigned C type, declared once. Arithmetic is on the
//!   type's width (32 bits below it: no promotion to `int`), its shifts' counts masked as Cranelift's are. Casts are
//!   C casts (OpenCL C 1.2 has no other).
//! - **Memory:** an address is the device's address of a byte of the batch's one arena, and each access is the
//!   arena's pointer at the address's offset from the arena's first byte (`hb`). An integer cast to a pointer is never
//!   accessed: the device compiler took two such pointers to one byte as different objects and read a byte back from
//!   before its store (`!(1/0)` was true; 0348, stage 5).
//! - **The context** (each function's first parameter) is a column of the batch's table: a field is its 8-byte
//!   slot's row (0408, L2), `cs` bytes a row, so a SIMD group's lanes read one line. The context is only ever a
//!   field's base (`context_uses`).
//! - **Widths:** the words read and write the same bytes at several widths (a field stored as 32 bits, read in a
//!   64-bit word), so every access is a byte or an aligned 64-bit word (`ukl_ldw_*`, `ukl_stw_*`): no direct access
//!   of another width the compiler's type-based alias rules could reorder, and none unaligned. The IR's `aligned` flag
//!   is the CPU's, and is not used.
//! - **The context** (each function's first parameter) is a column of the batch's table: a field is its 8-byte slot's
//!   row (0408, L2), `cs` bytes a row, so a SIMD group's lanes read one field as adjacent words. The context is only
//!   ever a field's base (`context_uses`).
//! - **Control:** the graph structured (`shape::Shape`), printed as C without labels.
//! - **Calls:** each function `UKL_FUNC`, called directly, the compiler inlining as it chooses; the graph has no
//!   recursion (no GPU language has it), which the translation checks.
//!
//! What it does not print is an error, never a fallback: vectors, stack slots, the stack pointer, traps, and more than
//! one result.

#[path = "clif_ukl/shape.rs"]
mod shape;

use shape::{Shape, returned_call, successors};
use cranelift_codegen::ir::{self, InstructionData, Opcode, condcodes::IntCC, types};
use std::fmt::Write;

/// A fingerprint of a text (FNV-1a): a translation's own, which it ends with (`native_cpu_pp::ukl_source`).
pub fn fingerprint(text: &str) -> u64 {
    text.bytes().fold(0xcbf2_9ce4_8422_2325u64, |h, b| (h ^ u64::from(b)).wrapping_mul(0x100_0000_01b3))
}

/// A type's unsigned and signed C names and its bits.
fn ty(t: ir::Type) -> Result<(&'static str, &'static str, u32), String> {
    Ok(match t {
        types::I8 => ("uint8_t", "int8_t", 8),
        types::I16 => ("uint16_t", "int16_t", 16),
        types::I32 => ("uint32_t", "int32_t", 32),
        types::I64 => ("uint64_t", "int64_t", 64),
        t => return Err(format!("the type {t}")),
    })
}

/// What every translation starts with: the library's backend and its word loads and stores.
const PRELUDE: &str = "#include <ukl/backend.h>\n#include <ukl/memory.h>\n\n\
// The batch's launch: its contexts' count, the device's address of the arena's first byte (`hb`): each access is\n\
// the arena's pointer at an address's offset from it; and the contexts' table's row bytes (`cs`, 0408 L2).\n\
typedef struct PpBatch { uint64_t hb; uint32_t count; uint32_t pad; uint64_t cs; } PpBatch;\n\
UKL_REFLECT_STRUCT(PpBatch, hb, count, pad, cs)\n\n";

/// The functions (by their user name's index), as UKL: each of `entries` called from a kernel of its name over a
/// batch, one context a thread taken by ticket (decision 0027's workers): `ctxs[t]` the context's address,
/// `results[t]` its run's result.
pub fn translate(funcs: &[(u32, ir::Function)], entries: &[(u32, &str)]) -> Result<String, String> {
    let mut out = String::from("// Generated by rerail_compiler::clif_ukl from the Cranelift IR. Do not edit.\n");
    out.push_str(PRELUDE);
    // Callees before callers, as C++ needs: by the call graph, which may have no cycle. A function's calls are its
    // call instructions', not its imports: an import whose calls the inliner took (a hot read's) calls nothing.
    let calls = |f: &ir::Function| -> Vec<u32> {
        let mut out = Vec::new();
        for block in f.layout.blocks() {
            for inst in f.layout.block_insts(block) {
                let InstructionData::Call { func_ref, .. } = f.dfg.insts[inst] else { continue };
                if let ir::ExternalName::User(r) = &f.dfg.ext_funcs[func_ref].name {
                    let index = f.params.user_named_funcs()[*r].index;
                    if !out.contains(&index) {
                        out.push(index);
                    }
                }
            }
        }
        out
    };
    let mut order: Vec<u32> = Vec::new();
    let mut state: std::collections::HashMap<u32, u8> = Default::default();
    fn visit(id: u32, funcs: &[(u32, ir::Function)], calls: &dyn Fn(&ir::Function) -> Vec<u32>, state: &mut std::collections::HashMap<u32, u8>, order: &mut Vec<u32>) -> Result<(), String> {
        match state.get(&id) {
            Some(2) => return Ok(()),
            Some(_) => return Err(format!("u0:{id} is called in a cycle: no GPU language has recursion")),
            None => {}
        }
        state.insert(id, 1);
        let f = &funcs.iter().find(|(i, _)| *i == id).ok_or_else(|| format!("no function u0:{id}"))?.1;
        for c in calls(f) {
            // A callee not among the functions: named with its caller and its signature (a read, or a word).
            if !funcs.iter().any(|(i, _)| *i == c) {
                let sig = f.dfg.ext_funcs.values().find(|e| matches!(&e.name, ir::ExternalName::User(r) if f.params.user_named_funcs()[*r].index == c)).map(|e| f.dfg.signatures[e.signature].to_string());
                return Err(format!("no function u0:{c}, called by u0:{id} ({}), signature {}", f.name, sig.unwrap_or_default()));
            }
            visit(c, funcs, calls, state, order)?;
        }
        state.insert(id, 2);
        order.push(id);
        Ok(())
    }
    for (id, _) in funcs {
        visit(*id, funcs, &calls, &mut state, &mut order)?;
    }
    for id in order {
        let f = &funcs.iter().find(|(i, _)| *i == id).expect("listed").1;
        function(&mut out, id, f).map_err(|e| format!("u0:{id}: {e}"))?;
    }
    for &(entry, n) in entries {
        let f = &funcs.iter().find(|(id, _)| *id == entry).ok_or("no entry")?.1;
        if f.signature.params.len() != 1 || f.signature.returns.len() != 1 {
            return Err(format!("the entry {n}: one parameter and one result"));
        }
        writeln!(
            out,
            "// The entry over a batch: each worker takes contexts by ticket until none is left.\n\
             DEFINE_KERNEL2(pp, {n}, RWBUFFER, uint64_t, ctxs, \"[count + 1]\", RWBUFFER, uint64_t, results, \"[count]\",\n\
             \x20              RWBUFFER, uint32_t, ticket, \"[1]\", RWBUFFER, uint8_t, heap, \"[arena]\", ARGS, PpBatch, p, )\n\
             {{\n\
             \x20 for (uint32_t k = 0u; k < p.count; k++) {{\n\
             \x20   const uint32_t t = ukl_atomic_add(ticket, 1u);\n\
             \x20   if (t >= p.count) return;\n\
             \x20   results[t] = f{entry}(0ul, heap, p.hb, p.cs, ctxs[t]);\n\
             \x20 }}\n\
             }}\n"
        )
        .unwrap();
    }
    Ok(out)
}

/// One function.
fn function(out: &mut String, id: u32, f: &ir::Function) -> Result<(), String> {
    let dfg = &f.dfg;
    if !f.sized_stack_slots.is_empty() {
        return Err("a stack slot".into());
    }
    let ret_ty = match f.signature.returns.len() {
        0 => "void",
        1 => ty(f.signature.returns[0].value_type)?.0,
        _ => return Err("more than one result".into()),
    };
    let fields = context_fields(f);
    context_uses(f, &fields)?;
    let name = |v: ir::Value| format!("v{}", dfg.resolve_aliases(v).as_u32());
    let entry = f.layout.entry_block().ok_or("no entry block")?;
    let params: Vec<String> = dfg.block_params(entry).iter().map(|&v| Ok(format!("{} a{}", ty(dfg.value_type(v))?.0, v.as_u32()))).collect::<Result<_, String>>()?;
    writeln!(out, "UKL_FUNC {ret_ty} f{id}(uint64_t pin, UKL_GLOBAL uint8_t* heap, uint64_t hb, uint64_t cs{}{}) {{", if params.is_empty() { "" } else { ", " }, params.join(", ")).unwrap();
    let mut declared = std::collections::BTreeMap::new();
    for b in f.layout.blocks() {
        for &v in dfg.block_params(b) {
            declared.insert(v.as_u32(), ty(dfg.value_type(v))?.0);
        }
        for inst in f.layout.block_insts(b) {
            for &v in dfg.inst_results(inst) {
                declared.insert(v.as_u32(), ty(dfg.value_type(v))?.0);
            }
        }
    }
    for (v, t) in &declared {
        writeln!(out, "  {t} v{v} = 0;").unwrap();
    }
    for &v in dfg.block_params(entry) {
        writeln!(out, "  v{0} = a{0};", v.as_u32()).unwrap();
    }
    out.push_str("  uint32_t d = 0u, j = 0u;\n");
    let blocks: Vec<ir::Block> = std::iter::once(entry).chain(f.layout.blocks().filter(|&b| b != entry)).collect();
    let node_of: std::collections::HashMap<ir::Block, usize> = blocks.iter().enumerate().map(|(i, &b)| (b, i)).collect();
    let first: Vec<Vec<usize>> = blocks.iter().map(|&b| successors(f, b).iter().map(|t| node_of[t]).collect()).collect();
    let sizes: Vec<usize> = blocks.iter().map(|&b| f.layout.block_insts(b).count()).collect();
    match Shape::of(first, &sizes) {
        Some(shape) => {
            let emit = |node: usize, jump: &dyn Fn(usize) -> Result<String, String>| -> Result<String, String> {
                let mut s = String::new();
                for inst in f.layout.block_insts(blocks[node]) {
                    s.push_str(&instruction(f, inst, &fields, &name, &|k, _| jump(k))?);
                    s.push('\n');
                }
                Ok(s)
            };
            // Inside one construct, so every exit's `break` has one to leave.
            let body = shape.tree(&emit, 0)?;
            writeln!(out, "do {{\n{body}}} while (false);\n  return {};\n}}\n", if ret_ty == "void" { "" } else { "0" }).unwrap();
        }
        None => {
            // An irreducible graph: a loop over a `switch` on the block.
            writeln!(out, "  uint b = {}u;\n  for (;;) {{\n  switch (b) {{", entry.as_u32()).unwrap();
            for blk in f.layout.blocks() {
                writeln!(out, "  case {}u: {{", blk.as_u32()).unwrap();
                for inst in f.layout.block_insts(blk) {
                    out.push_str(&instruction(f, inst, &fields, &name, &|_, to: ir::Block| Ok(format!("b = {}u; continue;", to.as_u32())))?);
                    out.push('\n');
                }
                out.push_str("  } break;\n");
            }
            writeln!(out, "  default: return {};\n  }}\n  }}\n}}\n", if ret_ty == "void" { "" } else { "0" }).unwrap();
        }
    }
    Ok(())
}

/// A function's context: its first parameter.
fn context(f: &ir::Function) -> Option<ir::Value> {
    f.layout.entry_block().and_then(|e| f.dfg.block_params(e).first().copied())
}

/// The values that are the context plus a constant (the context itself, and `iadd_imm`s of them), each with its
/// constant.
type Fields = std::collections::HashMap<ir::Value, i64>;

fn context_fields(f: &ir::Function) -> Fields {
    let dfg = &f.dfg;
    let mut fields = Fields::new();
    let Some(c) = context(f) else { return fields };
    fields.insert(c, 0);
    loop {
        let before = fields.len();
        for b in f.layout.blocks() {
            for inst in f.layout.block_insts(b) {
                if let InstructionData::BinaryImm64 { opcode: Opcode::IaddImm, arg, imm } = dfg.insts[inst]
                    && let Some(&o) = fields.get(&dfg.resolve_aliases(arg))
                {
                    fields.insert(dfg.first_result(inst), o + imm.bits());
                }
            }
        }
        if fields.len() == before {
            return fields;
        }
    }
}

/// The context is used only as a load's or a store's base, at a field within one 8-byte slot, as a callee's context
/// (its first argument), or plus a constant (`context_fields`) for the same uses: the device's table holds a context
/// by slots, so any other use, an address made from it any other way or the context as a value, is refused.
fn context_uses(f: &ir::Function, fields: &Fields) -> Result<(), String> {
    let dfg = &f.dfg;
    for b in f.layout.blocks() {
        for inst in f.layout.block_insts(b) {
            let data = &dfg.insts[inst];
            for (i, &v) in dfg.inst_args(inst).iter().enumerate() {
                let Some(&at) = fields.get(&dfg.resolve_aliases(v)) else { continue };
                let field = |n: u32| {
                    data.load_store_offset().is_some_and(|o| {
                        let o = at + i64::from(o);
                        o >= 0 && o % i64::from(n) == 0 && o % 8 + i64::from(n) <= 8
                    })
                };
                let ok = match data.opcode() {
                    Opcode::Uload8 | Opcode::Sload8 if i == 0 => field(1),
                    Opcode::Uload16 | Opcode::Sload16 if i == 0 => field(2),
                    Opcode::Uload32 | Opcode::Sload32 if i == 0 => field(4),
                    Opcode::Load if i == 0 => dfg.inst_results(inst).first().is_some_and(|&r| field(dfg.value_type(r).bytes())),
                    Opcode::Store | Opcode::Istore8 | Opcode::Istore16 | Opcode::Istore32 if i == 1 => {
                        let n = match data.opcode() {
                            Opcode::Istore8 => 1,
                            Opcode::Istore16 => 2,
                            Opcode::Istore32 => 4,
                            _ => dfg.value_type(dfg.inst_args(inst)[0]).bytes(),
                        };
                        field(n)
                    }
                    Opcode::Call => i == 0 && at == 0,
                    Opcode::IaddImm => fields.contains_key(&dfg.first_result(inst)),
                    _ => false,
                };
                if !ok {
                    return Err(format!("the context used other than as a field's base: {}", dfg.display_inst(inst)));
                }
            }
        }
    }
    Ok(())
}

/// A branch to `call`: its arguments into its block's parameters (all read first), then on.
fn goto(f: &ir::Function, call: &ir::BlockCall, k: usize, name: &dyn Fn(ir::Value) -> String, jump: &dyn Fn(usize, ir::Block) -> Result<String, String>) -> Result<String, String> {
    let dfg = &f.dfg;
    let to = call.block(&dfg.value_lists);
    let args: Vec<String> = call
        .args(&dfg.value_lists)
        .map(|a| match a {
            ir::BlockArg::Value(v) => Ok(name(v)),
            _ => Err("a block argument that is not a value".to_string()),
        })
        .collect::<Result<_, _>>()?;
    let params = dfg.block_params(to);
    let mut s = String::from("{ ");
    if params.len() == 1 {
        write!(s, "v{} = {}; ", params[0].as_u32(), args[0]).unwrap();
    } else if !params.is_empty() {
        for (i, (a, p)) in args.iter().zip(params).enumerate() {
            write!(s, "const {} t{i} = {a}; ", ty(dfg.value_type(*p))?.0).unwrap();
        }
        for (i, p) in params.iter().enumerate() {
            write!(s, "v{} = t{i}; ", p.as_u32()).unwrap();
        }
    }
    s.push_str(&jump(k, to)?);
    s.push_str(" }");
    Ok(s)
}

/// A 64-bit constant as C, of type `u`.
fn konst(c: i64, u: &str) -> String {
    format!("(({u})({:#x}ul))", c as u64)
}

fn instruction(f: &ir::Function, inst: ir::Inst, fields: &Fields, name: &dyn Fn(ir::Value) -> String, jump: &dyn Fn(usize, ir::Block) -> Result<String, String>) -> Result<String, String> {
    let dfg = &f.dfg;
    let data = &dfg.insts[inst];
    let op = data.opcode();
    let args: Vec<String> = dfg.inst_args(inst).iter().map(|&v| name(v)).collect();
    let results = dfg.inst_results(inst);
    let r = results.first().map(|&v| name(v));
    let rt = results.first().map(|&v| dfg.value_type(v));
    let at = dfg.inst_args(inst).first().map(|&v| dfg.value_type(v));
    if rt.is_some_and(|t| t.is_vector()) || at.is_some_and(|t| t.is_vector()) {
        return Err(format!("{op} on vectors"));
    }
    let set = |e: String| -> String { format!("{} = {e};", r.clone().expect("a result")) };
    let (u, s, bits) = rt.and_then(|t| ty(t).ok()).unwrap_or(("uint64_t", "int64_t", 64));
    // The width arithmetic is done at: no promotion to `int` below 32 bits.
    let w = if bits == 64 { "uint64_t" } else { "uint32_t" };
    let ws = if bits == 64 { "int64_t" } else { "int32_t" };
    let bin = |o: &str| set(format!("(({u})((({w})({})) {o} (({w})({}))))", args[0], args[1]));
    let imm = || -> Result<i64, String> {
        match data {
            InstructionData::UnaryImm { imm, .. } | InstructionData::BinaryImm64 { imm, .. } | InstructionData::IntCompareImm { imm, .. } => Ok(imm.bits()),
            _ => Err(format!("{op}: no immediate")),
        }
    };
    let bimm = |o: &str| -> Result<String, String> { Ok(set(format!("(({u})((({w})({})) {o} (({w}){})))", args[0], konst(imm()?, u)))) };
    // A value as its signed type, at the width arithmetic is done at.
    let signed = |x: &str| format!("(({ws})(({s})({x})))");
    // The arena's byte at the address: its offset from the arena's first byte.
    let addr = |p: &str| -> String {
        let off = data.load_store_offset().unwrap_or(0);
        if off == 0 { format!("(({p}) - hb)") } else { format!("(({p}) + {} - hb)", konst(i64::from(off), "uint64_t")) }
    };
    // A field of the context (the function's first parameter, or it plus a constant): its 8-byte slot's row of the
    // batch's table (0408, L2), `cs` bytes a row, in the context's column; `context_uses` checked it lies in one slot.
    let place = |i: usize| -> String {
        let base = dfg.resolve_aliases(dfg.inst_args(inst)[i]);
        match fields.get(&base) {
            Some(&o) => {
                let off = o + i64::from(data.load_store_offset().unwrap_or(0));
                format!("(({}) - hb + cs * {}ul + {}ul)", name(context(f).expect("a context")), off / 8, off % 8)
            }
            None => addr(&args[i]),
        }
    };
    let load = |n: u32| -> String { format!("ukl_ldw_u{}(heap, {})", n * 8, place(0)) };
    let store = |n: u32, x: &str| -> String { format!("ukl_stw_u{}(heap, {}, (uint64_t)({x}));", n * 8, place(1)) };
    let shift = |x: &str| format!("(((uint32_t)({x})) & {}u)", bits - 1);
    // The operand's bits counted by the library's 32- or 64-bit count.
    let (aw, abits) = match at.and_then(|t| ty(t).ok()) {
        Some((_, _, 64)) => (64, 64),
        Some((_, _, b)) => (32, b),
        None => (64, 64),
    };
    Ok(match op {
        Opcode::Iconst => set(konst(imm()?, u)),
        Opcode::Iadd => bin("+"),
        Opcode::Isub => bin("-"),
        Opcode::Imul => bin("*"),
        Opcode::Ineg => set(format!("(({u})(0u - (({w})({}))))", args[0])),
        Opcode::Udiv => bin("/"),
        Opcode::Urem => bin("%"),
        Opcode::Sdiv => set(format!("(({u})({} / {}))", signed(&args[0]), signed(&args[1]))),
        Opcode::Srem => set(format!("(({u})({} % {}))", signed(&args[0]), signed(&args[1]))),
        Opcode::Umulhi if bits == 64 => set(format!("ukl_umulhi64({}, {})", args[0], args[1])),
        Opcode::Umulhi => set(format!("(({u})((((uint64_t)({})) * ((uint64_t)({}))) >> {bits}))", args[0], args[1])),
        Opcode::Band => bin("&"),
        Opcode::Bor => bin("|"),
        Opcode::Bxor => bin("^"),
        Opcode::BandNot => set(format!("(({u})((({w})({})) & ~(({w})({}))))", args[0], args[1])),
        Opcode::BorNot => set(format!("(({u})((({w})({})) | ~(({w})({}))))", args[0], args[1])),
        Opcode::BxorNot => set(format!("(({u})((({w})({})) ^ ~(({w})({}))))", args[0], args[1])),
        Opcode::Bnot => set(format!("(({u})(~(({w})({}))))", args[0])),
        // The library's reverse of 32 or 64 bits, the type's bits at the top: shifted down to its width.
        Opcode::Bitrev if bits == 64 => set(format!("ukl_reverse64({})", args[0])),
        Opcode::Bitrev => set(format!("(({u})(ukl_reverse32((uint32_t)({})) >> {}u))", args[0], 32 - bits)),
        Opcode::IaddImm => bimm("+")?,
        Opcode::ImulImm => bimm("*")?,
        Opcode::UdivImm => bimm("/")?,
        Opcode::BandImm => bimm("&")?,
        Opcode::BorImm => bimm("|")?,
        Opcode::BxorImm => bimm("^")?,
        Opcode::IrsubImm => set(format!("(({u})((({w}){}) - (({w})({}))))", konst(imm()?, u), args[0])),
        Opcode::Ishl => set(format!("(({u})((({w})({})) << {}))", args[0], shift(&args[1]))),
        Opcode::Ushr => set(format!("(({u})((({w})({})) >> {}))", args[0], shift(&args[1]))),
        Opcode::Sshr => set(format!("(({u})({} >> {}))", signed(&args[0]), shift(&args[1]))),
        Opcode::IshlImm => set(format!("(({u})((({w})({})) << {}u))", args[0], (imm()? as u32) % bits)),
        Opcode::UshrImm => set(format!("(({u})((({w})({})) >> {}u))", args[0], (imm()? as u32) % bits)),
        Opcode::SshrImm => set(format!("(({u})({} >> {}u))", signed(&args[0]), (imm()? as u32) % bits)),
        // A rotate by a constant: two shifts at the type's width (none for a count of 0).
        Opcode::RotlImm => match (imm()? as u32) % bits {
            0 => set(args[0].clone()),
            k => set(format!("(({u})(((({w})({x})) << {k}u) | ((({w})({x})) >> {r}u)))", x = args[0], r = bits - k)),
        },
        Opcode::Popcnt => set(format!("(({u})(ukl_popcount{aw}({})))", args[0])),
        // Below 32 bits, the count of a 32-bit value less the bits above the type's.
        Opcode::Clz => set(format!("(({u})(ukl_clz{aw}({}) - {}u))", args[0], aw - abits)),
        // Below 32 bits, the bit past the type's set: a value of 0 counts the type's bits.
        Opcode::Ctz if abits < 32 => set(format!("(({u})(ukl_ctz32(((uint32_t)({})) | {:#x}u)))", args[0], 1u32 << abits)),
        Opcode::Ctz => set(format!("(({u})(ukl_ctz{aw}({})))", args[0])),
        Opcode::Umin => set(format!("(({u})(ukl_min((({w})({})), (({w})({})))))", args[0], args[1])),
        Opcode::Umax => set(format!("(({u})(ukl_max((({w})({})), (({w})({})))))", args[0], args[1])),
        Opcode::Smin => set(format!("(({u})(ukl_min({}, {})))", signed(&args[0]), signed(&args[1]))),
        Opcode::Smax => set(format!("(({u})(ukl_max({}, {})))", signed(&args[0]), signed(&args[1]))),
        Opcode::UaddOverflow => format!("{0} = (({2})((({w})({3})) + (({w})({4})))); {1} = (uint8_t)({0} < {3});", name(results[0]), name(results[1]), u, args[0], args[1]),
        Opcode::Icmp | Opcode::IcmpImm => {
            let cc = data.cond_code().ok_or("a compare with no condition")?;
            let (au, asg, _) = ty(dfg.value_type(dfg.inst_args(inst)[0]))?;
            let b = if op == Opcode::IcmpImm { konst(imm()?, au) } else { args[1].clone() };
            let (sig, o) = match cc {
                IntCC::Equal => (false, "=="),
                IntCC::NotEqual => (false, "!="),
                IntCC::SignedLessThan => (true, "<"),
                IntCC::SignedGreaterThanOrEqual => (true, ">="),
                IntCC::SignedGreaterThan => (true, ">"),
                IntCC::SignedLessThanOrEqual => (true, "<="),
                IntCC::UnsignedLessThan => (false, "<"),
                IntCC::UnsignedGreaterThanOrEqual => (false, ">="),
                IntCC::UnsignedGreaterThan => (false, ">"),
                IntCC::UnsignedLessThanOrEqual => (false, "<="),
            };
            let t = if sig { asg } else { au };
            set(format!("((uint8_t)((({t})({})) {o} (({t})({b}))))", args[0]))
        }
        Opcode::Select => set(format!("{} != 0 ? {} : {}", args[0], args[1], args[2])),
        Opcode::Uextend | Opcode::Ireduce | Opcode::Bitcast => set(format!("(({u})({}))", args[0])),
        Opcode::Sextend => {
            let from = ty(dfg.value_type(dfg.inst_args(inst)[0]))?;
            set(format!("(({u})(({s})(({})({}))))", from.1, args[0]))
        }
        Opcode::Load => set(format!("(({u})({}))", load(bits / 8))),
        Opcode::Uload8 => set(format!("(({u})({}))", load(1))),
        Opcode::Uload16 => set(format!("(({u})({}))", load(2))),
        Opcode::Uload32 => set(format!("(({u})({}))", load(4))),
        Opcode::Sload8 => set(format!("(({u})(({s})((int8_t)({}))))", load(1))),
        Opcode::Sload16 => set(format!("(({u})(({s})((int16_t)({}))))", load(2))),
        Opcode::Sload32 => set(format!("(({u})(({s})((int32_t)({}))))", load(4))),
        Opcode::Store => {
            let (_, _, vb) = ty(dfg.value_type(dfg.inst_args(inst)[0]))?;
            store(vb / 8, &args[0])
        }
        Opcode::Istore8 => store(1, &args[0]),
        Opcode::Istore16 => store(2, &args[0]),
        Opcode::Istore32 => store(4, &args[0]),
        Opcode::GetPinnedReg => set("pin".to_string()),
        Opcode::SetPinnedReg => format!("pin = {};", args[0]),
        Opcode::Nop => String::new(),
        Opcode::Call => {
            let InstructionData::Call { func_ref, .. } = data else { return Err("a call of no function".into()) };
            let callee = match &dfg.ext_funcs[*func_ref].name {
                ir::ExternalName::User(r) => f.params.user_named_funcs()[*r].index,
                n => return Err(format!("a call of {n:?}")),
            };
            let call = format!("f{callee}(pin, heap, hb, cs{}{})", if args.is_empty() { "" } else { ", " }, args.join(", "));
            if returned_call(f, inst) {
                return Ok(format!("return {call};"));
            }
            match results.len() {
                0 => format!("{call};"),
                1 => set(call),
                _ => return Err("a call of more than one result".into()),
            }
        }
        Opcode::Return if f.layout.prev_inst(inst).is_some_and(|c| returned_call(f, c)) => String::new(),
        Opcode::Return => match args.len() {
            0 => "return;".to_string(),
            1 => format!("return {};", args[0]),
            _ => return Err("a return of more than one value".into()),
        },
        Opcode::Jump => {
            let InstructionData::Jump { destination, .. } = data else { return Err("a jump with no destination".into()) };
            goto(f, destination, 0, name, jump)?
        }
        Opcode::Brif => {
            let InstructionData::Brif { blocks, .. } = data else { return Err("a branch with no blocks".into()) };
            format!("if ({} != 0) {} else {}", args[0], goto(f, &blocks[0], 0, name, jump)?, goto(f, &blocks[1], 1, name, jump)?)
        }
        // A jump table: a `switch`, its cases the table's (successors 1 on), the rest the
        // default (successor 0). A jump in a case breaks the `switch`, then the construct around.
        Opcode::BrTable => {
            let InstructionData::BranchTable { table, .. } = data else { return Err("a jump table of nothing".into()) };
            let jt = &f.dfg.jump_tables[*table];
            let default = goto(f, &jt.default_block(), 0, name, jump)?;
            let mut arms: Vec<(String, Vec<usize>)> = Vec::new();
            for (i, call) in jt.as_slice().iter().enumerate() {
                let to = goto(f, call, i + 1, name, jump)?;
                if to == default {
                    continue;
                }
                match arms.iter_mut().find(|a| a.0 == to) {
                    Some(a) => a.1.push(i),
                    None => arms.push((to, vec![i])),
                }
            }
            let mut sw = format!("switch ({}) {{ ", args[0]);
            for (to, keys) in &arms {
                for k in keys {
                    write!(sw, "case {k}: ").unwrap();
                }
                write!(sw, "{to} break; ").unwrap();
            }
            write!(sw, "default: {default} break; }}").unwrap();
            sw
        }
        op => return Err(format!("the opcode {op}")),
    })
}

#[cfg(test)]
mod tests {
    use cranelift_codegen::ir::{AbiParam, Function, InstBuilder, MemFlags, Signature, UserFuncName, types::I64};
    use cranelift_codegen::isa::CallConv;
    use cranelift_frontend::{FunctionBuilder, FunctionBuilderContext};

    /// A function of the context: `body` given the builder and the context, returning a value.
    fn of_context(body: impl FnOnce(&mut FunctionBuilder<'_>, cranelift_codegen::ir::Value) -> cranelift_codegen::ir::Value) -> Function {
        let mut sig = Signature::new(CallConv::Tail);
        sig.params.push(AbiParam::new(I64));
        sig.returns.push(AbiParam::new(I64));
        let mut f = Function::with_name_signature(UserFuncName::user(0, 0), sig);
        let mut ctx = FunctionBuilderContext::new();
        let mut b = FunctionBuilder::new(&mut f, &mut ctx);
        let entry = b.create_block();
        b.append_block_params_for_function_params(entry);
        b.switch_to_block(entry);
        let c = b.block_params(entry)[0];
        let r = body(&mut b, c);
        b.ins().return_(&[r]);
        b.seal_all_blocks();
        b.finalize();
        f
    }

    /// A context field, directly or through the context plus a constant, is its slot's row of the batch's table
    /// (0408, L2): 8 bytes on and 4 bytes into it is row 1 and byte 4.
    #[test]
    fn a_context_field_is_its_slots_row() {
        let f = of_context(|b, c| {
            let at = b.ins().iadd_imm(c, 8);
            let x = b.ins().uload32(MemFlags::trusted(), at, 4);
            let y = b.ins().load(I64, MemFlags::trusted(), c, 16);
            b.ins().iadd(x, y)
        });
        let ukl = super::translate(&[(0, f)], &[(0, "k")]).unwrap();
        assert!(ukl.contains("((v0) - hb + cs * 1ul + 4ul)"), "{ukl}");
        assert!(ukl.contains("((v0) - hb + cs * 2ul + 0ul)"), "{ukl}");
    }

    /// Any other use of the context is refused: an address made from it by a value, the context as a value, or a
    /// field across two slots.
    #[test]
    fn the_context_as_a_value_is_refused() {
        let made = of_context(|b, c| {
            let at = b.ins().iadd(c, c);
            b.ins().load(I64, MemFlags::trusted(), at, 0)
        });
        let returned = of_context(|_, c| c);
        let across = of_context(|b, c| b.ins().load(I64, MemFlags::trusted(), c, 4));
        for f in [made, returned, across] {
            let e = super::translate(&[(0, f)], &[(0, "k")]).unwrap_err();
            assert!(e.contains("the context used other than as a field's base"), "{e}");
        }
    }
}
