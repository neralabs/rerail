// The language registry `code_rule_dsl::language` includes (`OUT_DIR/language_registry.rs`), generated as the
// engine's build script generates it (`native/src/build_languages.rs`, the same code), and the vendored grammars the
// registry declares (`native/src/build_grammars.rs`): built here, by the crate that declares their symbols, so every
// crate's tests link them (the engine's build script leaves them to this one once it is split).
#[path = "../../src/build_identity.rs"]
#[allow(dead_code)]
mod identity;
#[path = "../../src/build_languages.rs"]
mod languages;
#[path = "../../src/build_grammars.rs"]
mod grammars;
// The grammars' token automata, built here once (`tape::token_automata`), not in every process.
#[path = "../../src/code_rule_dsl/tape/token_automata.rs"]
#[allow(dead_code)]
mod token_automata;

use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"));
    // `native/` is two levels up. Not `canonicalize()`: on Windows that gives a `\\?\` path, in which the grammar
    // build's `/`-joined paths are invalid (os error 123).
    let native = manifest.ancestors().nth(2).expect("native/ is the manifest's grandparent").to_path_buf();
    let omitted = languages::omitted_languages(&native.parent().expect("repository root").join("languages"));
    grammars::build_all(&native, &omitted);
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("out dir"));
    languages::generate_registry(&native, &omitted, &out);
    token_automata_built(&native, &out);
}

/// Each grammar's automata (`token_automata::GRAMMARS`) as bytes in `OUT_DIR/token_automata`, and `built(lang)`,
/// which `tape::tokens` includes, naming them.
fn token_automata_built(native: &std::path::Path, out: &std::path::Path) {
    let dir = out.join("token_automata");
    std::fs::create_dir_all(&dir).expect("OUT_DIR is writable");
    println!("cargo:rerun-if-changed={}", native.join("src/code_rule_dsl/tape/token_automata.rs").display());
    let (mut arms, mut census_arms) = (String::new(), String::new());
    for (variant, path) in token_automata::GRAMMARS {
        let json = native.join("grammars").join(path).join("grammar.json");
        println!("cargo:rerun-if-changed={}", json.display());
        let text = std::fs::read_to_string(&json).unwrap_or_else(|e| panic!("{}: {e}", json.display()));
        // A grammar with no automata (one `build` refuses) keeps all its tokens, as before.
        let Ok(built) = token_automata::build(&text) else { continue };
        std::fs::write(dir.join(format!("{variant}.bin")), token_automata::encode(&built)).expect("OUT_DIR is writable");
        let census = token_automata::census(&built.texts, built.kinds.iter().map(|(sym, automaton)| (sym, automaton)), &built.extras);
        std::fs::write(dir.join(format!("{variant}.census")), token_automata::encode_census(&census)).expect("OUT_DIR is writable");
        arms.push_str(&format!("        GrammarDialect::{variant} => include_bytes!(concat!(env!(\"OUT_DIR\"), \"/token_automata/{variant}.bin\")),\n"));
        census_arms.push_str(&format!("        GrammarDialect::{variant} => include_bytes!(concat!(env!(\"OUT_DIR\"), \"/token_automata/{variant}.census\")),\n"));
    }
    let code = format!(
        "/// Generated by the lang crate's build script (`token_automata_built`).\nfn built(lang: GrammarDialect) -> Option<&'static [u8]> {{\n    Some(match lang {{\n{arms}        _ => return None,\n    }})\n}}\n\n/// Generated with `built`: each grammar's census (`token_automata::Census`).\npub(in crate::code_rule_dsl) fn census(lang: GrammarDialect) -> Option<&'static [u8]> {{\n    Some(match lang {{\n{census_arms}        _ => return None,\n    }})\n}}\n"
    );
    std::fs::write(out.join("token_automata.rs"), code).expect("OUT_DIR is writable");
}
