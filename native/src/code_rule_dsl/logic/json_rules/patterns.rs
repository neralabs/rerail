//! The translator's regular expressions, compiled once per batch of translations (`Translator`) and passed
//! to each pass as `px`: Python's module-level `re.compile`s.

use super::pyre::re;
use fancy_regex::Regex;

pub struct Patterns {
    pub text_ticks: Regex,
    pub text_string: Regex,
    pub text_upper: Regex,
    pub text_mv_ref: Regex,
    pub text_bind_arg: Regex,
    pub text_bind_key: Regex,
    pub text_pattern: Regex,
    pub text_capture: Regex,
    pub text_named_group: Regex,
    pub text_agg_start: Regex,
    pub text_pieces: Regex,
    pub text_called: Regex,
    pub text_atom_start: Regex,
    pub text_top_upper: Regex,
    pub text_have: Regex,
    pub text_td_var: Regex,
    pub text_str_piece: Regex,
    pub souffle_flags: Regex,
    pub souffle_stmt_tok: Regex,
    pub souffle_tick_var: Regex,
    pub souffle_named_group: Regex,
    pub simplify_generated: Regex,
    pub simplify_meaningless: Regex,
    pub simplify_prot: Regex,
    pub simplify_cap: Regex,
    pub simplify_var: Regex,
    pub simplify_tick_mv: Regex,
    pub simplify_call: Regex,
    pub simplify_bare_rel: Regex,
    pub simplify_bare_name: Regex,
    pub simplify_node_atom: Regex,
    pub fold_template_call: Regex,
    pub fold_named: Regex,
    pub fold_bare: Regex,
    pub fold_word: Regex,
    pub fold_piece: Regex,
    pub share_top_call: Regex,
    pub share_agg_body: Regex,
    pub share_lower_var: Regex,
    pub demand_agg: Regex,
    pub demand_positive: Regex,
    pub demand_eq: Regex,
    pub demand_ancestor: Regex,
    pub demand_unary: Regex,
    pub demand_fan: Regex,
    pub demand_up: Regex,
    pub demand_empty_neg: Regex,
    pub translate_viol_head: Regex,
    pub translate_from_clause: Regex,
    pub translate_no_match_group: Regex,
    pub engine_dialect_anchor: Regex,
    pub engine_dialect_lit: Regex,
    pub engine_dialect_decl: Regex,
    pub engine_dialect_not_lower_digit: Regex,
    pub engine_dialect_message: Regex,
    pub engine_dialect_brace: Regex,
    pub engine_dialect_options: Regex,
    pub engine_dialect_lone_any: Regex,
    pub engine_dialect_lone_mv: Regex,
    pub engine_dialect_text_use: Regex,
    pub engine_dialect_rule: Regex,
    pub engine_dialect_host_reads: Regex,
    pub engine_dialect_head_start: Regex,
    pub engine_dialect_strings: Regex,
    pub engine_dialect_pair: Regex,
    pub engine_dialect_unbound_test: Regex,
    pub engine_dialect_agg_open: Regex,
    pub engine_dialect_stop_axis: Regex,
}

impl Patterns {
    pub fn new() -> Self {
        Patterns {
            text_ticks: re(r"`+[^`]*`+"),
            text_string: re(r#""(?:[^"\\]|\\.)*""#),
            text_upper: re(r#"(?<![\w$"@])([A-Z][A-Z0-9_]*)\b(?!\s*\()"#),
            text_mv_ref: re(r"\$\$?\$?([A-Z_][A-Z0-9_]*)"),
            text_bind_arg: re(r#""bind": \{([^}]*)\}"#),
            text_bind_key: re(r#""([A-Z_][A-Z0-9_]*)":"#),
            text_pattern: re(r"~\s*(`+)(.*?)\1"),
            text_capture: re(r"(?<![\w$])([A-Z][A-Z0-9_]*)\s*=\s*[a-z0-9]"),
            text_named_group: re(r"\(\?P?<([A-Za-z_]\w*)>"),
            text_agg_start: re(r"\b(?:count|sum|min|max|mean)\b[^:{}()]*:\s*\{"),
            text_pieces: re(r#"("(?:[^"\\]|\\.)*"|`+[^`]*`+)"#),
            text_called: re(r"(?<![\w.])([a-z_]\w*)\("),
            text_atom_start: re(r"^[a-z_][A-Za-z0-9_]*\("),
            text_top_upper: re(r"(?<![\w$@])([A-Z][A-Z0-9_]*)\b"),
            text_have: re(r#"(?<![\w$])([A-Z][A-Z0-9_]*)\s*=\s*[@a-z0-9"]"#),
            text_td_var: re(r"(?<![\w$])([td]\d+)\b"),
            text_str_piece: re(r#"("(?:[^"\\]|\\.)*")"#),
            souffle_flags: re(r"^\(\?[a-zA-Z]+\)"),
            souffle_stmt_tok: re(r#"(?s)"(?:[^"\\]|\\.)*"|`+|//[^\n]*|:-|=>|!=|<=|>=|\d+(?:\.\d+)?(?:[eE][-+]?\d+)?|[A-Za-z_][A-Za-z0-9_]*|@[A-Za-z_]\w*|\d+(?:\.\d+)?(?:[eE][-+]?\d+)?|\S"#),
            souffle_tick_var: re(r"\$\$?\$?([A-Za-z_]\w*)"),
            souffle_named_group: re(r"\(\?P?<([A-Za-z_]\w*)>"),
            simplify_generated: re(r"^(alt|stop|option|set)_\d+$"),
            simplify_meaningless: re(r"^[a-z]{1,2}_?\d+$"),
            simplify_prot: re(r#""(?:[^"\\]|\\.)*"|(`+)[\s\S]*?(?<!`)\1(?!`)"#),
            simplify_cap: re(r"(?<![\w@])\$*[A-Z][A-Z0-9_]*\b"),
            simplify_var: re(r"(?<![\w@$])([a-z][a-z]*\d+|[a-z])\b(?!\s*\()"),
            simplify_tick_mv: re(r"\$+[A-Z_]"),
            simplify_call: re(r"(?<![\w.@$])([a-z_]\w*)\("),
            simplify_bare_rel: re(r"(?<![\w.@$])([a-z]\w*_\d+|[a-z]{1,2}\d+)\b(?!\s*\()"),
            simplify_bare_name: re(r"(?<![\w.@$])([a-z]\w*)\b(?!\s*\()"),
            simplify_node_atom: re(r"^node\(_, ([a-z]\w*), _, _, _\)$"),
            fold_template_call: re(r"(?<![\w.@$])([a-z_]\w*)\(([^()]*)\)"),
            fold_named: re(r"\(\?P?<(?![=!])"),
            fold_bare: re(r"(?<![\w.@$])([a-z_]\w*)\b(?!\s*\()"),
            fold_word: re(r"(?<![\w.@$])([a-z_]\w*)\b"),
            fold_piece: re("(\u{0}S\u{0}|\u{0}R\u{0}\\(([^()]*)\\))"),
            share_top_call: re(r"(?<![\w.!])([a-z_]\w*)\("),
            share_agg_body: re(r"\{[^{}]*\}"),
            share_lower_var: re(r#"(?<![\w$@"])([a-z][a-z0-9_]*)\b(?!\s*\()"#),
            demand_agg: re(r"(?s)^(?:[A-Za-z]\w* = )?(?:count|sum|min|max|mean)(?: [^:{]*)? : \{(.*)\}(.*)$"),
            demand_positive: re(r"(?s)^[a-z_]\w*\(.*\)$"),
            demand_eq: re(r#"(?s)^[A-Za-z]\w* = [A-Za-z_]\w*$|^[a-z]\w* ~ (`+).*\1( at "[^"]*")?$"#),
            demand_ancestor: re(r"^(?:within_stop|within)\(([a-z]\w*), ([a-z]\w*)(?:, [^()]*)?\)$"),
            demand_unary: re(r"^([a-z_]\w*)\(([a-z]\w*)\)$"),
            demand_fan: re(r#"(?<![\w.])(?:within|within_stop)\((?!n\b)\w+, \w+|(?<![\w.])precedes(?:_stop)?\(n, "#),
            demand_up: re(r"^(?:within|within_stop|inside)\(n, "),
            demand_empty_neg: re(r"(,\s*)?!\w+_u0_empty\([^()]*\)(\s*,)?"),
            translate_viol_head: re(r#"^\.violation (\w+)\((.*?)\)( code "(?:[^"\\]|\\.)*")? ("(?:[^"\\]|\\.)*")$"#),
            translate_from_clause: re(r"from clause `([^`]*)`"),
            translate_no_match_group: re(r#"!\s*match\("(?:[^"\\]|\\.)*""#),
            engine_dialect_anchor: re(r"(?m)^\.violation (\w+)\(([^)]*)\)(.*)\n    anchor (\w+)\n"),
            engine_dialect_lit: re(r#""(?:[^"\\]|\\.)*"|`[^`]*`|//[^\n]*|(?m:^\.\w+)"#),
            engine_dialect_decl: re(r"(?m)^\.decl (\w+)\("),
            engine_dialect_not_lower_digit: re(r"[^a-z0-9]+"),
            engine_dialect_message: re(r#"(?m)^\.violation (\w+)\(([^)]*)\)((?: code "(?:[^"\\]|\\.)*")? )("(?:[^"\\]|\\.)*")"#),
            engine_dialect_brace: re(r"\{([^{}]*)\}|([{}])"),
            engine_dialect_options: re(r"(?m)^\.violation (\w+)\(([^)]*)\)[^\n]*\n((?:    [^\n]*\n)*?)    options (\{[^\n]*\})\n"),
            engine_dialect_lone_any: re(r"(?<![\w$])([a-z][a-z0-9_]*) ~ `\$_`"),
            engine_dialect_lone_mv: re(r"(?<![\w$])([a-z][a-z0-9_]*) ~ `\$([A-Z][A-Z0-9_]*)`"),
            engine_dialect_text_use: re(r"(?<![\w$])text\((\w+), (\w+)\)"),
            engine_dialect_rule: re(r"(?ms)^[A-Za-z_]\w*\([^\n]*?\) :-.*?\.(?=\s*$)"),
            engine_dialect_host_reads: re(r"(?m)^// Guest captures a host rule reads, by text \(another document\): (.*)$"),
            engine_dialect_head_start: re(r"(?m)^([A-Za-z_]\w*)\("),
            engine_dialect_strings: re(r#""(?:[^"\\]|\\.)*""#),
            engine_dialect_pair: re(r"(?<![\w$])([a-z]\w*) = ([A-Z][A-Z0-9_]*), \1 = ([A-Z][A-Z0-9_]*)(?!\w)"),
            engine_dialect_unbound_test: re(r"count : \{ text\(([A-Z][A-Z0-9_]*), (\w+)\), text\(\1, \2\) \} = 0"),
            engine_dialect_agg_open: re(r"(?:count|sum|min|max|mean|join)(?: \w+)? : \{"),
            engine_dialect_stop_axis: re(r"(?<![\w$])(within_stop|precedes_stop)\((\w+), (\w+), ([a-z]\w*)\)"),
        }
    }
}

impl Default for Patterns {
    fn default() -> Self {
        Self::new()
    }
}
