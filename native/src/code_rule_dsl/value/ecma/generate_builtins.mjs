// Writes builtins.rs: the allowlists @eslint-community/eslint-utils' getStaticValue folds calls and getters through
// (`builtinNames`, `callAllowed`, `callPassThrough` and `getterAllowed` in its index.mjs), each function named by
// every path from a builtin global that reaches it (`parseFloat` and `Number.parseFloat` are one function), and the
// numeric data properties of `Math` and `Number` that its member access reads. The lists are evaluated from the
// package's own source text, so they are what that version folds on the Node.js running this. Run offline, not in CI:
//   node generate_builtins.mjs <node_modules with @eslint-community/eslint-utils@4.10.1>
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";

const modules = resolve(process.argv[2]);
const require = createRequire(join(modules, "noop.js"));
const utils = join(modules, "@eslint-community/eslint-utils");
const { version } = require(join(utils, "package.json"));
const source = readFileSync(join(utils, "index.mjs"), "utf8");

// The initializer of `const <name> = ...;` at the top level of the module.
function initializer(name) {
  const start = source.indexOf(`const ${name} =`);
  if (start < 0) throw new Error(`no ${name}`);
  const end = source.indexOf(";\n", start);
  return source.slice(start + `const ${name} =`.length, end);
}
const evaluate = name => new Function(`return (${initializer(name)});`)();

const builtinNames = [...evaluate("builtinNames")].sort();
const callAllowed = evaluate("callAllowed");
const callPassThrough = evaluate("callPassThrough");
const getterAllowed = evaluate("getterAllowed");

// Every `G`, `G.p` and `G.prototype.p` (G a builtin global) whose value is `fn`.
function paths(fn) {
  const found = [];
  for (const name of builtinNames) {
    const value = globalThis[name];
    if (value === fn) found.push(name);
    if ((typeof value !== "object" && typeof value !== "function") || value === null) continue;
    for (const key of Object.getOwnPropertyNames(value)) {
      const descriptor = Object.getOwnPropertyDescriptor(value, key);
      if (descriptor && "value" in descriptor && descriptor.value === fn) found.push(`${name}.${key}`);
    }
    const prototype = typeof value === "function" ? value.prototype : undefined;
    if (prototype === undefined || prototype === null) continue;
    for (const key of Object.getOwnPropertyNames(prototype)) {
      const descriptor = Object.getOwnPropertyDescriptor(prototype, key);
      if (descriptor && "value" in descriptor && descriptor.value === fn) found.push(`${name}.prototype.${key}`);
    }
  }
  if (found.length === 0) throw new Error(`no path to ${fn.name}`);
  return found;
}
const names = set => [...new Set([...set].flatMap(paths))].sort();

const getters = getterAllowed
  .flatMap(([classFn, allowed]) => {
    const [name] = paths(classFn).filter(path => !path.includes("."));
    return [...allowed].map(key => `${name}.prototype.${key}`);
  })
  .sort();

const constants = [];
for (const name of ["Math", "Number"]) {
  for (const key of Object.getOwnPropertyNames(globalThis[name]).sort()) {
    const descriptor = Object.getOwnPropertyDescriptor(globalThis[name], key);
    if (!descriptor || !("value" in descriptor) || typeof descriptor.value !== "number") continue;
    const value = descriptor.value;
    const literal = Number.isNaN(value)
      ? "f64::NAN"
      : value === Infinity
        ? "f64::INFINITY"
        : value === -Infinity
          ? "f64::NEG_INFINITY"
          : String(value).includes(".") || String(value).includes("e")
            ? String(value)
            : `${String(value)}.0`;
    constants.push([`${name}.${key}`, literal]);
  }
}

const list = (items, indent = "    ") => items.map(item => `${indent}"${item}",`).join("\n");
writeFileSync(
  join(import.meta.dirname, "builtins.rs"),
  `//! What @eslint-community/eslint-utils ${version}'s \`getStaticValue\` folds calls and getters through: its
//! \`builtinNames\`, \`callAllowed\`, \`callPassThrough\` and \`getterAllowed\`, each function under every path
//! from a builtin global that reaches it, sorted; and the numeric data properties of \`Math\` and \`Number\` its member
//! access reads. Generated by \`generate_builtins.mjs\` from the package's \`index.mjs\` on Node.js ${process.versions.node};
//! do not edit.

// The constants are Node.js's own values, spelled as it prints them.
#![allow(clippy::approx_constant)]

/// Globals whose value \`getStaticValue\` reads where no file-local binding shadows them.
pub(crate) const BUILTIN_NAMES: &[&str] = &[
${list(builtinNames)}
];

/// Functions whose calls fold.
pub(crate) const CALL_ALLOWED: &[&str] = &[
${list(names(callAllowed))}
];

/// Functions whose calls are their first argument.
pub(crate) const CALL_PASS_THROUGH: &[&str] = &[
${list(names(callPassThrough))}
];

/// Accessors whose reads fold.
pub(crate) const GETTER_ALLOWED: &[&str] = &[
${list(getters)}
];

/// Numeric data properties of \`Math\` and \`Number\`.
pub(crate) const CONSTANTS: &[(&str, f64)] = &[
${constants.map(([name, literal]) => `    ("${name}", ${literal}),`).join("\n")}
];
`,
);
console.log(builtinNames.length, names(callAllowed).length, names(callPassThrough).length, getters.length, constants.length);
