<?php
// Writes by_reference.rs: every internal function of PHP 8.5.11 (`php -n`, the extensions it loads
// listed in the output) that takes a parameter by reference, lowercased, with its parameters'
// names in order (a named argument is matched to its parameter by them) and the 0-based positions
// of those it takes by reference; a variadic by-reference parameter is `-1 - position` (it and
// every later argument). It refuses to run unless PHP's version and loaded extensions are
// ../data/php_runtime.json's, the runtime php_builtins.json is generated with: a function this
// table lacks reads as taking nothing by reference, so the two must list the same functions. Run
// offline, not in CI, from this directory:
//   /opt/homebrew/Cellar/php/8.5.11/bin/php -n generate_by_reference.php

declare(strict_types=1);

$runtime = json_decode(
    (string) file_get_contents(__DIR__ . '/../data/php_runtime.json'),
    true,
    flags: JSON_THROW_ON_ERROR,
);
if (php_ini_loaded_file() !== false) {
    throw new RuntimeException('run with php -n: an ini file may load more extensions');
}
if (PHP_VERSION !== $runtime['php']) {
    throw new RuntimeException("PHP {$runtime['php']} required, not " . PHP_VERSION);
}
$extensions = get_loaded_extensions();
sort($extensions, SORT_STRING);
if ($extensions !== $runtime['extensions']) {
    throw new RuntimeException(sprintf(
        'loaded extensions differ from php_runtime.json: missing [%s], extra [%s]',
        implode(', ', array_diff($runtime['extensions'], $extensions)),
        implode(', ', array_diff($extensions, $runtime['extensions'])),
    ));
}

$functions = [];
foreach (get_defined_functions()['internal'] as $name) {
    $parameters = [];
    $positions = [];
    foreach ((new ReflectionFunction($name))->getParameters() as $parameter) {
        $parameters[] = $parameter->getName();
        if ($parameter->isPassedByReference()) {
            $positions[] = $parameter->isVariadic() ? -1 - $parameter->getPosition() : $parameter->getPosition();
        }
    }
    if ($positions) {
        $functions[strtolower($name)] = [$parameters, $positions];
    }
}
ksort($functions, SORT_STRING);
$quote = static fn (string $text): string => '"' . str_replace(['\\', '"'], ['\\\\', '\\"'], $text) . '"';
$out = "// @generated by generate_by_reference.php with PHP " . PHP_VERSION . " (php -n; extensions: "
    . implode(', ', $extensions) . "). Do not edit.\n\n"
    . "/// PHP's internal functions that take a parameter by reference, lowercased and sorted, with\n"
    . "/// their parameters' names in order and the 0-based positions of those taken by reference;\n"
    . "/// `-1 - p` is a variadic one at `p`.\n"
    . "#[rustfmt::skip]\n"
    . "pub(super) const BY_REFERENCE: &[(&str, &[&str], &[i8])] = &[\n";
foreach ($functions as $name => [$parameters, $positions]) {
    $out .= "    (" . $quote($name) . ", &[" . implode(', ', array_map($quote, $parameters)) . "], &["
        . implode(', ', $positions) . "]),\n";
}
$out .= "];\n";
file_put_contents(__DIR__ . '/by_reference.rs', $out);
