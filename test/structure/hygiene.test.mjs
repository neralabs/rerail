// Structure gate, hygiene metrics (#19-#21, #25): each predicate on a tiny in-memory tree.

import { describe, expect, it } from "vitest";
import { memoryRepo } from "../../scripts/check/check-structure/repo.mjs";
import { check as binariesLfs } from "../../scripts/check/check-structure/metrics/19-binaries-lfs.mjs";
import { check as generatedMarked } from "../../scripts/check/check-structure/metrics/20-generated-marked.mjs";
import { check as readmes } from "../../scripts/check/check-structure/metrics/21-top-level-readmes.mjs";
import { check as manifest } from "../../scripts/check/check-structure/metrics/25-generated-manifest.mjs";

const paths = (result) => result.findings.map((item) => item.path);
const binary = (size) => Buffer.concat([Buffer.from([0]), Buffer.alloc(size - 1, 1)]);
const MARK = ["Generated", "by"].join(" ");

describe("#19 large binaries in LFS", () => {
  it("flags binaries over 100 KB that no filter=lfs pattern covers; text and small files pass", () => {
    const result = binariesLfs(
      memoryRepo({
        ".gitattributes": "*.safetensors filter=lfs diff=lfs merge=lfs -text\nnative/**/names.bin filter=lfs\n",
        "model/model.safetensors": binary(200 * 1024),
        "native/src/value/names/names.bin": binary(200 * 1024),
        "native/src/value/other.bin": binary(200 * 1024),
        "fixtures/big.expected.json": "x".repeat(300 * 1024),
        "model/small.bin": binary(1024),
      }),
    );
    expect(paths(result)).toEqual(["native/src/value/other.bin"]);
  });

  it("lets a later line unset LFS for a path", () => {
    const result = binariesLfs(
      memoryRepo({
        ".gitattributes": "*.bin filter=lfs\nkeep/*.bin -filter\n",
        "keep/a.bin": binary(150 * 1024),
        "other/b.bin": binary(150 * 1024),
      }),
    );
    expect(paths(result)).toEqual(["keep/a.bin"]);
  });
});

describe("#20 generated files marked", () => {
  const header = (generator) => `// ${MARK} ${generator}; do not edit.\n`;

  it("requires the header on *.generated.* files and a name or manifest row for header-marked files", () => {
    const result = generatedMarked(
      memoryRepo({
        "scripts/generate/value/builtins.mjs": "",
        "scripts/generate/README.md": "| Generated | Generator |\n|---|---|\n| `native/src/names.rs` | `scripts/generate/value/builtins.mjs` |\n",
        "native/src/builtins.generated.rs": header("scripts/generate/value/builtins.mjs"),
        "native/src/names.rs": header("scripts/generate/value/builtins.mjs"),
        "native/src/entities.rs": header("scripts/generate/value/builtins.mjs"),
        "src/brand.generated.ts": "export const x = 1;\n",
        "src/registry.generated.ts": header("scripts/generate/missing.ts"),
        "native/src/data/globals.generated.json": "{}",
      }),
    );
    expect(result.findings.map((item) => `${item.path}: ${item.message.split(",")[0].split(";")[0]}`)).toEqual([
      "native/src/entities.rs: generated (header marker) but neither named *.generated.* nor listed in scripts/generate/README.md",
      "src/brand.generated.ts: missing `Generated by <generator path>",
      "src/registry.generated.ts: header names scripts/generate/missing.ts",
    ]);
  });

  it("does not treat lockfiles or recordings as generated sources", () => {
    const result = generatedMarked(
      memoryRepo({
        "Cargo.lock": "# This file is automatically @generated by Cargo.\n",
        "packs/php/upstream/psalm/composer.lock": '{"_readme": ["This file is @generated automatically"]}',
        "fixtures/php/scope/a.expected.json": `{"note": "${MARK} generate.py"}`,
      }),
    );
    expect(result).toEqual({ actual: "100% (0/0)", findings: [] });
  });

  it("asks no header of a binary-format generated file, whether its bytes or its LFS pointer are checked out", () => {
    const pointer = "version https://git-lfs.github.com/spec/v1\noid sha256:00\nsize 1626241\n";
    const result = generatedMarked(
      memoryRepo({
        "native/grammars/sql/src/parser.generated.c.gz": pointer,
        "native/grammars/rust/src/parser.generated.c.gz": binary(1024),
        "native/src/pointer.generated.rs": pointer,
      }),
    );
    expect(paths(result)).toEqual(["native/src/pointer.generated.rs"]);
  });
});

describe("#21 top-level READMEs", () => {
  it("flags top-level dirs without README.md, except dot-dirs and LICENSES/", () => {
    const result = readmes(
      memoryRepo({
        "fixtures/README.md": "",
        "fixtures/php/a.json": "",
        "src/index.ts": "",
        ".github/workflows/ci.yml": "",
        "LICENSES/MIT.txt": "",
        "README.md": "",
      }),
    );
    expect(paths(result)).toEqual(["src/README.md"]);
  });
});

describe("#25 generated-file manifest", () => {
  const table = (rows) =>
    ["| Generated file | Generator | Command |", "|---|---|---|", ...rows.map(([a, b]) => `| \`${a}\` | \`${b}\` | npm run x |`)].join("\n");

  it("requires a manifest once *.generated.* files exist", () => {
    expect(paths(manifest(memoryRepo({ "src/a.generated.ts": "" })))).toEqual(["scripts/generate/README.md", "src/a.generated.ts"]);
  });

  it("checks rows both ways: listed files and generators exist, generated files are listed", () => {
    const result = manifest(
      memoryRepo({
        "scripts/generate/README.md": table([
          ["src/a.generated.ts", "scripts/generate/a.ts"],
          ["src/gone.generated.ts", "scripts/generate/a.ts"],
          ["docs/reference.html", "scripts/generate/missing.mjs"],
          ["packs/node/rules/", "scripts/generate/packs/node_policies.py"],
        ]),
        "scripts/generate/a.ts": "",
        "scripts/generate/packs/node_policies.py": "",
        "src/a.generated.ts": "",
        "src/b.generated.ts": "",
        "docs/reference.html": "",
        "packs/node/rules/x.generated.json": "{}",
      }),
    );
    expect(result.findings.map((item) => `${item.path}${item.line ? `:${item.line}` : ""}: ${item.message}`)).toEqual([
      "scripts/generate/README.md:4: row's generated path src/gone.generated.ts is not tracked",
      "scripts/generate/README.md:5: row's generator scripts/generate/missing.mjs is not tracked",
      "src/b.generated.ts: not listed in scripts/generate/README.md",
    ]);
  });

  it("flags a header that names a different generator than the manifest", () => {
    const result = manifest(
      memoryRepo({
        "scripts/generate/README.md": table([["src/a.generated.ts", "scripts/generate/a.ts"]]),
        "scripts/generate/a.ts": "",
        "scripts/generate/b.ts": "",
        "src/a.generated.ts": `// ${MARK} scripts/generate/b.ts; do not edit.\n`,
      }),
    );
    expect(result.findings).toEqual([
      { path: "src/a.generated.ts", message: "header names scripts/generate/b.ts; scripts/generate/README.md names scripts/generate/a.ts" },
    ]);
  });
});
