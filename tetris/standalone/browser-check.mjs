import assert from 'node:assert/strict';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const source = resolve(process.env.RERAIL_SOURCE ?? fileURLToPath(new URL('../../../wolfeel', import.meta.url)));
const { chromium } = await import(pathToFileURL(resolve(source, 'node_modules/@playwright/test/index.mjs')));
const baseURL = process.env.TETRIS_STANDALONE_URL ?? 'http://127.0.0.1:4320';
const browser = await chromium.launch({ headless: true });

async function exercise(page, label) {
  const text = name => page.locator(`[data-text="${name}"]`).first();
  await page.waitForFunction(() => document.querySelectorAll('#board .cell').length === 200, { timeout: 30000 });
  assert.equal(await page.locator('#preview .cell').count(), 16);
  assert.equal(await text('title').textContent(), 'FALLING FACTS');
  await page.locator('#manual-mode').click();
  await page.waitForFunction(() => document.body.dataset.timeMode === 'manual');
  await page.keyboard.press('r');
  await page.waitForFunction(() => document.querySelector('[data-text="clock"]').textContent === '0');
  await page.locator('#time-step').click();
  await page.waitForFunction(() => document.querySelector('[data-text="clock"]').textContent === '100');
  await page.waitForTimeout(200);
  assert.equal(await text('clock').textContent(), '100', 'manual mode must remain still');
  await page.locator('#inspect').click();
  assert.match(await page.locator('#trace').textContent(), /clock\(100\)/);
  await page.keyboard.press('ArrowLeft');
  await page.waitForFunction(() => document.querySelectorAll('#board .fact-changed').length > 0);
  await page.keyboard.press('ArrowUp');
  await page.keyboard.press('Space');
  await page.waitForFunction(() => document.querySelector('[data-text="pieces"]').textContent === '1');
  assert.ok(Number(await text('score').textContent()) > 0);

  await page.locator('#watch-engine').click();
  await page.waitForFunction(() => document.querySelectorAll('.fact-node').length > 30);
  if ((await page.locator('#wave-play').textContent()).includes('Pause')) await page.locator('#wave-play').click();
  await page.locator('#wave-position').evaluate(input => { input.value = 0; input.dispatchEvent(new Event('input', { bubbles: true })); });
  assert.equal(await page.locator('.fact-node[data-relation="screen_cell"] .svg-screen-cell').count(), 216, 'initial facts must be populated');
  await page.locator('.graph-time-steps [data-key="KeyN"]').click();
  await page.waitForFunction(() => document.querySelector('[data-text="clock"]').textContent === '100');
  await page.waitForFunction(() => document.querySelectorAll('#round-history option').length >= 2);
  if ((await page.locator('#wave-play').textContent()).includes('Pause')) await page.locator('#wave-play').click();
  assert.ok(await page.locator('#wave-markers .wave-band').count() > 0);
  assert.ok(await page.locator('.rule-edge').count() > 50);
  const edge = page.locator('.edge-hit').first();
  await edge.dispatchEvent('click');
  assert.match(await page.locator('#source-caption').textContent(), /Pinned rule/);
  assert.ok(await page.locator('#rule-source .selected-source-line').count() > 0);
  await page.locator('#browse-current-source').click();
  await page.waitForFunction(() => document.querySelectorAll('#source-browser-code .source-line').length > 200);
  assert.ok(parseInt(await page.locator('#source-browser-file-count').textContent()) > 100);
  assert.ok(await page.locator('#source-browser-code .syntax-relation').count() > 0);
  await page.locator('#source-file-filter').fill('core.rr');
  await page.locator('.source-file[data-path="docs/rule-syntax/lib/core.rr"]').click();
  await page.waitForFunction(() => document.getElementById('source-browser-path').textContent.endsWith('/core.rr'));
  await page.locator('#close-source-browser').click();
  await page.locator('#close-evaluation').click();
  await page.waitForFunction(() => document.getElementById('evaluation-panel').hidden);
  await page.locator('#inspect').click();
  assert.equal(await page.locator('#board .fact-changed').count(), 0);

  await page.locator('#realtime-mode').click();
  await page.waitForFunction(() => document.body.dataset.timeMode === 'realtime');
  await page.locator('#watch-engine').click();
  await page.waitForFunction(() => document.getElementById('evaluation-panel').dataset.playback === 'live');
  const round = Number(await page.locator('#evaluation-panel').getAttribute('data-round'));
  await page.waitForFunction(round => Number(document.getElementById('evaluation-panel').dataset.round) > round + 2, round);
  assert.equal(await page.evaluate(() => document.body.dataset.timeMode), 'realtime');
  assert.ok(await page.locator('#wave-position').evaluate(input => input.value === input.max));
  await page.locator('#wave-play').click();
  const held = await page.locator('#evaluation-panel').getAttribute('data-round');
  await page.waitForTimeout(250);
  assert.equal(await page.locator('#evaluation-panel').getAttribute('data-round'), held);
  await page.locator('#follow-latest').click();
  await page.waitForFunction(held => Number(document.getElementById('evaluation-panel').dataset.round) > Number(held), held);
  await page.locator('#close-evaluation').click();
  await page.waitForFunction(() => document.getElementById('evaluation-panel').hidden);
  assert.equal(await page.locator('#board .fact-changed').count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  console.log(`${label}: WASM gameplay, manual steps, facts, waves, source browsing, live following, mobile passed.`);
}
try {
  const context = await browser.newContext({ viewport: { width: 1560, height: 1150 } });
  const requests = [], errors = [];
  context.on('request', request => requests.push({ url: request.url(), method: request.method() }));
  context.on('page', page => page.on('pageerror', error => errors.push(error.message)));
  const page = await context.newPage();
  await page.goto(baseURL + '/');
  await exercise(page, 'Static folder');
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  await context.setOffline(true);
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('#board .cell').length === 200);
  await page.locator('#manual-mode').click();
  await page.waitForFunction(() => document.body.dataset.timeMode === 'manual');
  await page.locator('#time-step').click();
  await page.waitForFunction(() => document.querySelector('[data-text="clock"]').textContent === '100');
  assert.ok(requests.every(request => request.method === 'GET'), 'no game/backend POST requests');
  assert.ok(requests.every(request => !/\/(facts|trace|sources)(\?|$)/.test(request.url)), 'no backend endpoints');
  assert.ok(requests.every(request => request.url.startsWith(baseURL)), 'all dependencies must be local');
  assert.deepEqual(errors, []);
  console.log('Static folder: offline reload and play passed; zero backend requests.');
  await context.close();

  const local = await browser.newContext({ viewport: { width: 1560, height: 1150 }, offline: true });
  const fileErrors = [], network = [];
  local.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
  const filePage = await local.newPage();
  filePage.on('pageerror', error => fileErrors.push(error.message));
  await filePage.goto(pathToFileURL(fileURLToPath(new URL('./falling-facts.html', import.meta.url))).href);
  await exercise(filePage, 'Single HTML (file://, offline)');
  assert.deepEqual(network, []);
  assert.deepEqual(fileErrors, []);
  console.log('Single HTML: zero network requests; everything, including the engine and sources, is embedded.');
  await local.close();
} finally { await browser.close(); }
