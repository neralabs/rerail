"""Writes pure-lazy-runtime-purity.tables.rr, the linter's name sets and signatures.
    python3 docs/rule-syntax/data-layer/gen-pure-lazy-runtime-purity.py [--check]
The source is scripts/lint_pure_lazy_runtime_purity.py at the pinned commit of the data-layer repository. Each
named set at module level, and each str set written inline in a function (INLINE), becomes plp_name("<SET>", x)
rows (RUNTIME_SINK_KEYWORDS is a union there, and is computed the same way here);
TRANSPARENT_SCHEMA_CALLBACK_REGISTRY_ACCESSES becomes plp_registry_access rows; the two signatures written in the
linter become signing.rr allow_sig rows.
--check regenerates the text and fails if the committed file differs."""
import ast, json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = "/Users/jeremy/orca/workspaces/nera-data-layer-ner1131-base-audit"
COMMIT = "2b1504adc4291daaf080b2e932962b134da1a69a"
LINTER = "scripts/lint_pure_lazy_runtime_purity.py"
OUT = os.path.join(HERE, "pure-lazy-runtime-purity.tables.rr")
SETS = ["PROTECTED_RUNTIME_ATTRS", "PURE_SURFACE_CARRIER_ATTRS", "RUNTIME_HANDLE_TYPE_NAMES", "IMMUTABLE_GLOBAL_CALLS",
        "TYPE_ONLY_GLOBAL_CALLS", "MANAGED_MEMOIZATION_CACHE_CONSTRUCTORS", "MANAGED_MEMOIZATION_CACHE_ACCESSES",
        "MUTATING_METHOD_NAMES", "RUNTIME_SINK_KEYWORDS", "OPAQUE_LAZY_OPERATION_PAYLOAD_FIELDS",
        "OPAQUE_PURE_LAZY_HELPER_CALLS", "PURE_SURFACE_HELPER_CALLS", "LEGACY_DECORATOR_NAMES",
        "RUNTIME_OWNER_PARAM_NAMES", "PLAN_HELPER_TERMINAL_NAMES", "PURE_SOURCE_TRIGGERS", "PURE_DECORATOR_NAMES",
        "STRICT_OWNER_VIOLATION_CODES"]
# The sets written inline in a function: (function, n-th str set in source order) -> the name used here.
INLINE = {("_annotation_mentions_name", 0): "type_subscripts", ("_lazy_wrapper_call", 0): "lazy_wrapper_roots",
          ("_lazy_wrapper_call", 1): "lazy_wrapper_methods", ("_is_immutable_global_expr", 0): "opaque_immutable_calls",
          ("_call_is_regex_compile", 0): "regex_modules",
          ("_call_is_managed_memoization_cache", 0): "local_metadata_caches",
          ("_PureFunctionAnalyzer", 0): "queue_methods", ("_shared_fact_file_has_pure_trigger", 0): "file_triggers",
          ("_shared_fact_file_has_global_state_factory_trigger", 0): "global_state_factories",
          ("_call_targets", 0): "receiver_names"}


def source():
    return subprocess.run(["git", "-C", REPO, "show", f"{COMMIT}:{LINTER}"], check=True, capture_output=True,
                          text=True).stdout


def literals():
    tree = ast.parse(source())
    out = {}
    for fn in tree.body:
        if not isinstance(fn, (ast.FunctionDef, ast.ClassDef)):
            continue
        sets = sorted((n for n in ast.walk(fn) if isinstance(n, ast.Set)
                       and all(isinstance(e, ast.Constant) and isinstance(e.value, str) for e in n.elts)),
                      key=lambda n: (n.lineno, n.col_offset))
        for i, node in enumerate(sets):
            if (fn.name, i) in INLINE:
                out[INLINE[fn.name, i]] = {e.value for e in node.elts}
    for st in tree.body:
        if isinstance(st, (ast.Assign, ast.AnnAssign)):
            t = st.targets[0] if isinstance(st, ast.Assign) else st.target
            if not isinstance(t, ast.Name) or st.value is None:
                continue
            v = st.value
            if isinstance(v, ast.BinOp) and isinstance(v.op, ast.BitOr):   # A | frozenset({...})
                out[t.id] = set(out[v.left.id]) | set(ast.literal_eval(v.right.args[0]))
                continue
            if isinstance(v, ast.Call) and v.args:
                v = v.args[0]
            try:
                out[t.id] = ast.literal_eval(v)
            except ValueError:
                pass
    return out


def text():
    lit = literals()
    rows = [f"// Generated by gen-pure-lazy-runtime-purity.py from {LINTER} at {COMMIT[:9]}. Do not edit.",
            "// plp_name(set, x): x is in the linter's name set of that name.",
            ".decl plp_name(set: symbol, x: symbol)"]
    for name in SETS + sorted(INLINE.values()):
        xs = [f"plp_name({json.dumps(name)}, {json.dumps(x)})." for x in sorted(lit[name])]
        rows += [" ".join(xs[i:i + 3]) for i in range(0, len(xs), 3)]
    rows.append("// plp_registry_access(path, global, access): TRANSPARENT_SCHEMA_CALLBACK_REGISTRY_ACCESSES.")
    rows.append(".decl plp_registry_access(path: symbol, g: symbol, access: symbol)")
    for p, g, a in sorted(lit["TRANSPARENT_SCHEMA_CALLBACK_REGISTRY_ACCESSES"]):
        rows.append(f"plp_registry_access({json.dumps(p)}, {json.dumps(g)}, {json.dumps(a)}).")
    rows.append("// The signatures written in the linter, checked by lib/data-layer/signing.rr.")
    rows.append(f"allow_sig(\"plp\", \"lint_pure_lazy_runtime_purity\", {json.dumps(lit['ALLOWLIST_SIGNATURE'])}).")
    rows.append(f"allow_sig(\"plp_ceiling\", \"lint_pure_lazy_runtime_purity:burn_down_ceiling\", "
                f"{json.dumps(lit['BURN_DOWN_CEILING_SIGNATURE'])}).")
    return "\n".join(rows) + "\n"


def main():
    t = text()
    if "--check" in sys.argv:
        if open(OUT).read() != t:
            sys.exit(f"{OUT} differs from {LINTER} at {COMMIT[:9]}: rerun without --check")
        print("ok")
    else:
        open(OUT, "w").write(t)


if __name__ == "__main__":
    main()
