"""Writes bootstrap-engine-invariants.tables.rr, the linter's name sets as bei_set(SET, name) rows.
    python3 docs/rule-syntax/data-layer/gen-bootstrap-engine-invariants.py [--check]
The source is scripts/lint_bootstrap_engine_invariants.py at the pinned commit of the data-layer repository. Every
module-level frozenset of strings becomes rows under its own name; `*OTHER` inside a set is expanded. --check
regenerates the text and fails if the committed file differs."""
import ast, json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = "/Users/jeremy/orca/workspaces/nera-data-layer-ner1131-base-audit"
COMMIT = "2b1504adc4291daaf080b2e932962b134da1a69a"
LINTER = "scripts/lint_bootstrap_engine_invariants.py"
OUT = os.path.join(HERE, "bootstrap-engine-invariants.tables.rr")


def sets():
    src = subprocess.run(["git", "-C", REPO, "show", f"{COMMIT}:{LINTER}"], check=True, capture_output=True,
                         text=True).stdout
    out = {}
    for st in ast.parse(src).body:
        if not (isinstance(st, ast.Assign) and isinstance(st.targets[0], ast.Name)):
            continue
        v = st.value
        if not (isinstance(v, ast.Call) and getattr(v.func, "id", "") == "frozenset" and v.args
                and isinstance(v.args[0], ast.Set)):
            continue
        xs = set()
        for e in v.args[0].elts:
            if isinstance(e, ast.Starred):
                xs |= out[e.value.id]
            else:
                xs.add(ast.literal_eval(e))
        if all(isinstance(x, str) for x in xs):
            out[st.targets[0].id] = xs
    return out


def text():
    rows = [f"// Generated by gen-bootstrap-engine-invariants.py from {LINTER} at {COMMIT[:9]}. Do not edit.",
            "// bei_set(s, x): x is in the linter's module-level frozenset s.",
            ".decl bei_set(s: symbol, x: symbol)"]
    for name, xs in sets().items():
        rows.append(f"// {name}")
        rows += [f"bei_set({json.dumps(name)}, {json.dumps(x)})." for x in sorted(xs)]
    return "\n".join(rows) + "\n"


def main():
    t = text()
    if "--check" in sys.argv:
        if open(OUT).read() != t:
            sys.exit(f"{OUT} differs from {LINTER} at {COMMIT[:9]}: rerun without --check")
        print("ok")
    else:
        open(OUT, "w").write(t)


if __name__ == "__main__":
    main()
