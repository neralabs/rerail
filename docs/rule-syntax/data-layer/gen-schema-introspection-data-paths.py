"""Writes schema-introspection-data-paths.tables.rr, the linter's name, path and marker tables.
    python3 docs/rule-syntax/data-layer/gen-schema-introspection-data-paths.py [--check]
The source is scripts/lint_schema_introspection_data_paths.py at the pinned commit of the data-layer repository.
Each table is read from the module-level literal of the same name. --check regenerates the text and fails if the
committed file differs, and checks the .scope include lines of the rule against DATA_PATH_PREFIXES."""
import ast, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = "/Users/jeremy/orca/workspaces/nera-data-layer-ner1131-base-audit"
COMMIT = "2b1504adc4291daaf080b2e932962b134da1a69a"
LINTER = "scripts/lint_schema_introspection_data_paths.py"
OUT = os.path.join(HERE, "schema-introspection-data-paths.tables.rr")
RULE = os.path.join(HERE, "schema-introspection-data-paths.rr")
# linter literal -> (relation, comment)
SETS = [
    ("FORBIDDEN_CALL_NAMES", "sidp_probe", "callee names that introspect the live schema"),
    ("FORBIDDEN_SQL_TEXT", "sidp_sql", "SQL text that introspects it, matched case-insensitively"),
    ("SCHEMA_AUTHORITY_NAME_MARKERS", "sidp_authority", "words in a def name that make it schema authority"),
    ("ALLOWED_PATH_MARKERS", "sidp_path_marker", "text in \"/\" + path that takes a file out of the data path"),
]


def literals():
    src = subprocess.run(["git", "-C", REPO, "show", f"{COMMIT}:{LINTER}"], check=True, capture_output=True,
                         text=True).stdout
    out = {}
    for st in ast.parse(src).body:
        if isinstance(st, (ast.Assign, ast.AnnAssign)):
            t = st.targets[0] if isinstance(st, ast.Assign) else st.target
            v = st.value
            if isinstance(v, ast.Call) and v.args:      # frozenset({...})
                v = v.args[0]
            if isinstance(t, ast.Name) and v is not None:
                try:
                    out[t.id] = ast.literal_eval(v)
                except ValueError:
                    pass
    return out


def text():
    lit = literals()
    rows = [f"// Generated by gen-schema-introspection-data-paths.py from {LINTER} at {COMMIT[:9]}. Do not edit."]
    for name, rel, what in SETS:
        rows.append(f"// {rel}: {name}, {what}.")
        rows.append(f".decl {rel}(x: symbol)")
        xs = [f"{rel}({json.dumps(x)})." for x in sorted(lit[name])]
        rows += [" ".join(xs[i:i + 4]) for i in range(0, len(xs), 4)]
    rows.append("// sidp_primitive(path, def, callee): PRIMITIVE_DEFINITION_CALLS, the primitives' own definitions.")
    rows.append(".decl sidp_primitive(p: symbol, f: symbol, x: symbol)")
    for e in sorted(lit["PRIMITIVE_DEFINITION_CALLS"]):
        p, f, x = e.split(":")
        rows.append(f"sidp_primitive({json.dumps(p)}, {json.dumps(f)}, {json.dumps(x)}).")
    return "\n".join(rows) + "\n"


def main():
    t = text()
    if "--check" in sys.argv:
        if open(OUT).read() != t:
            sys.exit(f"{OUT} differs from {LINTER} at {COMMIT[:9]}: rerun without --check")
        scope = set(re.findall(r'"([^"]+)/\*\*/\*\.py"', "".join(l for l in open(RULE) if l.startswith(".scope include"))))
        want = {p.rstrip("/") for p in literals()["DATA_PATH_PREFIXES"]}
        if scope != want:
            sys.exit(f"{RULE}: .scope include differs from DATA_PATH_PREFIXES: {sorted(scope ^ want)}")
        print("ok")
    else:
        open(OUT, "w").write(t)


if __name__ == "__main__":
    main()
