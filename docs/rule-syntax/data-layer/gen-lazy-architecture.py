#!/usr/bin/env python3
"""Generate data-layer/lazy-architecture.tables.rr from the linter's module-level constants.

  python3 data-layer/gen-lazy-architecture.py           write the table
  python3 data-layer/gen-lazy-architecture.py --check   exit 1 if the table differs from the linter

Every module-level constant of scripts/lint_lazy_architecture.py that is a string, or a set, frozenset or tuple of
strings (unions of other such constants and "a" + "b" concatenations included), becomes facts
`la_set("NAME", "value").`. The linter is read from git at the pinned commit; nothing is checked out or run.
"""
import ast, os, subprocess, sys

REPO = "/Users/jeremy/orca/workspaces/nera-data-layer-ner1131-base-audit"
COMMIT = "2b1504adc4291daaf080b2e932962b134da1a69a"
SCRIPT = "scripts/lint_lazy_architecture.py"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "lazy-architecture.tables.rr")


def value(node, env):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        a, b = value(node.left, env), value(node.right, env)
        return a + b if isinstance(a, str) and isinstance(b, str) else None
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
        a, b = value(node.left, env), value(node.right, env)
        return a | b if isinstance(a, frozenset) and isinstance(b, frozenset) else None
    if isinstance(node, (ast.Set, ast.Tuple, ast.List)):
        items = [value(e, env) for e in node.elts]
        return frozenset(items) if all(isinstance(i, str) for i in items) else None
    if isinstance(node, ast.Dict) and not node.keys:          # frozenset({}) is an empty dict literal
        return frozenset()
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in ("frozenset", "set"):
        return value(node.args[0], env) if node.args else frozenset()
    if isinstance(node, ast.Name):
        return env.get(node.id)
    return None


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def table():
    src = subprocess.run(["git", "-C", REPO, "show", f"{COMMIT}:{SCRIPT}"], check=True, capture_output=True,
                         text=True).stdout
    env, order = {}, []
    for stmt in ast.parse(src).body:
        if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(stmt.targets[0], ast.Name):
            name, node = stmt.targets[0].id, stmt.value
        elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name) and stmt.value is not None:
            name, node = stmt.target.id, stmt.value
        else:
            continue
        v = value(node, env)
        if v is None or name == "ALLOWLIST_SIGNATURE":
            continue
        env[name] = v
        order.append(name)
    lines = ["// Generated by data-layer/gen-lazy-architecture.py from " + SCRIPT + " at " + COMMIT[:9] + ".",
             "// Do not edit: la_set(NAME, v) for each string, and each member of each string set or tuple.",
             "// la_set is declared in lib/data-layer/lazy-analyzer.rr.", "#include \"data-layer/lazy-analyzer.rr\""]
    for name in order:
        v = env[name]
        for item in sorted([v] if isinstance(v, str) else v):
            lines.append(f'la_set("{name}", "{esc(item)}").')
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = table()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("ok" if ok else f"{OUT} differs from the linter; rerun without --check")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT}: {text.count(chr(10)) - 4} facts")
