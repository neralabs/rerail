"""Writes cached-pure-lazy-allowlist.symbols.rr, the verifier's protected runtime symbols.
    python3 docs/rule-syntax/data-layer/gen-cached-pure-lazy-allowlist.py [--check]
The source is scripts/verify_cached_pure_lazy_allowlist.py at the pinned commit of the data-layer repository: the
three frozensets PURITY_RUNTIME_SYMBOLS, POLICY_RUNTIME_SYMBOLS and OPTIMIZER_CACHE_RUNTIME_SYMBOLS, whose source
names ("purity", "policy", "optimizer_cache") are the ones cached_pure_lazy_runtime_source_hash writes. --check
regenerates the text and fails if the committed file differs."""
import ast, json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = "/Users/jeremy/orca/workspaces/nera-data-layer-ner1131-base-audit"
COMMIT = "2b1504adc4291daaf080b2e932962b134da1a69a"
SCRIPT = "scripts/verify_cached_pure_lazy_allowlist.py"
OUT = os.path.join(HERE, "cached-pure-lazy-allowlist.symbols.rr")
SETS = [("PURITY_RUNTIME_SYMBOLS", "purity"), ("POLICY_RUNTIME_SYMBOLS", "policy"),
        ("OPTIMIZER_CACHE_RUNTIME_SYMBOLS", "optimizer_cache")]


def literals():
    src = subprocess.run(["git", "-C", REPO, "show", f"{COMMIT}:{SCRIPT}"], check=True, capture_output=True,
                         text=True).stdout
    out = {}
    for st in ast.parse(src).body:
        if isinstance(st, ast.Assign) and isinstance(st.targets[0], ast.Name):
            v = st.value
            if isinstance(v, ast.Call) and v.args:      # frozenset({...})
                v = v.args[0]
            try:
                out[st.targets[0].id] = ast.literal_eval(v)
            except ValueError:
                pass
    return out


def text():
    lit = literals()
    rows = [f"// Generated by gen-cached-pure-lazy-allowlist.py from {SCRIPT} at {COMMIT[:9]}. Do not edit.",
            "// cpl_runtime_symbol(source, name): a top-level name of the runtime the policy's runtime hash covers.",
            ".decl cpl_runtime_symbol(source: symbol, name: symbol)"]
    for name, src in SETS:
        rows.append(f"// {name}")
        xs = [f"cpl_runtime_symbol({json.dumps(src)}, {json.dumps(x)})." for x in sorted(lit[name])]
        rows += [" ".join(xs[i:i + 2]) for i in range(0, len(xs), 2)]
    return "\n".join(rows) + "\n"


def main():
    t = text()
    if "--check" in sys.argv:
        if open(OUT).read() != t:
            sys.exit(f"{OUT} differs from {SCRIPT} at {COMMIT[:9]}: rerun without --check")
        print("ok")
    else:
        open(OUT, "w").write(t)


if __name__ == "__main__":
    main()
