"""Generate the keyword tables of RF04 and RF06 from their policy JSON. Run: python3 gen-keywords.py

  sqlfluff-rf04-references-keywords.facts.rr   from packs/sql/rules/sqlfluff-rf04-references-keywords.json
  sqlfluff-rf06-references-quoting.facts.rr    from packs/sql/rules/sqlfluff-rf06-references-quoting.json

Each JSON holds its list as one regex alternation over the identifier's text: RF04's `(?i)^(?:ABORT|…)$`, the
keywords sqlfluff's dialects reserve or list as unreserved, and RF06's `(?i)^"(?:ALL|…)"$`, PostgreSQL's reserved
words, which stay quoted. This script reads each alternation back into one row per word.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
RULES = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "packs", "sql", "rules"))
TABLES = {
    "sqlfluff-rf04-references-keywords": ("sql_keyword", r"\(\?i\)\^\(\?:(?P<w>[A-Z0-9_|]+)\)\$",
        "a keyword sqlfluff knows (reserved or unreserved, in the dialects the pack serves)"),
    "sqlfluff-rf06-references-quoting": ("pg_reserved", r"\(\?i\)\^\"\(\?:(?P<w>[A-Z0-9_|]+)\)\"\$",
        "a word PostgreSQL reserves: an identifier spelled so must stay quoted"),
}


def regexes(t):
    if isinstance(t, dict):
        for k, v in t.items():
            if k == "regex" and isinstance(v, str):
                yield v
            yield from regexes(v)
    elif isinstance(t, list):
        for x in t:
            yield from regexes(x)


def words(rule, pat):
    (m,) = [m for m in (re.fullmatch(pat, r) for r in regexes(json.load(open(os.path.join(RULES, rule + ".json"))))) if m]
    return m.group("w").split("|")


def main():
    for rule, (rel, pat, what) in TABLES.items():
        ws = words(rule, pat)
        rows, lines, cur = [f'{rel}("{w}").' for w in ws], [], ""
        for r in rows:
            if cur and len(cur) + 1 + len(r) > 116:
                lines.append(cur); cur = r
            else:
                cur = f"{cur} {r}" if cur else r
        head = (f"// {rule}.facts.rr: {len(ws)} words, upper case, in the JSON's order.\n"
                f"// GENERATED by packs/sql/gen-keywords.py from packs/sql/rules/{rule}.json. Do not edit; rerun the\n"
                f"// script. check-keywords.py rebuilds the JSON's regex from these rows.\n//\n"
                f"// {rel}(w)   {what}\n.decl {rel}(w: symbol)\n")
        out = os.path.join(HERE, rule + ".facts.rr")
        open(out, "w").write(head + "\n".join(lines + [cur]) + "\n")
        print(f"wrote {out}: {len(ws)} words")


if __name__ == "__main__":
    main()
