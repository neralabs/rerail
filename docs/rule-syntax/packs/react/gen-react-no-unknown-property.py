"""Write react-no-unknown-property.props.rr: the name tables of react/no-unknown-property, read from the JSON.

The JSON spells eslint-plugin-react's tables as regex alternations; this reads them back into facts:
  dom_property(x)        a DOM property name React knows, in its exact case (getDOMPropertyNames, React 19)
  dom_attribute(x, std)  an HTML or SVG attribute name and the property React wants instead: class -> className
  only_on(x, tag)        a property React supports only on some tags (ATTRIBUTE_TAGS_MAP); only_on_says gives the list
  any_case(x)            a property matched in any letter case (DOM_PROPERTIES_IGNORE_CASE)
  aria_property(x)       an aria-* attribute (ARIA_PROPERTIES)
Run from anywhere: python3 gen-react-no-unknown-property.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "..", "..", "packs", "react", "rules", "react-no-unknown-property.json")


def names(regex):
    """The alternatives of ^(?:a|b)$, ^(?i:a|b)$ or several such joined by |, with their case mode."""
    out = []
    for flag, body in re.findall(r"\^\(\?(i?):([^()]*)\)\$", regex):
        out += [(x, flag == "i") for x in body.split("|")]
    return out


def tables():
    d = json.load(open(JSON))
    c = {x["id"]: x for x in d["clauses"]}
    rule = lambda k: c[k]["forbid"]["ast"]["rule"]
    t = {"only_on": [], "only_on_says": [], "dom_attribute": [], "dom_property": [], "any_case": [], "aria": []}
    for k in c:
        if k.startswith("wrong-element-"):
            r = rule(k)
            says = re.sub(r"^Remove \$N from this <\$T>; React supports it only on ", "", c[k]["violation"]["message"])
            for x, _ in names(r["has"]["regex"]):
                t["only_on_says"].append((x, says.rstrip(".")))
                t["only_on"] += [(x, tag) for tag, _ in names(r["inside"]["not"]["has"]["regex"])]
    # html-or-svg-name: the JSON's transform gives the standard name (":" and "-" separate words, camelCase,
    # then four React spellings).
    special = {"class": "className", "for": "htmlFor", "crossorigin": "crossOrigin", "nomodule": "noModule"}
    for x, _ in names(rule("html-or-svg-name")["has"]["regex"]):
        w = x.replace(":", "-").split("-")
        camel = w[0] + "".join(p[:1].upper() + p[1:] for p in w[1:])
        t["dom_attribute"].append((x, special.get(camel, camel)))
    for part in rule("unknown")["all"]:
        alts = names(part["not"]["has"]["regex"])
        if all(i for _, i in alts) and len(alts) < 20:      # the lower-cased list of every property is not one
            t["any_case"] += [x for x, _ in alts]
        elif len(alts) > 300 and not any(i for _, i in alts):     # the exact-case list
            t["dom_property"] = [x for x, _ in alts]
    shared = c["shared"]["define"]["utils"]["dom-attribute"]["all"][1]["not"]["has"]["regex"]
    t["aria"] = [x for x, _ in names(shared)]
    return t


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(t):
    lines = ["// Generated by gen-react-no-unknown-property.py from packs/react/rules/react-no-unknown-property.json.",
             "// Do not edit; check-react-no-unknown-property.py checks that it round-trips.",
             ".decl dom_property(x: symbol)", ".decl dom_attribute(x: symbol, std: symbol)",
             ".decl only_on(x: symbol, tag: symbol)", ".decl only_on_says(x: symbol, tags: symbol)",
             ".decl any_case(x: symbol)", ".decl aria_property(x: symbol)"]
    def rows(fmt, items, per=4):
        items = [fmt(i) for i in items]
        for i in range(0, len(items), per):
            lines.append(" ".join(items[i:i + per]))
    rows(lambda x: f"dom_property({q(x)}).", t["dom_property"], 5)
    rows(lambda p: f"dom_attribute({q(p[0])}, {q(p[1])}).", t["dom_attribute"], 3)
    rows(lambda p: f"only_on({q(p[0])}, {q(p[1])}).", t["only_on"], 4)
    rows(lambda p: f"only_on_says({q(p[0])}, {q(p[1])}).", t["only_on_says"], 1)
    rows(lambda x: f"any_case({q(x)}).", t["any_case"], 4)
    rows(lambda x: f"aria_property({q(x)}).", t["aria"], 4)
    open(os.path.join(HERE, "react-no-unknown-property.props.rr"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    write(tables())
