"""Writes ruff-up035-deprecated-import.moves.rr, UP035's table, from the rule's JSON.
    python3 docs/rule-syntax/packs/python/gen-ruff-up035-deprecated-import.py
Each JSON clause names a module, a util listing the names it reports, a pythonVersion range and a message. A name
listed by several clauses of one module belongs to the first (the lowest version); the JSON's `not up-to-…`
conditions say the same. The check (check-ruff-up035-deprecated-import.py) rebuilds the clauses from the table."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "..", "..", "packs", "python", "rules", "ruff-up035-deprecated-import.json")
OUT = os.path.join(HERE, "ruff-up035-deprecated-import.moves.rr")


def minor(v):
    return int(v.split(".")[1])


def clauses(d):
    """(id, module, names, lo, hi, message) per reporting clause, read from the JSON."""
    utils = d["clauses"][0]["define"]["utils"]
    out = []
    for c in d["clauses"][1:]:
        ast = c["forbid"]["ast"]
        rule = ast["rule"]
        mod = re.fullmatch(r"\^(.*)\$", rule["has"]["regex"]).group(1).replace("\\s*\\.\\s*", ".")
        spec = rule["all"][0]
        if "matches" in spec:
            util = json.dumps(utils[spec["matches"]])
        else:
            util = json.dumps(spec)
        names = re.search(r"\^\(\?:([^)]*)\)\$", util).group(1).split("|")
        v = ast.get("when", {}).get("pythonVersion", {})
        lo = minor(v["min"]) if "min" in v else 0
        hi = minor(v["max"]) if "max" in v else 99
        out.append((c["id"], mod, names, lo, hi, c["violation"]["message"]))
    return out


def main():
    d = json.load(open(JSON))
    rows, says, seen = [], [], set()
    for cid, mod, names, lo, hi, msg in clauses(d):
        says.append(f"move_says({json.dumps(cid)}, {lo}, {hi}, {json.dumps(msg)}).")
        for x in names:
            if (mod, x, lo, hi) in seen or any(s[0] == mod and s[1] == x and s[3] == hi and s[2] < lo for s in seen):
                continue
            seen.add((mod, x, lo, hi))
            rows.append(f"moved({json.dumps(mod)}, {json.dumps(x)}, {json.dumps(cid)}).")
    with open(OUT, "w") as f:
        f.write("// Generated by gen-ruff-up035-deprecated-import.py from ruff-up035-deprecated-import.json. Do not edit.\n")
        f.write("// moved(m, x, clause): `from m import x` is reported under the clause, from the first version that has x\n")
        f.write("// elsewhere. move_says(clause, lo, hi, msg): the clause reports for targets 3.lo to 3.hi, with msg.\n")
        f.write(".decl moved(m: symbol, x: symbol, clause: symbol)\n")
        f.write(".decl move_says(clause: symbol, lo: number, hi: number, msg: symbol)\n")
        f.write("\n".join(rows + says) + "\n")


if __name__ == "__main__":
    main()
