"""Writes ruff-air301-airflow3-removal.names.rr: the Airflow names that Airflow 3 removed or moved (AIR301), from the
JSON's name clauses (those with an `old-name` util): each old name, whether it covers everything under it, the new
module and name its guard looks for, and its message with `$N` (the old name) and `$L` (its last part) filled in.
    python3 docs/rule-syntax/packs/python/gen-ruff-air301-airflow3-removal.py
"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "..", "..", "packs", "python", "rules", "ruff-air301-airflow3-removal.json")
OUT = os.path.join(HERE, "ruff-air301-airflow3-removal.names.rr")
NEW = re.compile(r"(?:replace it with `([^`]+)`, imported from|import `([^`]+)` from) `([^`]+)`")


def clauses(policy):
    return [c for c in policy["clauses"] if "old-name" in c.get("forbid", {}).get("ast", {}).get("utils", {})]


def rows(policy):
    out = []
    for c in clauses(policy):
        ut = c["forbid"]["ast"]["utils"]; res = ut["old-name"]["resolves"]; msg = c["violation"]["message"]
        m = x = ""
        if "guarded" in ut:
            g = NEW.search(msg); x, m = g.group(1) or g.group(2), g.group(3)
        for q in res["import"]:
            text = msg.replace("$N", q).replace("$L", q.rsplit(".", 1)[1])
            out.append((q, "prefix" if res.get("prefix") else "exact", m, x, text))
    return out


def render(rs):
    out = ["// Generated by gen-ruff-air301-airflow3-removal.py from the JSON's name clauses. Do not edit.",
           "// air301_name(old, how, module, name, msg): `old` (how \"exact\"), or anything under it (how \"prefix\"), was",
           "// removed in Airflow 3, with message msg; when module is not \"\", `name` in `module` replaces it, and a",
           "// fallback for that is guarded.",
           ".decl air301_name(old: symbol, how: symbol, module: symbol, name: symbol, msg: symbol)"]
    out += ["air301_name(%s)." % ", ".join(json.dumps(v) for v in r) for r in rs]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(OUT, "w").write(render(rows(json.load(open(JSON)))))
