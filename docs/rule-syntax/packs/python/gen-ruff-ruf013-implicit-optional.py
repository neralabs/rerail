"""Writes ruff-ruf013-implicit-optional.stdlib.rr: the standard-library modules Ruff's RUF013 treats as known types
(is_known_type: typing_extensions, and is_known_standard_library for the target version), from Ruff's own table
(known_stdlib.rs). The JSON's `known-name` list is that table at Python 3.10; check-…py compares them.
    python3 docs/rule-syntax/packs/python/gen-ruff-ruf013-implicit-optional.py
"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "..", "..", "packs", "python", "rules", "ruff-ruf013-implicit-optional.json")
RS = ("/Users/jeremy/orca/workspaces/rerail/wolfeel/.rerail/port-readiness/upstream/ruff/"
      "0be08a206f9c3180afd3e93bcc792ed5cb1f4db1/crates/ruff_python_stdlib/src/sys/known_stdlib.rs")
OUT = os.path.join(HERE, "ruff-ruf013-implicit-optional.stdlib.rr")
MINORS = range(7, 16)  # the minor versions known_stdlib.rs lists


def modules(policy):
    """The JSON's list: Ruff's table at 3.10, typing_extensions first."""
    utils = policy["clauses"][0]["define"]["utils"]
    for alt in utils["known-name"]["any"]:
        imp = alt.get("resolves", {}).get("import")
        if imp:
            return imp
    raise SystemExit("no known-name import list in the JSON")


def table(src):
    """known_stdlib.rs as {"_": [...], "7": [...], …}: each arm of its `matches!`, in order."""
    arms = re.findall(r'\(\s*(_|\d+),\s*((?:\|?\s*"[^"]+"\s*)+)\)', src)
    return {v: re.findall(r'"([^"]+)"', mods) for v, mods in arms}


def split(t):
    """Modules known at every listed version, and (module, minor) for the rest."""
    every = ["typing_extensions"] + t["_"]
    every += sorted(m for m in set().union(*(t[str(v)] for v in MINORS)) if all(m in t[str(v)] for v in MINORS))
    some = [(m, v) for v in MINORS for m in t[str(v)] if m not in every]
    return every, some


def facts(items, out):
    line = ""
    for fact in items:
        if len(line) + len(fact) + 1 > 118:
            out.append(line.rstrip())
            line = ""
        line += fact + " "
    out.append(line.rstrip())


def render(every, some):
    out = ["// Generated by gen-ruff-ruf013-implicit-optional.py from Ruff's known_stdlib.rs. Do not edit.",
           "// stdlib_module(m): a top-level module whose names RUF013 treats as known types at every Python version.",
           ".decl stdlib_module(m: symbol)"]
    facts([f'stdlib_module("{m}").' for m in every], out)
    out += ["// stdlib_module_in(m, minor): a module known only when the code targets Python 3.minor.",
            ".decl stdlib_module_in(m: symbol, minor: number)"]
    facts([f'stdlib_module_in("{m}", {v}).' for m, v in some], out)
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(OUT, "w").write(render(*split(table(open(RS).read()))))
