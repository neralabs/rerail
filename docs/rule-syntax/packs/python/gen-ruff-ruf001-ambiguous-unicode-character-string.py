"""Writes ruff-ruf001-ambiguous-unicode-character-string.confusables.rr: Ruff's look-alike characters (those with
an ASCII representant), split as the JSON splits them into `symbol` (not alphanumeric) and `any-letter`, and the
word logic RUF001, RUF002 and RUF003 share.
    python3 docs/rule-syntax/packs/python/gen-ruff-ruf001-ambiguous-unicode-character-string.py
"""
import json, os, re, unicodedata
HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "..", "..", "packs", "python", "rules",
                    "ruff-ruf001-ambiguous-unicode-character-string.json")
OUT = os.path.join(HERE, "ruff-ruf001-ambiguous-unicode-character-string.confusables.rr")


def parse_class(rx):
    """The code points of the one bracketed class in rx (literal characters, a-b ranges, \\x{h} escapes)."""
    body = rx[rx.index("[") + 1:rx.rindex("]")]
    toks = re.findall(r"\\x\{([0-9a-fA-F]+)\}|(-)|(.)", body, re.S)
    cps, i = [], 0
    vals = [int(h, 16) if h else ("-" if d else ord(c)) for h, d, c in toks]
    while i < len(vals):
        if i + 2 < len(vals) and vals[i + 1] == "-":
            cps.extend(range(vals[i], vals[i + 2] + 1)); i += 3
        else:
            cps.append(vals[i]); i += 1
    return sorted(set(cps))


def classes(policy):
    u = policy["clauses"][0]["define"]["utils"]
    return parse_class(u["symbol"]["regex"]), parse_class(u["any-letter"]["regex"])


def char(cp):
    """A class member as the .rr regex string writes it: printable characters as themselves, others escaped."""
    cat = unicodedata.category(chr(cp))
    return f"\\\\x{{{cp:x}}}" if cat[0] in "ZCM" else chr(cp)


def runs(cps):
    """cps as class members: single characters, pairs, and a-b ranges for longer runs."""
    out, i = [], 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1: j += 1
        out.append(char(cps[i]) if j == i else (char(cps[i]) + char(cps[j]) if j == i + 1 else
                                                char(cps[i]) + "-" + char(cps[j])))
        i = j + 1
    return out


def packed(cps, width=72):
    """The class body cut into pieces of about width characters, never inside a range."""
    lines, cur = [], ""
    for r in runs(cps):
        if len(cur) + len(r) > width: lines.append(cur); cur = ""
        cur += r
    return lines + [cur]


def render(sym, let):
    head = f'''// Generated by gen-ruff-ruf001-ambiguous-unicode-character-string.py from the JSON's character classes. Do not
// edit; regenerate. Shared by RUF001 (strings), RUF002 (docstrings) and RUF003 (comments).
//
// confusable_text(t): the rule lists the text pieces it checks: string contents, docstring contents, comments.
// confusable_char(t, ch): ch is a look-alike in t that Ruff reports. Ruff splits the text into words, runs of
// alphanumeric characters (Unicode Alphabetic or Number):
//   - a look-alike that is not alphanumeric (`）`, an en quad) is always reported;
//   - a look-alike letter (`α`, `Р`) is reported when its word has an ASCII letter or digit, or has no other
//     non-ASCII letter: in "Bαd" and "Р" yes; in "Русский" no, `й` says the word is Russian.
// Only look-alikes whose representant is ASCII count: {len(sym)} symbols and {len(let)} letters. One match_all
// per piece of a class: each matches one character, so the pieces add up to the whole class.
.decl confusable_text(t: loc)
.decl confusable_char(t: loc, ch: span)
confusable_char(t, ch) :- confusable_word(t, w), confusable_word_counts(w), confusable_letter(w, ch).
// confusable_word(t, w): a word of t with a non-ASCII character.
.decl confusable_word(t: loc, w: span)
confusable_word(t, w) :- confusable_text(t), match_all("(?<w>[\\\\p{{Alphabetic}}\\\\p{{N}}]+)", t),
    match("[\\\\s\\\\S]*[^\\\\x00-\\\\x7f][\\\\s\\\\S]*", w).
// confusable_word_counts(w): w has an ASCII letter or digit, or every non-ASCII character in it is a look-alike.
.decl confusable_word_counts(w: span)
confusable_word_counts(w) :- confusable_word(_, w), match("[\\\\s\\\\S]*[0-9A-Za-z][\\\\s\\\\S]*", w).
confusable_word_counts(w) :- confusable_word(_, w), n = count : {{ match_all("(?<c>[^\\\\x00-\\\\x7f])", w) }},
    n = count : {{ confusable_letter(w, _) }}.
.decl confusable_letter(w: span, ch: span)
'''
    out = [head.rstrip("\n"), "// The symbols: look-alikes that are not alphanumeric."]
    out += [f'confusable_char(t, ch) :- confusable_text(t), match_all("(?<ch>[{p}])", t).' for p in packed(sym)]
    out.append("// The letters (and digits): look-alikes that are alphanumeric.")
    out += [f'confusable_letter(w, ch) :- confusable_word(_, w), match_all("(?<ch>[{p}])", w).' for p in packed(let)]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(OUT, "w").write(render(*classes(json.load(open(JSON)))))
