"""Writes ruff-npy201-numpy2-deprecation.members.rr: the NumPy members NumPy 2.0 removes (NPY201), each with its
advice group and, where Ruff knows one, the replacement member a compatibility fallback may read, from the JSON's
clauses (one per group).
    python3 docs/rule-syntax/packs/python/gen-ruff-npy201-numpy2-deprecation.py
"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "..", "..", "packs", "python", "rules", "ruff-npy201-numpy2-deprecation.json")
OUT = os.path.join(HERE, "ruff-npy201-numpy2-deprecation.members.rr")
SKIP = ("shared", "string-annotation-or-pattern")


def groups(policy):
    """[(clause id, [old qualified names], replacement or "", message)]. A clause with a fallback exemption
    (`not: fallback`) names its replacement as the message's first `…`."""
    out = []
    for c in policy["clauses"]:
        if c["id"] in SKIP:
            continue
        rule, msg = c["forbid"]["ast"]["rule"], c["violation"]["message"]
        new = re.match(r"Use `([\w.]+)`", msg).group(1) if "not" in rule else ""
        out.append((c["id"], rule["resolves"]["import"], new, msg))
    return out


def render(gs):
    out = ["// Generated by gen-ruff-npy201-numpy2-deprecation.py from the JSON's clauses. Do not edit.",
           "// npy201_member(q, g): NumPy 2.0 removes q; g is its advice group.",
           "// npy201_advice(g, m): group g's message; `$NAME` is the reference as written.",
           "// npy_replacement(q, new) (python/misc2-numpy): q's replacement, which exempts compatibility fallbacks.",
           ".decl npy201_member(q: symbol, g: symbol)", ".decl npy201_advice(g: symbol, m: symbol)"]
    for g, qs, new, m in gs:
        out.append(f"npy201_advice({json.dumps(g)}, {json.dumps(m)}).")
        for q in qs:
            out.append(f'npy201_member("{q}", "{g}").' + (f' npy_replacement("{q}", "{new}").' if new else ""))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(OUT, "w").write(render(groups(json.load(open(JSON)))))
