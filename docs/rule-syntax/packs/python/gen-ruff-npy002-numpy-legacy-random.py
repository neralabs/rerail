"""Writes ruff-npy002-numpy-legacy-random.methods.rr: the legacy numpy.random functions NPY002 reports, grouped by
the advice each group gets, from the JSON's clauses (one clause per group).
    python3 docs/rule-syntax/packs/python/gen-ruff-npy002-numpy-legacy-random.py
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "..", "..", "packs", "python", "rules", "ruff-npy002-numpy-legacy-random.json")
OUT = os.path.join(HERE, "ruff-npy002-numpy-legacy-random.methods.rr")
SKIP = ("shared", "string-annotation")


def groups(policy):
    """[(clause id, [qualified names], message)] in the JSON's order."""
    return [(c["id"], c["forbid"]["ast"]["rule"]["resolves"]["import"], c["violation"]["message"])
            for c in policy["clauses"] if c["id"] not in SKIP]


def render(gs):
    out = ["// Generated by gen-ruff-npy002-numpy-legacy-random.py from the JSON's clauses. Do not edit.",
           "// npy002_method(q, g): q is a legacy numpy.random function of advice group g.",
           "// npy002_advice(g, m): group g's message; `$NAME` is the reference as written.",
           ".decl npy002_method(q: symbol, g: symbol)", ".decl npy002_advice(g: symbol, m: symbol)"]
    for g, qs, m in gs:
        out.append(f"npy002_advice({json.dumps(g)}, {json.dumps(m)}).")
        out += [f'npy002_method("{q}", "{g}").' for q in qs]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(OUT, "w").write(render(groups(json.load(open(JSON)))))
