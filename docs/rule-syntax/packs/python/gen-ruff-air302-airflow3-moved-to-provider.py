"""Writes ruff-air302-airflow3-moved-to-provider.moved.rr: the Airflow names that moved into provider packages in
Airflow 3 (AIR302), from each clause's `old` import list and its message.
    python3 docs/rule-syntax/packs/python/gen-ruff-air302-airflow3-moved-to-provider.py
"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "..", "..", "packs", "python", "rules", "ruff-air302-airflow3-moved-to-provider.json")
OUT = os.path.join(HERE, "ruff-air302-airflow3-moved-to-provider.moved.rr")
MSG = re.compile(r"Install `apache-airflow-providers-([\w.-]+)>=([\w.]+)` and import `([^`]+)` from `([^`]+)` instead\.")


def rows(policy):
    out = []
    for c in policy["clauses"]:
        if "forbid" not in c:
            continue
        p, v, name, module = MSG.fullmatch(c["violation"]["message"]).groups()
        for old in c["forbid"]["ast"]["utils"]["old"]["resolves"]["import"]:
            out.append((old, p, v, module, old.rsplit(".", 1)[1] if name == "$ORIG" else name))
    return out


def render(rs):
    out = ["// Generated by gen-ruff-air302-airflow3-moved-to-provider.py from the JSON's clauses. Do not edit.",
           "// air302_moved(old, provider, version, module, name): `old` is now `name` in `module`, which",
           "// apache-airflow-providers-<provider> >= version provides.",
           ".decl air302_moved(old: symbol, provider: symbol, version: symbol, module: symbol, name: symbol)"]
    out += ['air302_moved("%s", "%s", "%s", "%s", "%s").' % r for r in rs]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(OUT, "w").write(render(rows(json.load(open(JSON)))))
