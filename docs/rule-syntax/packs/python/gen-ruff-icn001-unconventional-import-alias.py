"""Writes ruff-icn001-unconventional-import-alias.aliases.rr: Ruff's default import conventions (ICN001), from the
JSON's chain of `replace` transforms (module regex -> alias).
    python3 docs/rule-syntax/packs/python/gen-ruff-icn001-unconventional-import-alias.py
"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "..", "..", "packs", "python", "rules", "ruff-icn001-unconventional-import-alias.json")
OUT = os.path.join(HERE, "ruff-icn001-unconventional-import-alias.aliases.rr")
DOT = r"[\s\\]*\.[\s\\]*"


def aliases(policy):
    tr = policy["clauses"][0]["forbid"]["ast"]["transform"]
    keys = sorted((k for k in tr if k != "E"), key=lambda k: int(k[1:])) + ["E"]
    out = []
    for k in keys:
        r = tr[k]["replace"]
        m = re.fullmatch(r"\^(.*)\$", r["replace"]).group(1)
        out.append((m.replace(DOT, "."), r["by"]))
    return out


def render(pairs):
    out = ["// Generated by gen-ruff-icn001-unconventional-import-alias.py from the JSON's transforms. Do not edit.",
           "// icn_alias(m, a): Ruff's default convention is `import m as a` (flake8-import-conventions' defaults).",
           ".decl icn_alias(m: symbol, a: symbol)"]
    out += [f'icn_alias("{m}", "{a}").' for m, a in pairs]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(OUT, "w").write(render(aliases(json.load(open(JSON)))))
