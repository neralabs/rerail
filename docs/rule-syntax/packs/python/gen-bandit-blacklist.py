#!/usr/bin/env python3
"""Generate lib/python/security-blacklist.rr, Bandit 1.9.4's blacklists (B3xx calls, B4xx imports), from the
pack's rerail.policy/v1 rules (packs/python/rules/bandit-*.json at the repository root).

Each call rule's JSON lists its qualified names under `resolves.import`; each import rule's JSON lists its modules as
`import M` patterns. Three entries come from Bandit alone (see EXTRA): eval, which the JSON spells as a regex, and the
import lists B403, B404 and B412, which have no rule in the pack but still take precedence over later lists (Bandit
reports one blacklisted import per statement, from the first list that matches).

    python3 packs/python/gen-bandit-blacklist.py          # writes the table
    python3 packs/python/gen-bandit-blacklist.py --stdout
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
RR = HERE.parent.parent
REPO = RR.parent.parent
RULES = REPO / "packs" / "python" / "rules"
OUT = RR / "lib" / "python" / "security-blacklist.rr"

CALLS = ["B301", "B302", "B303", "B304", "B305", "B306", "B307", "B308", "B310", "B311", "B312", "B313", "B314",
         "B315", "B316", "B317", "B318", "B319", "B321", "B323"]
# Bandit's order of the import lists (bandit/blacklists/imports.py); the rank is the index.
IMPORTS = ["B401", "B402", "B403", "B404", "B405", "B406", "B407", "B408", "B409", "B411", "B412", "B413", "B415"]
EXTRA = {
    "B307": ["eval"],                                            # the JSON: an identifier matching ^eval$
    "B403": ["pickle", "cPickle", "dill", "shelve"],
    "B404": ["subprocess"],
    "B412": ["wsgiref.handlers.CGIHandler", "twisted.web.twcgi.CGIScript", "twisted.web.twcgi.CGIDirectory"],
}


def rule_file(code):
    found = sorted(RULES.glob(f"bandit-{code.lower()}-*.json"))
    return found[0] if found else None


def walk(x):
    if isinstance(x, dict):
        yield x
        for v in x.values():
            yield from walk(v)
    elif isinstance(x, list):
        for v in x:
            yield from walk(v)


def call_names(doc):
    """The qualified names a call rule's JSON lists, in order."""
    out = []
    for d in walk(doc["clauses"]):
        r = d.get("resolves")
        if isinstance(r, dict) and isinstance(r.get("import"), list):
            out += [q for q in r["import"] if q not in out]
    return out


def import_modules(doc):
    """The modules of an import rule's `import M` patterns, in order (the `not` alternatives are left out)."""
    out = []
    for c in doc["clauses"]:
        for alt in c["forbid"]["ast"]["rule"].get("any", []):
            m = re.fullmatch(r"import ([\w.]+)", alt.get("pattern", ""))
            if m and m.group(1) not in out:
                out.append(m.group(1))
    return out


def table():
    calls, imports = {}, {}
    for code in CALLS:
        f = rule_file(code)
        calls[code] = EXTRA.get(code) or call_names(json.load(open(f)))
    for code in IMPORTS:
        f = rule_file(code)
        imports[code] = EXTRA.get(code) or import_modules(json.load(open(f)))
    return calls, imports


def render(calls, imports):
    lines = [
        "// python/security-blacklist: Bandit 1.9.4's blacklists, the data of its B001 test.",
        "// GENERATED by packs/python/gen-bandit-blacklist.py from packs/python/rules/bandit-*.json (and Bandit's",
        "// bandit/blacklists/*.py for eval, B403, B404 and B412). Do not edit; rerun the script.",
        "// packs/python/check-bandit-blacklist.py checks it against the JSON, and against Bandit with --bandit DIR.",
        "//",
        "// blacklist_call(code, q)          a call whose qualified name (python/security's qual_call) is q: code.",
        "// blacklist_import(code, rank, m)  an import of a name that starts with m: code. Bandit reports one per",
        "//                                  statement, from the lowest rank that matches (its order of the lists).",
        ".decl blacklist_call(code: symbol, q: symbol)",
        ".decl blacklist_import(code: symbol, rank: number, m: symbol)",
    ]
    for code, qs in calls.items():
        lines += [f'blacklist_call("{code}", "{q}").' for q in qs]
    for rank, (code, ms) in enumerate(imports.items()):
        lines += [f'blacklist_import("{code}", {rank}, "{m}").' for m in ms]
    return "\n".join(lines) + "\n"


def main():
    text = render(*table())
    if "--stdout" in sys.argv:
        sys.stdout.write(text)
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(RR)}: {text.count(chr(10))} lines")


if __name__ == "__main__":
    main()
