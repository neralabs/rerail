"""Generate n-no-deprecated-api.facts.rr and n-no-unsupported-features-es-builtins.facts.rr from eslint-plugin-n's
own trace maps for n/no-deprecated-api and n/no-unsupported-features/es-builtins.
Run: python3 gen-node-tables.py --plugin DIR --globals FILE
  DIR: eslint-plugin-n 18.4.1 unpacked (`npm pack eslint-plugin-n@18.4.1`); FILE: the npm globals package's
  globals.json, whose "node" and "builtin" sets are the globals the policies declare.

no-deprecated-api: the map is two object literals in DIR/lib/rules/no-deprecated-api.js, `rawModules` and `globals`: a trie of
property names whose [READ], [CALL] and [CONSTRUCT] leaves say since when that use is deprecated, what replaces it
and when it was removed. This script reads the literals (plain JSON once the keys are quoted) and writes one row
per leaf, named as lib/tsx/values.rr names APIs: a module "domain", its member "fs#exists", a global "Buffer" or
"process.binding". The global `process` is the module's trie (`process: modules.process`).
ReferenceTracker follows a global only where the scope declares it, so node_global lists only the map's globals that
globals.json declares (Buffer, Intl, process, require); GLOBAL, root and the COUNTER_* names are reached through
globalThis alone.

es-builtins: the map is `traceMap.globals` in DIR/lib/rules/no-unsupported-features/es-builtins.js, every leaf a
[READ] with one supported release (no backports, nothing experimental, no modules); one es_since row per leaf.
"""
import argparse, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "n-no-deprecated-api.facts.rr")
ES_OUT = os.path.join(HERE, "n-no-unsupported-features-es-builtins.facts.rr")
HOW = {"READ": "read", "CALL": "call", "CONSTRUCT": "new"}


def literal(src, name):
    """The object literal `name = {...}` (`const name = {` or a `name: {` key) of src, as Python data."""
    m = re.search(r"(?:const %s = |\b%s: )\{" % (name, name), src)
    i = m.end() - 1
    depth, j = 0, i
    for j in range(i, len(src)):
        depth += {"{": 1, "}": -1}.get(src[j], 0) if src[j] in "{}" else 0
        if depth == 0:
            break
    body = src[i:j + 1]
    body = re.sub(r"^\s*//.*$", "", body, flags=re.M)
    body = re.sub(r"\[(READ|CALL|CONSTRUCT)\]:", r'"@\1":', body)
    body = re.sub(r"process: modules\.process", '"process": "@process"', body)
    body = re.sub(r'(?m)^(\s*)([A-Za-z_$][\w$]*):', r'\1"\2":', body)
    body = re.sub(r'([{,]\s*)([A-Za-z_$][\w$]*):', r'\1"\2":', body)
    body = re.sub(r",(\s*[}\]])", r"\1", body)
    return json.loads(body)


def leaves(trie, path):
    for k, v in trie.items():
        if k.startswith("@"):
            yield path, HOW[k[1:]], v
        else:
            yield from leaves(v, path + [k])


def q(t):
    return '"%s"' % t.replace("\\", "\\\\").replace('"', '\\"')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plugin", required=True)
    ap.add_argument("--globals", required=True)
    a = ap.parse_args()
    gj = json.load(open(a.globals))
    declared = set(gj["node"]) | set(gj["builtin"])
    src = open(os.path.join(a.plugin, "lib", "rules", "no-deprecated-api.js")).read()
    modules, glob = literal(src, "rawModules"), literal(src, "globals")
    glob["process"] = modules["process"]
    rows, apis = [], 0
    member, gpath, gtop, mods = set(), set(), set(), set()
    for space, trie in (("module", modules), ("global", glob)):
        for path, how, info in leaves(trie, []):
            if space == "module":
                mods.add(path[0])
                api = path[0] if len(path) == 1 else path[0] + "#" + ".".join(path[1:])
                if len(path) > 1:
                    member.add((path[0], ".".join(path[1:])))
                if len(path) == 1:
                    how = "load"
            else:
                api = ".".join(path)
                gtop.add(path[0])
                for n in range(2, len(path) + 1):
                    gpath.add(".".join(path[:n]))
            apis += 1
            rows.append("dep(%s, %s, %s, %s)." % (q(api), q(how), q(info["since"]), q(info.get("removed") or "")))
            rb = info.get("replacedBy")
            if isinstance(rb, str):
                rows.append("dep_hint(%s, %s, %s)." % (q(api), q(how), q(rb)))
            elif isinstance(rb, list):
                for i, alt in enumerate(rb):
                    rows.append("dep_alt(%s, %s, %d, %s, %s)." % (q(api), q(how), i, q(alt["name"]), q(alt["supported"])))
    out = ["// n-no-deprecated-api.facts.rr: the Node.js APIs eslint-plugin-n reports as deprecated.",
           "// GENERATED by packs/node/gen-node-tables.py from eslint-plugin-n 18.4.1's trace map",
           "// (lib/rules/no-deprecated-api.js). Do not edit; rerun the script. %d entries." % apis,
           "//",
           "// dep(api, how, since, removed)     api, used as how, is deprecated since Node.js `since`; removed \"\" or the",
           "//                                   release that removed it. how: \"load\" (the module itself), \"read\", \"call\", \"new\".",
           "// dep_hint(api, how, text)          what to use instead, as the plugin words it",
           "// dep_alt(api, how, i, name, v)     replacement i, to suggest where every configured release is >= v",
           "// API names as lib/tsx/values.rr spells them: \"domain\", \"fs#exists\", \"Buffer\", \"process.binding\".",
           "// trace_module, trace_member (tsx/node-trace.rr) and node_global, api_known (tsx/values.rr) rows trace them.",
           ".decl dep(api: symbol, how: symbol, since: symbol, removed: symbol)",
           ".decl dep_hint(api: symbol, how: symbol, text: symbol)",
           ".decl dep_alt(api: symbol, how: symbol, i: number, name: symbol, v: symbol)",
           ""] + rows + [""]
    out += ["trace_module(%s)." % q(m) for m in sorted(mods)]
    out += ["trace_member(%s, %s)." % (q(m), q(x)) for m, x in sorted(member)]
    out += ["node_global(%s)." % q(g) for g in sorted(gtop & declared)]
    out += ["api_known(%s)." % q(p) for p in sorted(gpath)]
    open(OUT, "w").write("\n".join(out) + "\n")
    print("wrote", OUT, apis, "entries")
    es_builtins(a.plugin, declared)


def es_builtins(plugin, declared):
    src = open(os.path.join(plugin, "lib", "rules", "no-unsupported-features", "es-builtins.js")).read()
    glob = literal(src[src.index("const traceMap"):], "globals")
    rows, top, paths = [], set(), set()
    for path, how, info in leaves(glob, []):
        assert how == "read" and len(info["supported"]) == 1 and set(info) == {"supported"}, (path, info)
        api = ".".join(path)
        rows.append("es_since(%s, %s)." % (q(api), q(info["supported"][0])))
        top.add(path[0])
        for n in range(2, len(path) + 1):
            paths.add(".".join(path[:n]))
    out = ["// n-no-unsupported-features-es-builtins.facts.rr: which Node.js release added each ECMAScript built-in.",
           "// GENERATED by packs/node/gen-node-tables.py from eslint-plugin-n 18.4.1's trace map",
           "// (lib/rules/no-unsupported-features/es-builtins.js). Do not edit; rerun the script. %d entries." % len(rows),
           "//",
           "// es_since(api, v)   global api (\"Array.from\", \"Promise.any\") exists from Node.js v on; every entry is read",
           "//                    and has one release. node_global, api_known (tsx/values.rr) rows trace them.",
           ".decl es_since(api: symbol, v: symbol)",
           ""] + rows + [""]
    out += ["node_global(%s)." % q(g) for g in sorted(top & declared)]
    out += ["api_known(%s)." % q(p) for p in sorted(paths)]
    open(ES_OUT, "w").write("\n".join(out) + "\n")
    print("wrote", ES_OUT, len(rows), "entries;", "undeclared:", sorted(top - declared))


main()
