"""Generate the deprecated-function table of phpcs-generic-php-deprecated-functions from its policy JSON.
Run: python3 gen-deprecated-functions.py

  phpcs-generic-php-deprecated-functions.facts.rr   from packs/php/rules/phpcs-generic-php-deprecated-functions.json

The JSON holds the list as `resolves.import` on the call's function: the functions PHP 8.5 marks deprecated, as the
sniff reads them from the running PHP (ReflectionFunction::isDeprecated). One row per name, in the JSON's order.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
RULE = "phpcs-generic-php-deprecated-functions"
JSON = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "packs", "php", "rules", RULE + ".json"))


def names():
    (cl,) = json.load(open(JSON))["clauses"]
    return cl["forbid"]["ast"]["rule"]["has"]["resolves"]["import"]


def main():
    rows, lines, cur = [f'deprecated_fn("{x}").' for x in names()], [], ""
    for r in rows:
        if cur and len(cur) + 1 + len(r) > 116:
            lines.append(cur); cur = r
        else:
            cur = f"{cur} {r}" if cur else r
    lines.append(cur)
    head = (f"// {RULE}.facts.rr: {len(rows)} functions, lowercase, in the JSON's order.\n"
            f"// GENERATED by packs/php/gen-deprecated-functions.py from packs/php/rules/{RULE}.json.\n"
            f"// Do not edit; rerun the script. check-deprecated-functions.py rebuilds the JSON's list from these rows.\n//\n"
            f"// deprecated_fn(x)   PHP 8.5 marks global function x deprecated\n.decl deprecated_fn(x: symbol)\n")
    open(os.path.join(HERE, RULE + ".facts.rr"), "w").write(head + "\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
