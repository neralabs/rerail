#!/usr/bin/env python3
"""Writes lib/vue/elements.rr: the well-known HTML, SVG and MathML element names and the SVG attributes with
mixed case, as eslint-plugin-vue 10.11.1 lists them, read from the vue pack's JSON policies (attribute-hyphenation's
`custom-tag` util and its `static` clause).

    python3 packs/vue/gen-vue-elements.py          (from docs/rule-syntax)
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
RR = os.path.normpath(os.path.join(HERE, "..", ".."))
REPO = os.path.normpath(os.path.join(RR, "..", ".."))
JSON = os.path.join(REPO, "packs", "vue", "rules", "eslint-plugin-vue-attribute-hyphenation.json")
OUT = os.path.join(RR, "lib", "vue", "elements.rr")


def walk(x):
    if isinstance(x, dict):
        yield x
        for v in x.values():
            yield from walk(v)
    elif isinstance(x, list):
        for v in x:
            yield from walk(v)


def lists():
    """(html, svg, math, weird attributes), each in the JSON's order."""
    d = json.load(open(JSON))
    alts = []
    for node in walk(d["clauses"][0]["define"]["utils"]["custom-tag"]):
        r = node.get("regex") if isinstance(node.get("regex"), str) else None
        m = r and re.fullmatch(r"\^\(\?:(.*)\)\$", r)
        if m and node.get("kind") is None and "|" in m.group(1):
            alts.append(m.group(1).split("|"))
    html, svg, math = alts
    attrs = None
    for node in walk(d["clauses"][1]):
        r = node.get("regex") if isinstance(node.get("regex"), str) else None
        if r and r.startswith("data-|aria-|slot-scope|"):
            attrs = r.split("|")[3:]
    return html, svg, math, attrs


def write(path=OUT):
    html, svg, math, attrs = lists()
    L = ["// vue/elements: generated by packs/vue/gen-vue-elements.py from the vue pack's JSON; do not edit.",
         "// eslint-plugin-vue 10.11.1's lists (lib/utils/html-elements.json, svg-elements.json, math-elements.json,",
         "// svg-attributes-weird-case.json): the element names each namespace knows, compared case-sensitively, and the",
         "// SVG attributes that attribute-hyphenation leaves alone (viewBox, stroke-width, …).",
         "//   vhtml_name(x), vsvg_name(x), vmath_name(x), vsvg_weird_attr(x)"]
    for rel, xs in (("vhtml_name", html), ("vsvg_name", svg), ("vmath_name", math), ("vsvg_weird_attr", attrs)):
        L.append(f".decl {rel}(x: symbol)")
        row = []
        for x in xs:
            row.append(f'{rel}("{x}").')
            if sum(len(r) + 1 for r in row) > 100:
                L.append(" ".join(row)); row = []
        if row:
            L.append(" ".join(row))
    open(path, "w").write("\n".join(L) + "\n")
    return html, svg, math, attrs


if __name__ == "__main__":
    h, s, m, a = write()
    print(f"{os.path.relpath(OUT, RR)}: {len(h)} html, {len(s)} svg, {len(m)} math, {len(a)} attributes")
