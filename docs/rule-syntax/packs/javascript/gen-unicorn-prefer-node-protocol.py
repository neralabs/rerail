"""Writes unicorn-prefer-node-protocol.modules.rr from the policy JSON's list of built-in modules.
    python3 docs/rule-syntax/packs/javascript/gen-unicorn-prefer-node-protocol.py
The JSON holds the list as one regex alternation, ^(?:a|b\\/c|…)$; each name becomes a row bare_builtin(name)."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "../../../../packs/javascript/rules/unicorn-prefer-node-protocol.json")


def names():
    j = json.load(open(JSON))
    rx = next(c for c in j["clauses"] if c["id"] == "import")["forbid"]["ast"]["rule"]["value"]["regex"]
    body = re.fullmatch(r"\^\(\?:(.*)\)\$", rx)[1]
    return sorted(n.replace("\\/", "/") for n in body.split("|"))


if __name__ == "__main__":
    L = ["// Generated by gen-unicorn-prefer-node-protocol.py from packs/javascript/rules/unicorn-prefer-node-protocol.json.",
         "// Do not edit. bare_builtin(m): Node.js built-in module m, written without the node: prefix.",
         ".decl bare_builtin(m: symbol)"]
    line = ""
    for n in names():
        r = f'bare_builtin("{n}"). '
        if len(line) + len(r) > 119:
            L.append(line.rstrip())
            line = ""
        line += r
    L.append(line.rstrip())
    open(os.path.join(HERE, "unicorn-prefer-node-protocol.modules.rr"), "w").write("\n".join(L) + "\n")
