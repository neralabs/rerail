"""Writes eslint-no-irregular-whitespace.chars.rr from the policy JSON's character classes.
    python3 docs/rule-syntax/packs/javascript/gen-eslint-no-irregular-whitespace.py
Each row is one code point: irregular(cp, re, what). re is a regex fragment matching that one character: the
character itself (UTF-8), or \\xhh below 0x80, so the rule can join the rows into an alternation."""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "../../../../packs/javascript/rules/eslint-no-irregular-whitespace.json")


def classes():
    """The in-token clause's regex: a class of whitespace runs, and a class of line terminators."""
    j = json.load(open(JSON))
    rx = next(c for c in j["clauses"] if c["id"] == "in-token")["forbid"]["ast"]["rule"]["regex"]
    return re.findall(r"\[((?:\\x(?:\{[0-9A-Fa-f]+\}|[0-9A-Fa-f]{2})|-)+)\]", rx)


def expand(cls):
    cps = [int(h1 or h2, 16) for h1, h2 in re.findall(r"\\x\{([0-9A-Fa-f]+)\}|\\x([0-9A-Fa-f]{2})", cls)]
    out, i, parts = [], 0, re.findall(r"\\x\{[0-9A-Fa-f]+\}|\\x[0-9A-Fa-f]{2}|-", cls)
    while i < len(parts):
        cp = int(parts[i].strip("\\x{}"), 16)
        if i + 2 < len(parts) and parts[i + 1] == "-":
            out += range(cp, int(parts[i + 2].strip("\\x{}"), 16) + 1)
            i += 3
        else:
            out.append(cp)
            i += 1
    return out


def rows():
    run, line = classes()
    return [(cp, "run") for cp in expand(run)] + [(cp, "line") for cp in expand(line)]


def frag(cp):
    return f"\\\\x{cp:02X}" if cp < 0x80 else chr(cp)


if __name__ == "__main__":
    L = ["// Generated by gen-eslint-no-irregular-whitespace.py from packs/javascript/rules/eslint-no-irregular-whitespace.json.",
         "// Do not edit. irregular(cp, re, what): code point cp, a regex matching it, and \"run\" (whitespace) or",
         "// \"line\" (a line terminator ESLint reports on its own). The characters are invisible: read the code points.",
         ".decl irregular(cp: number, re: symbol, what: symbol)"]
    for cp, what in rows():
        L.append(f'irregular({cp}, "{frag(cp)}", "{what}").  // U+{cp:04X}')
    open(os.path.join(HERE, "eslint-no-irregular-whitespace.chars.rr"), "w", encoding="utf-8").write("\n".join(L) + "\n")
