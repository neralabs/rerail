"""Generate next-no-unwanted-polyfillio.facts.rr from the policy JSON. Run: python3 gen-polyfillio.py

The JSON (packs/next/rules/next-no-unwanted-polyfillio.json) has eslint-plugin-next's two lists inside one regex on
the src value: the Polyfill.io hosts it checks, as an alternation of prefixes, and NEXT_POLYFILLED_FEATURES, as the
alternation after `features=`. This script reads both alternations back into rows.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "packs", "next", "rules",
                                     "next-no-unwanted-polyfillio.json"))
OUT = os.path.join(HERE, "next-no-unwanted-polyfillio.facts.rr")


def src_regex(doc):
    """The regex the JSON tests the src string's value with."""
    def walk(t):
        if isinstance(t, dict):
            v = t.get("value")
            if isinstance(v, dict) and "regex" in v and "features=" in v["regex"]:
                yield v["regex"]
            for x in t.values():
                yield from walk(x)
        elif isinstance(t, list):
            for x in t:
                yield from walk(x)
    (rx,) = set(walk(doc))
    return rx


def split_top(s):
    """'a|(?:b|c)|d' -> ['a', '(?:b|c)', 'd']: split an alternation at depth 0."""
    out, depth, cur = [], 0, ""
    for i, ch in enumerate(s):
        if ch == "(" and (i == 0 or s[i - 1] != "\\"):
            depth += 1
        elif ch == ")" and s[i - 1] != "\\":
            depth -= 1
        if ch == "|" and depth == 0:
            out.append(cur); cur = ""
        else:
            cur += ch
    return out + [cur]


def parse(rx):
    """(hosts, features) from the JSON's regex. `@` is written (?:@|%40), the URL-encoded form beside it."""
    m = re.fullmatch(r"\^\(\?:(?P<hosts>.*?)\)\[\^\?#\]\*\\\?\(\?:\[\^&#\]\*&\)\*features=\(\?:\[\^&#\]\*\?\(\?:,\|%2\[Cc\]\)\)\?"
                     r"\(\?:(?P<feats>.*)\)\(\?:\(\?:,\|%2\[Cc\]\)\|&\|#\|\$\)", rx)
    assert m, rx[:200]
    unesc = lambda p: re.sub(r"\\(.)", r"\1", p.replace("(?:@|%40)", "@"))
    return [unesc(h) for h in split_top(m.group("hosts"))], [unesc(f) for f in split_top(m.group("feats"))]


def main():
    hosts, feats = parse(src_regex(json.load(open(JSON))))
    rows = [f'polyfill_host("{h}").' for h in hosts] + [f'polyfilled("{f}").' for f in feats]
    head = f"""// next-no-unwanted-polyfillio.facts.rr: what eslint-plugin-next's no-unwanted-polyfillio checks for.
// GENERATED by packs/next/gen-polyfillio.py from packs/next/rules/next-no-unwanted-polyfillio.json. Do not edit;
// rerun the script. check-polyfillio.py rebuilds the JSON's regex from these rows. {len(hosts)} hosts, {len(feats)} features.
//
// polyfill_host(p)   a Polyfill.io endpoint: the plugin checks a src that starts with p
// polyfilled(f)      NEXT_POLYFILLED_FEATURES: a polyfill.io feature name Next.js already ships
.decl polyfill_host(p: symbol)
.decl polyfilled(f: symbol)
"""
    lines, cur = [], ""
    for r in rows:
        if cur and len(cur) + 1 + len(r) > 116:
            lines.append(cur); cur = r
        else:
            cur = f"{cur} {r}" if cur else r
    open(OUT, "w").write(head + "\n".join(lines + [cur]) + "\n")
    print(f"wrote {OUT}: {len(hosts)} hosts, {len(feats)} features")


if __name__ == "__main__":
    main()
